def _rgo_bonus_output_values(path: Path) -> dict[str, tuple[str, str]]:
    text = path.read_text(encoding="utf-8-sig")
    values: dict[str, tuple[str, str]] = {}
    pattern = re.compile(r"^(pp_rgo_bonus_([a-z0-9_]+))\s*=\s*\{(?P<body>.*?)^\}", re.DOTALL | re.MULTILINE)
    for match in pattern.finditer(text):
        modifier = match.group(1)
        good = match.group(2)
        value_match = re.search(
            rf"^\s*local_{re.escape(good)}_output_modifier\s*=\s*([-+]?\d+(?:\.\d+)?)\s*$",
            match.group("body"),
            flags=re.MULTILINE,
        )
        if value_match is None:
            raise ValueError(f"{modifier} in {path} is missing local_{good}_output_modifier")
        values[good] = (modifier, value_match.group(1))
    if not values:
        raise ValueError(f"Could not find pp_rgo_bonus_<good> output modifiers in {path}")
    return values


