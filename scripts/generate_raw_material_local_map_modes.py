def _output_modifier_map_color_block(value_name: str, scale: SignedCenteredScale) -> str:
    buckets = signed_centered(scale)
    lines = [
        "\tmap_color = {",
        "\t\tif = {",
        "\t\t\tlimit = { is_ownable = no }",
        "\t\t\tvalue = rgb { 128 128 128 }",
        "\t\t}",
        bucketed_color_cases(value_name, buckets, first_branch="else_if"),
        "\t}",
    ]
    return "\n".join(lines)


def _output_modifier_legend_keys(upper: str) -> str:
    lines = [legend_keys(f"MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER", signed_centered(signed_scale_from_data(None)), OUTPUT_MODIFIER_LEGEND_CLASSES)]
    lines.append(
        f'\tlegend_key = {{ desc = "MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_RAW_MATERIAL" color = {_rgb(RAW_MATERIAL_STRIPE_RGB)} }}'
    )
    return "\n".join(lines)


def _write_script_values(
    path: Path,
    goods: Iterable[str],
    location_potential_values: dict[str, dict[str, list[str]]],
    rgo_bonus_values: dict[str, tuple[str, str]],
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    blocks = [
        "# Generated by scripts/generate_raw_material_local_map_modes.py - do not edit by hand.",
        "# Static planning values for the raw-material output map modes.",
        "# Total map value = generated location potential + active raw-material RGO bonus.",
        "# Map-label values multiply the total by 100 and floor it so map text is an integer.",
        "",
    ]
    for good in goods:
        blocks.extend(
            _script_value_block(
                good,
                location_potential_values.get(good, {}),
                rgo_bonus_values[good],
            )
        )
        blocks.append("")
    _write_crlf(path, "\n".join(blocks).rstrip() + "\n")


def _script_value_block(
    good: str,
    location_potential_values: dict[str, list[str]],
    rgo_bonus_value: tuple[str, str],
) -> list[str]:
    lines = [
        f"{_productivity_value_name(good)} = {{",
        f"\tvalue = {_productivity_location_potential_value_name(good)}",
        f"\tadd = {_productivity_rgo_bonus_value_name(good)}",
        "}",
        "",
        f"{_productivity_map_label_value_name(good)} = {{",
        f"\tvalue = {_productivity_value_name(good)}",
        "\tmultiply = 100",
        "\tfloor = yes",
        "}",
        "",
        f"{_productivity_location_potential_value_name(good)} = {{",
        "\tvalue = 0",
    ]
    for value, modifiers in sorted(location_potential_values.items(), key=_numeric_group_sort_key):
        lines.extend(_modifier_value_branch(value, modifiers))
    lines.extend(
        [
            "}",
            "",
            f"{_productivity_rgo_bonus_value_name(good)} = {{",
            "\tvalue = 0",
        ]
    )
    modifier, value = rgo_bonus_value
    lines.extend(_modifier_value_branch(value, [modifier]))
    lines.append("}")
    return lines


def _rgo_bonus_output_values(path: Path) -> dict[str, tuple[str, str]]:
    text = path.read_text(encoding="utf-8-sig")
    values: dict[str, tuple[str, str]] = {}
    pattern = re.compile(r"^(pp_rgo_bonus_([a-z0-9_]+))\s*=\s*\{(?P<body>.*?)^\}", re.DOTALL | re.MULTILINE)
    for match in pattern.finditer(text):
        modifier = match.group(1)
        good = match.group(2)
        value_match = re.search(
            rf"^\s*local_{re.escape(good)}_output_modifier\s*=\s*([-+]?\d+(?:\.\d+)?)\s*$",
            match.group("body"),
            flags=re.MULTILINE,
        )
        if value_match is None:
            raise ValueError(f"{modifier} in {path} is missing local_{good}_output_modifier")
        values[good] = (modifier, value_match.group(1))
    if not values:
        raise ValueError(f"Could not find pp_rgo_bonus_<good> output modifiers in {path}")
    return values


def _location_potential_output_values(
    path: Path,
    goods: Iterable[str],
) -> dict[str, dict[str, list[str]]]:
    text = path.read_text(encoding="utf-8-sig")
    wanted = set(goods)
    values: dict[str, dict[str, list[str]]] = {good: {} for good in wanted}
    pattern = re.compile(r"^(pp_loc_[a-z0-9_]+)\s*=\s*\{(?P<body>.*?)^\}", re.DOTALL | re.MULTILINE)
    for match in pattern.finditer(text):
        modifier = match.group(1)
        for value_match in re.finditer(
            r"^\s*local_([a-z0-9_]+)_output_modifier\s*=\s*([-+]?\d+(?:\.\d+)?)\s*$",
            match.group("body"),
            flags=re.MULTILINE,
        ):
            good = value_match.group(1)
            value = value_match.group(2)
            if good in wanted and value not in {"0", "0.0", "0.00", "+0", "+0.0", "+0.00", "-0", "-0.0", "-0.00"}:
                values[good].setdefault(value, []).append(modifier)
    return values


def _modifier_value_branch(value: str, modifiers: list[str]) -> list[str]:
    operation, amount = _value_operation(value)
    lines = ["\tif = {"]
    if len(modifiers) == 1:
        lines.append(f"\t\tlimit = {{ has_location_modifier = {modifiers[0]} }}")
    else:
        lines.extend(["\t\tlimit = {", "\t\t\tOR = {"])
        lines.extend(f"\t\t\t\thas_location_modifier = {modifier}" for modifier in modifiers)
        lines.extend(["\t\t\t}", "\t\t}"])
    lines.extend([f"\t\t{operation} = {amount}", "\t}"])
    return lines


def _value_operation(value: str) -> tuple[str, str]:
    if value.startswith("-"):
        return "subtract", value[1:]
    return "add", value.removeprefix("+")


def _numeric_group_sort_key(item: tuple[str, list[str]]) -> tuple[float, str]:
    value, _modifiers = item
    return float(value), value


def _productivity_value_name(good: str) -> str:
    return f"pp_{good}_productivity_map_value"


def _productivity_map_label_value_name(good: str) -> str:
    return f"pp_{good}_productivity_map_label_value"


def _productivity_location_potential_value_name(good: str) -> str:
    return f"pp_{good}_productivity_location_potential_map_value"


def _productivity_rgo_bonus_value_name(good: str) -> str:
    return f"pp_{good}_productivity_rgo_bonus_map_value"


def _upsert_localization(path: Path, goods: Iterable[str]) -> None:
    existing = path.read_text(encoding="utf-8-sig")
    generated = _localization_block(goods)
    if LOCALIZATION_START in existing:
        if LOCALIZATION_END in existing:
            pattern = re.compile(
                rf"{re.escape(LOCALIZATION_START)}.*?{re.escape(LOCALIZATION_END)}\n?",
                re.DOTALL,
            )
            updated = pattern.sub(lambda _match: generated, existing)
        else:
            legacy_end = re.compile(
                rf"{re.escape(LOCALIZATION_START)}.*?"
                r'  MAPMODE_PP_LOCAL_OUTPUT_TT_WATER: "[^"]*"\n?',
                re.DOTALL,
            )
            updated = legacy_end.sub(lambda _match: generated, existing)
    else:
        anchor = "  # Unemployed Peasants (Unemployment) map mode - absolute numbers, cap 0-50k"
        if anchor not in existing:
            raise ValueError(f"Could not find localization insertion point in {path}")
        updated = existing.replace(anchor, generated + "\n" + anchor)
    _write_crlf(path, updated.rstrip() + "\n")


def _localization_block(goods: Iterable[str]) -> str:
    lines = [
        LOCALIZATION_START,
        "  # Generated by scripts/generate_raw_material_local_map_modes.py - do not edit by hand.",
        '  PP_LOCAL_OUTPUT_MAPMODE_RANGE: "Red-yellow-green static productivity bands"',
    ]
    goods = list(goods)
    for good in goods:
        name = "Wheat Productivity" if good == WHEAT_GOOD else f"Local {_display_name(good)} Output"
        lines.append(f'  mapmode_pp_local_{good}_output_modifier_name: "{name}"')
    lines.append("")
    for good in goods:
        lines.extend(_output_modifier_legend_localization_lines(good))
    lines.append("")
    for good in goods:
        upper = good.upper()
        display = _display_name(good).lower()
        lines.append(
            f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_TT_LAND: '
            f'"[ROOT.GetLocation.GetName] has static {display} productivity of '
            f"[ROOT.GetLocation.MakeScope.ScriptValue('{_productivity_map_label_value_name(good)}')|0].\""
        )
    lines.append("")
    for good in goods:
        upper = good.upper()
        display = _display_name(good).lower()
        lines.append(
            f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_TT_LAND_BREAKDOWN: '
            f'"[ROOT.GetLocation.GetName] static {display} productivity: '
            f"[ROOT.GetLocation.MakeScope.ScriptValue('{_productivity_map_label_value_name(good)}')|0].\\n"
            f"Location potential: [ROOT.GetLocation.MakeScope.ScriptValue('{_productivity_location_potential_value_name(good)}')|2].\\n"
            f"Raw-material bonus: [ROOT.GetLocation.MakeScope.ScriptValue('{_productivity_rgo_bonus_value_name(good)}')|2].\\n"
            f'The map color uses only those two static planning factors. Red marks negative productivity, yellow marks near-neutral productivity, and green marks positive productivity; stripes mark locations where {display} is the raw material."'
        )
    lines.extend(
        [
            "",
            '  MAPMODE_PP_LOCAL_OUTPUT_TT_WATER: "[ROOT.GetLocation.GetName] is not a land [location|e] so it does not have production modifiers."',
            LOCALIZATION_END,
        ]
    )
    return "\n".join(lines) + "\n"


def _output_modifier_legend_localization_lines(good: str) -> list[str]:
    upper = good.upper()
    name_key = f"mapmode_pp_local_{good}_output_modifier_name"
    display = _display_name(good).lower()
    description = (
        f"This colors [locations|e] by static {display} productivity from location potential and raw-material bonus. "
        "Red marks negative productivity, yellow marks near-neutral productivity, and green marks positive productivity; "
        f"the location label shows the integer percent value. Stripes mark locations where {display} is the raw material."
    )
    lines = [f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER: "#T ${name_key}$#!\\n{description}"']
    lines.extend(
        f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_{suffix}: "{_output_modifier_legend_description(good, suffix)}"'
        for suffix in OUTPUT_MODIFIER_LEGEND_CLASSES
    )
    lines.append(f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_RAW_MATERIAL: "{_display_name(good)} raw material"')
    return lines


def _output_modifier_legend_description(good: str, suffix: str) -> str:
    if good == WHEAT_GOOD:
        return {
            "EXTREME_DEFICIT": "Severe wheat productivity deficit",
            "DEFICIT": "Wheat productivity deficit",
            "NEUTRAL": "Near neutral wheat productivity",
            "GOOD": "Good wheat productivity",
            "EXCELLENT": "Excellent wheat productivity",
            "EXCEPTIONAL": "Exceptional wheat productivity",
        }[suffix]
    display = _display_name(good).lower()
    generic_descriptions = {
        "EXTREME_DEFICIT": f"Extreme local {display} deficit",
        "DEFICIT": f"Local {display} productivity deficit",
        "NEUTRAL": f"Near neutral local {display} output",
        "GOOD": f"Good local {display} productivity",
        "EXCELLENT": f"Excellent local {display} productivity",
        "EXCEPTIONAL": f"Exceptional local {display} output",
    }
    return generic_descriptions[suffix]


def _display_name(good: str) -> str:
    return good.replace("_", " ").title()


def _rgb(value: tuple[int, int, int]) -> str:
    red, green, blue = value
    return f"rgb {{ {red} {green} {blue} }}"


def _write_crlf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="\n") as stream:
        stream.write(text)


def _ensure_icons(mod_root: Path, goods: Iterable[str], project: dict) -> None:
    vanilla_root = _vanilla_root(project)
    targets = [mod_root / IN_GAME_ICON_REL, mod_root / MAIN_MENU_ICON_REL]
    for target in targets:
        target.mkdir(parents=True, exist_ok=True)

    missing: list[str] = []
    for good in goods:
        source = _icon_source(mod_root, vanilla_root, good)
        if source is None:
            missing.append(good)
            continue
        for target_dir in targets:
            destination = target_dir / f"pp_local_{good}_output_modifier.dds"
            if not destination.exists():
                shutil.copy2(source, destination)
    if missing:
        raise FileNotFoundError("Missing icon source for raw material goods: " + ", ".join(missing))


def _icon_source(mod_root: Path, vanilla_root: Path, good: str) -> Path | None:
    candidates = [
        mod_root / IN_GAME_ICON_REL / f"pp_local_{good}_output_modifier.dds",
        mod_root / MAIN_MENU_ICON_REL / f"pp_local_{good}_output_modifier.dds",
        mod_root / IN_GAME_ICON_REL / f"pp_{good}_output.dds",
        mod_root / MAIN_MENU_ICON_REL / f"pp_{good}_output.dds",
        vanilla_root / "game" / TRADE_GOOD_ICON_REL / f"icon_goods_{good}.dds",
        mod_root / TRADE_GOOD_ICON_REL / f"icon_goods_{good}.dds",
        mod_root / "in_game" / "gfx" / "interface" / "icons" / "trade_goods" / f"icon_goods_{good}.dds",
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


