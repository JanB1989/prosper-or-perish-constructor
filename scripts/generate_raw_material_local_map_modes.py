def _upsert_location_potential_map_modifiers(path: Path, goods: Iterable[str]) -> None:
    goods_set = set(goods)
    current_modifier: str | None = None
    output: list[str] = []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if _is_generated_map_value_modifier_line(line):
            continue
        start_match = re.match(r"^(pp_loc_[a-z0-9_]+)\s*=\s*\{", line)
        if start_match:
            current_modifier = start_match.group(1)
        elif current_modifier is not None and line.strip() == "}":
            current_modifier = None
        output.append(line)
        if current_modifier is None:
            continue
        value_match = re.match(
            r"^(\s*)local_([a-z0-9_]+)_output_modifier\s*=\s*([-+]?\d+(?:\.\d+)?)\s*$",
            line,
        )
        if value_match is None:
            continue
        good = value_match.group(2)
        value = value_match.group(3)
        if good in goods_set and not _is_zero_value(value):
            output.append(
                f"{value_match.group(1)}{_productivity_location_potential_modifier_name(good)} = {value}"
            )
    _write_crlf(path, "\n".join(output).rstrip() + "\n")


def _upsert_rgo_bonus_map_modifiers(path: Path, goods: Iterable[str]) -> None:
    goods_set = set(goods)
    current_good: str | None = None
    output: list[str] = []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if _is_generated_map_value_modifier_line(line):
            continue
        start_match = re.match(r"^pp_rgo_bonus_([a-z0-9_]+)\s*=\s*\{", line)
        if start_match:
            current_good = start_match.group(1)
        elif current_good is not None and line.strip() == "}":
            current_good = None
        output.append(line)
        if current_good is None or current_good not in goods_set:
            continue
        value_match = re.match(
            rf"^(\s*)local_{re.escape(current_good)}_output_modifier\s*=\s*([-+]?\d+(?:\.\d+)?)\s*$",
            line,
        )
        if value_match is not None and not _is_zero_value(value_match.group(2)):
            output.append(
                f"{value_match.group(1)}{_productivity_rgo_bonus_modifier_name(current_good)} = {value_match.group(2)}"
            )
    _write_crlf(path, "\n".join(output).rstrip() + "\n")


def _is_generated_map_value_modifier_line(line: str) -> bool:
    return (
        re.match(
            r"^\s*pp_[a-z0-9_]+_productivity_(?:location_potential|rgo_bonus)_map_modifier\s*=",
            line,
        )
        is not None
    )


def _is_zero_value(value: str) -> bool:
    return float(value) == 0


def _upsert_localization(path: Path, goods: Iterable[str]) -> None:
    existing = path.read_text(encoding="utf-8-sig")
    generated = _localization_block(goods)
    if LOCALIZATION_START in existing:
        if LOCALIZATION_END in existing:
            pattern = re.compile(
                rf"{re.escape(LOCALIZATION_START)}.*?{re.escape(LOCALIZATION_END)}\n?",
                re.DOTALL,
            )
            updated = pattern.sub(lambda _match: generated, existing)
        else:
            legacy_end = re.compile(
                rf"{re.escape(LOCALIZATION_START)}.*?"
                r'  MAPMODE_PP_LOCAL_OUTPUT_TT_WATER: "[^"]*"\n?',
                re.DOTALL,
            )
            updated = legacy_end.sub(lambda _match: generated, existing)
    else:
        anchor = "  # Unemployed Peasants (Unemployment) map mode - absolute numbers, cap 0-50k"
        if anchor not in existing:
            raise ValueError(f"Could not find localization insertion point in {path}")
        updated = existing.replace(anchor, generated + "\n" + anchor)
    _write_crlf(path, updated.rstrip() + "\n")


def _localization_block(goods: Iterable[str]) -> str:
    lines = [
        LOCALIZATION_START,
        "  # Generated by scripts/generate_raw_material_local_map_modes.py - do not edit by hand.",
        '  PP_LOCAL_OUTPUT_MAPMODE_RANGE: "Red-yellow-green static productivity bands"',
    ]
    goods = list(goods)
    for good in goods:
        name = "Wheat Productivity" if good == WHEAT_GOOD else f"Local {_display_name(good)} Output"
        lines.append(f'  mapmode_pp_local_{good}_output_modifier_name: "{name}"')
    lines.append("")
    for good in goods:
        lines.extend(_output_modifier_legend_localization_lines(good))
    lines.append("")
    for good in goods:
        upper = good.upper()
        display = _display_name(good).lower()
        lines.append(
            f'  PP_LOCAL_{upper}_OUTPUT_MODIFIER_TOTAL_TT: '
            f'"Total static {display} productivity from location potential and RGO bonus."'
        )
    lines.append("")
    for good in goods:
        upper = good.upper()
        lines.append(
            f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_TT_LAND: '
            f'"{_output_modifier_tooltip(good)}"'
        )
    lines.append("")
    for good in goods:
        upper = good.upper()
        lines.append(
            f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_TT_LAND_BREAKDOWN: '
            f'"{_output_modifier_tooltip(good)}"'
        )
    lines.extend(
        [
            "",
            '  MAPMODE_PP_LOCAL_OUTPUT_TT_WATER: "[ROOT.GetLocation.GetName] is not a land [location|e] so it does not have production modifiers."',
            LOCALIZATION_END,
        ]
    )
    return "\n".join(lines) + "\n"


def _output_modifier_tooltip(good: str) -> str:
    upper = good.upper()
    name_key = f"mapmode_pp_local_{good}_output_modifier_name"
    total_value = _tooltip_value(
        f"SIMPLE_CUSTOM,PP_LOCAL_{upper}_OUTPUT_MODIFIER_TOTAL_TT",
        f"[ROOT.GetLocation.MakeScope.ScriptValue('{_productivity_value_name(good)}')|2]",
    )
    location_modifier = _productivity_location_potential_modifier_name(good)
    rgo_modifier = _productivity_rgo_bonus_modifier_name(good)
    location_value = _tooltip_value(
        f"MODIFIER_TYPE,{location_modifier}",
        f"[ROOT.GetLocation.MakeScope.ScriptValue('{_productivity_location_potential_value_name(good)}')|2]",
    )
    rgo_value = _tooltip_value(
        f"MODIFIER_TYPE,{rgo_modifier}",
        f"[ROOT.GetLocation.MakeScope.ScriptValue('{_productivity_rgo_bonus_value_name(good)}')|2]",
    )
    return (
        f"#T ${name_key}$#!\\n"
        f"Location potential static modifier: {location_value}\\n"
        f"RGO bonus static modifier: {rgo_value}\\n"
        f"Total static modifier: {total_value}"
    )


def _tooltip_value(desc_key: str, value: str) -> str:
    return f"#TOOLTIP:{desc_key} #L {value}#!#!"


def _output_modifier_legend_localization_lines(good: str) -> list[str]:
    upper = good.upper()
    name_key = f"mapmode_pp_local_{good}_output_modifier_name"
    display = _display_name(good).lower()
    description = (
        f"This colors [locations|e] by static {display} productivity from location potential and raw-material bonus. "
        "Red marks negative productivity, yellow marks near-neutral productivity, and green marks positive productivity; "
        f"stripes mark locations where {display} is the raw material."
    )
    lines = [f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER: "#T ${name_key}$#!\\n{description}"']
    lines.extend(
        f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_{suffix}: "{_output_modifier_legend_description(good, suffix)}"'
        for suffix in OUTPUT_MODIFIER_LEGEND_CLASSES
    )
    lines.append(f'  MAPMODE_PP_LOCAL_{upper}_OUTPUT_MODIFIER_RAW_MATERIAL: "{_display_name(good)} raw material"')
    return lines


def _output_modifier_legend_description(good: str, suffix: str) -> str:
    if good == WHEAT_GOOD:
        return {
            "EXTREME_DEFICIT": "Severe wheat productivity deficit",
            "DEFICIT": "Wheat productivity deficit",
            "NEUTRAL": "Near neutral wheat productivity",
            "GOOD": "Good wheat productivity",
            "EXCELLENT": "Excellent wheat productivity",
            "EXCEPTIONAL": "Exceptional wheat productivity",
        }[suffix]
    display = _display_name(good).lower()
    generic_descriptions = {
        "EXTREME_DEFICIT": f"Extreme local {display} deficit",
        "DEFICIT": f"Local {display} productivity deficit",
        "NEUTRAL": f"Near neutral local {display} output",
        "GOOD": f"Good local {display} productivity",
        "EXCELLENT": f"Excellent local {display} productivity",
        "EXCEPTIONAL": f"Exceptional local {display} output",
    }
    return generic_descriptions[suffix]


def _display_name(good: str) -> str:
    return good.replace("_", " ").title()


def _rgb(value: tuple[int, int, int]) -> str:
    red, green, blue = value
    return f"rgb {{ {red} {green} {blue} }}"


def _write_crlf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="\n") as stream:
        stream.write(text)


def _ensure_icons(mod_root: Path, goods: Iterable[str], project: dict) -> None:
    vanilla_root = _vanilla_root(project)
    targets = [mod_root / IN_GAME_ICON_REL, mod_root / MAIN_MENU_ICON_REL]
    for target in targets:
        target.mkdir(parents=True, exist_ok=True)

    missing: list[str] = []
    for good in goods:
        source = _icon_source(mod_root, vanilla_root, good)
        if source is None:
            missing.append(good)
            continue
        for target_dir in targets:
            destination = target_dir / f"pp_local_{good}_output_modifier.dds"
            if not destination.exists():
                shutil.copy2(source, destination)
    if missing:
        raise FileNotFoundError("Missing icon source for raw material goods: " + ", ".join(missing))


def _icon_source(mod_root: Path, vanilla_root: Path, good: str) -> Path | None:
    candidates = [
        mod_root / IN_GAME_ICON_REL / f"pp_local_{good}_output_modifier.dds",
        mod_root / MAIN_MENU_ICON_REL / f"pp_local_{good}_output_modifier.dds",
        mod_root / IN_GAME_ICON_REL / f"pp_{good}_output.dds",
        mod_root / MAIN_MENU_ICON_REL / f"pp_{good}_output.dds",
        vanilla_root / "game" / TRADE_GOOD_ICON_REL / f"icon_goods_{good}.dds",
        mod_root / TRADE_GOOD_ICON_REL / f"icon_goods_{good}.dds",
        mod_root / "in_game" / "gfx" / "interface" / "icons" / "trade_goods" / f"icon_goods_{good}.dds",
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


