def main() -> None:
    project = _load_project_config(PROJECT_CONFIG)
    mod_root = _project_path(project["project"]["mod_root"])
    rgo_bonus_values = _rgo_bonus_output_values(mod_root / RGO_STATIC_BONUSES_REL)
    raw_materials = list(rgo_bonus_values)

    _write_map_modes(mod_root / MAP_MODE_REL, raw_materials)
    _write_script_values(mod_root / SCRIPT_VALUES_REL, raw_materials)
    _write_modifier_type_definitions(mod_root / MODIFIER_TYPE_DEFINITIONS_REL, raw_materials)
    _write_modifier_icons(mod_root / MODIFIER_ICONS_REL, raw_materials)
    _write_modifier_type_localization(mod_root / MODIFIER_TYPE_LOCALIZATION_REL, raw_materials)
