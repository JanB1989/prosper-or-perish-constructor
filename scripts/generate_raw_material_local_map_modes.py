def main() -> None:
    project = _load_project_config(PROJECT_CONFIG)
    mod_root = _project_path(project["project"]["mod_root"])
    rgo_bonus_values = _rgo_bonus_output_values(mod_root / RGO_STATIC_BONUSES_REL)
    raw_materials = list(rgo_bonus_values)
    location_potential_values = _location_potential_output_values(
        mod_root / LOCATION_STATIC_MODIFIERS_REL,
        raw_materials,
    )

    _write_map_modes(mod_root / MAP_MODE_REL, raw_materials)
    _write_script_values(
        mod_root / SCRIPT_VALUES_REL,
        raw_materials,
        location_potential_values,
        rgo_bonus_values,
    )
    _upsert_localization(mod_root / LOCALIZATION_REL, raw_materials)
    _ensure_icons(mod_root, raw_materials, project)
    print(f"Generated local output modifier map modes for {len(raw_materials)} raw materials.")


def _load_project_config(path: Path) -> dict:
    with path.open("rb") as stream:
        return tomllib.load(stream)


def _project_path(raw: str) -> Path:
    path = _host_path(Path(raw))
    return path if path.is_absolute() else (ROOT / path).resolve()


def _host_path(path: Path) -> Path:
    path_text = str(path)
    match = re.match(r"^([A-Za-z]):[\\/](.*)$", path_text)
    if match is None or os.name == "nt":
        return path
    drive = match.group(1).lower()
    tail = match.group(2).replace("\\", "/")
    return Path("/mnt") / drive / tail


def _vanilla_root(project: dict) -> Path:
    parser = project.get("parser", {})
    load_order = _project_path(str(parser.get("load_order") or "constructor.load_order.toml"))
    with load_order.open("rb") as stream:
        raw = tomllib.load(stream)
    paths = raw.get("paths", {})
    vanilla_root = _host_path(Path(str(paths.get("vanilla_root", ""))))
    if not vanilla_root.is_absolute():
        vanilla_root = (load_order.parent / vanilla_root).resolve()
    return vanilla_root


def _write_map_modes(path: Path, goods: Iterable[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    goods = list(goods)
    scales = _local_output_scales(goods)
    blocks = [
        "# Generated by scripts/generate_raw_material_local_map_modes.py - do not edit by hand.",
        "# Displays static local output potential for every generated raw-material bonus good.",
        "# Red/yellow/green classified diverging scale. Values are additive percentages (0.1 = +10%).",
        "# Map color = per-location potential + active pp_rgo_bonus_<good> static modifier.",
        "# Map names use an integer percent script value. Stripes mark matching raw-material locations.",
        "# Geography index = 2 keeps these in the terrain/climate bucket.",
        "",
        "@zoom_step_near = 2",
        "@data_gradient_alpha_inside = 1",
        "@data_gradient_alpha_outside = 1",
        "@data_gradient_width = 0.25",
        "@data_gradient_color_mult = 0.9",
        "@data_edge_width = 0",
        "@data_edge_sharpness = 0.01",
        "@data_edge_alpha = 0",
        "@data_edge_color_mult = 0",
        "@data_before_lighting_blend = 0.5",
        "@data_after_lighting_blend = 0.5",
        "",
    ]
    for good in goods:
        blocks.append(_map_mode_block(good, scales[good]))
    _write_crlf(path, "\n".join(blocks).rstrip() + "\n")


def _local_output_scales(goods: Iterable[str]) -> dict[str, SignedCenteredScale]:
    calibration = load_scale_calibration()
    configured = calibration.get("scales", {}).get("local_output_modifier", {}) if calibration else {}
    return {good: signed_scale_from_data(configured.get(good)) for good in goods}


