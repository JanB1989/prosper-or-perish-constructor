"""Research cost of every advance in two global variable maps, for the advance tree's research-time chip (Jan, 2026-11-25).

The tree shows on every advance a country has not researched how many years it takes at the country's present
research. The GUI has no number for an advance's cost: ``Advance.GetResearchCost`` returns the cost factor cut to a
whole number (1 for a 25-point advance, seen in game 2026-11-25) and the real cost only comes as text. So this pass
writes the cost of every advance into two global variable maps at game start, keyed by the advance, and the chip
reads them (``GetVariableFromGlobalVariableMap('pp_advance_cost', AdvanceItem.GetDefinition.MakeScope)``, a lookup,
no script per frame):

    pp_advance_cost        cost while the advance's age is the world's current age or a later one
    pp_advance_cost_past   cost once the world has moved past its age (the GUI picks by ``Advance.HasResearchCostDiscount``)

Two maps, not two variables per advance: the game logs "variable is set but is never used" with four suggestions for
every variable only the GUI reads (36,000 lines at load for 7,290 variables, seen 2026-11-25). The on_action reads
both maps itself (it fills them only when they are missing), so they count as used. Advances that exist only in a
DLC folder are left out (their scope would not resolve without the DLC); they show no chip.

Cost (engine, private notes advance_ai_149.md; the same for every country):
    max(1, (base + past) x (1 + AGE_RESEARCH_MODIFIER x age index + research_cost))
    base = BASE_UNIQUE_RESEARCH_COST when the advance's ``potential`` names a country (``has_or_had_tag``), else
    BASE_RESEARCH_COST; past = PREVIOUS_AGE_REDUCTION for an advance of a past age, else 0.

A save made before this pass has no maps: the chip stays hidden there (it shows only where the advance has an entry).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from prosper_or_perish_constructor import start_technology as st

MOD_FOLDER = "pp"
OUTPUT = Path("in_game/common/on_action/pp_advance_research_cost.txt")
DEFINES = Path("loading_screen/common/defines")
CURRENT_MAP = "pp_advance_cost"
PAST_MAP = "pp_advance_cost_past"
ON_ACTION = "pp_advance_research_cost"
_HEADER = ("GENERATED by `uv run ppc advance-cost apply` (src/prosper_or_perish_constructor/advance_research_cost.py); "
           "do not edit.")
_DEFINE_KEYS = ("BASE_RESEARCH_COST", "BASE_UNIQUE_RESEARCH_COST", "AGE_RESEARCH_MODIFIER", "PREVIOUS_AGE_REDUCTION")
_AGE = re.compile(r"^age_(\d+)_")


class AdvanceCostError(ValueError):
    pass


@dataclass(frozen=True)
class Cost:
    advance: str
    age_index: int
    research_cost: float
    unique: bool
    current: float
    past: float
    dlc_only: bool = False


def defines(vanilla_root: Path, mod_root: Path | None) -> dict[str, float]:
    """The four research cost defines, the mod's value where it sets one."""
    found: dict[str, float] = {}
    for path in st.layered_files(vanilla_root, mod_root, DEFINES):
        text = path.read_text(encoding="utf-8-sig", errors="replace")
        for key in _DEFINE_KEYS:
            for match in re.finditer(rf"(?m)^\s*{key}\s*=\s*(-?[0-9.]+)", text):
                found[key] = float(match.group(1))
    missing = [k for k in _DEFINE_KEYS if k not in found]
    if missing:
        raise AdvanceCostError(f"research cost defines not found: {', '.join(missing)}")
    return found


def _names_a_country(block: tuple[st.Stmt, ...]) -> bool:
    for stmt in block:
        if stmt.key == "has_or_had_tag":
            return True
        if stmt.is_block and _names_a_country(stmt.value):  # type: ignore[arg-type]
            return True
    return False


def costs(vanilla_root: Path, mod_root: Path) -> list[Cost]:
    values = defines(vanilla_root, mod_root)
    base, unique_base = values["BASE_RESEARCH_COST"], values["BASE_UNIQUE_RESEARCH_COST"]
    per_age, past = values["AGE_RESEARCH_MODIFIER"], values["PREVIOUS_AGE_REDUCTION"]
    out = []
    advances = st.effective_advances(vanilla_root, mod_root)
    for key, (mode, body) in st.output_blocks(mod_root).items():   # the ladder's own blocks: its REPLACEs carry the dearer gates
        if mode in st._REPLACE_MODES and key in advances:
            advances[key].body = body
    for key, advance in sorted(advances.items()):
        match = _AGE.match(advance.age or "")
        if not match:
            raise AdvanceCostError(f"advance {key}: age {advance.age!r} has no index")
        index = int(match.group(1)) - 1
        raw = st._last_scalar(advance.body, "research_cost")
        try:
            research_cost = float(raw) if raw is not None else 0.0
        except ValueError as error:
            raise AdvanceCostError(f"advance {key}: research_cost {raw!r} is not a number") from error
        unique = any(_names_a_country(v) for v in st._values(advance.body, "potential") if isinstance(v, tuple))
        factor = 1 + per_age * index + research_cost
        b = unique_base if unique else base
        out.append(Cost(key, index, research_cost, unique, max(1.0, b * factor), max(1.0, (b + past) * factor),
                        dlc_only=not advance.base_defined))
    return out


def _number(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return text or "0"


def render(rows: list[Cost]) -> str:
    lines = [
        f"# {_HEADER}",
        "# The research cost of every advance, for the research-time chip of the advance tree (the GUI has no number",
        "# for it). Filled once at game start; a save made before this file has no maps and shows no chip.",
        "on_game_start = {",
        "\ton_actions = {",
        f"\t\t{ON_ACTION}",
        "\t}",
        "}",
        "",
        f"{ON_ACTION} = {{",
        "\teffect = {",
        "\t\tif = {",
        f"\t\t\tlimit = {{ NOR = {{ has_global_variable_map = {CURRENT_MAP} has_global_variable_map = {PAST_MAP} }} }}",
    ]
    for row in rows:
        if row.dlc_only:
            continue
        key = f"advance_type:{row.advance}"
        lines.append(f"\t\t\tadd_to_global_variable_map = {{ name = {CURRENT_MAP} key = {key} value = {_number(row.current)} }}")
        lines.append(f"\t\t\tadd_to_global_variable_map = {{ name = {PAST_MAP} key = {key} value = {_number(row.past)} }}")
    lines += ["\t\t}", "\t}", "}"]
    return "\n".join(lines) + "\n"


def apply(repo: Path, project: Path, mod_root: Path | None = None, vanilla_root: Path | None = None,
          *, write: bool = True) -> tuple[list[Cost], bool]:
    """Write the on_action file; returns the costs and whether the file differs (or differed) from the render."""
    from prosper_or_perish_constructor.worldbuilder.stage import vanilla_root as find_vanilla

    repo = Path(repo)
    mod_root = Path(mod_root) if mod_root is not None else repo / "mod" / MOD_FOLDER
    vanilla_root = Path(vanilla_root) if vanilla_root is not None else find_vanilla(repo, Path(project))
    rows = costs(vanilla_root, mod_root)
    text = "﻿" + render(rows)
    path = mod_root / OUTPUT
    changed = not path.is_file() or path.read_text(encoding="utf-8") != text
    if changed and write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return rows, changed


def summary(rows: list[Cost], changed: bool, write: bool = True) -> str:
    state = ("rewritten" if changed else "unchanged") if write else ("OFF (run ppc advance-cost apply)" if changed else "current")
    unique = sum(1 for r in rows if r.unique)
    dlc = sum(1 for r in rows if r.dlc_only)
    return (f"Advance research cost: {len(rows) - dlc} advances ({unique} country advances; {dlc} DLC-only left out), "
            f"{OUTPUT.name} {state}.")
