"""Blockade capacity x10 for every ship that is not a levy ship (2026-10-23, Jan).

Vanilla sets `blockade_capacity` on the navy age templates (00_age_templates_navy.txt) and on some unique ships; the
others take it through `copy_from`. This pass writes the resolved value x `[blockade_capacity] factor` on every navy
unit type that has one, so the result does not depend on whether the engine resolves `copy_from` before or after an
INJECT. Levy ships (`levy = yes`) keep vanilla's value, written explicitly in case they copy a scaled template.
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass
from pathlib import Path

from prosper_or_perish_constructor.ship_upkeep import MOD_FOLDER, _blocks, _number, _vanilla_blocks

OUTPUT = Path("in_game/common/unit_types/pp_blockade_capacity.txt")
DECIMALS = 5


@dataclass(frozen=True)
class Ship:
    unit: str
    category: str
    levy: bool
    vanilla: float
    new: float


def factor(project: Path) -> float:
    with Path(project).open("rb") as handle:
        return float(tomllib.load(handle)["blockade_capacity"]["factor"])


def plan(repo: Path, project: Path) -> list[Ship]:
    """One entry per navy unit type with a blockade capacity."""
    units = _vanilla_blocks(repo, project, "unit_types")
    scale = factor(project)

    def field(unit: str, key: str, seen: tuple[str, ...] = ()) -> object:
        body = units[unit]
        value = body.first(key)
        parent = body.first("copy_from")
        if value is None and parent is not None and str(parent) in units and str(parent) not in seen:
            return field(str(parent), key, (*seen, unit))
        return value

    ships: list[Ship] = []
    for unit in units:
        category = str(field(unit, "category") or "")
        vanilla = _number(field(unit, "blockade_capacity"))
        if not category.startswith("navy_") or vanilla <= 0:
            continue
        levy = str(units[unit].first("levy")) == "yes"
        ships.append(Ship(unit, category, levy, vanilla, vanilla if levy else round(vanilla * scale, DECIMALS)))
    return ships


def render(ships: list[Ship], scale: float) -> str:
    lines = [
        "# GENERATED by `uv run ppc blockade apply` (src/prosper_or_perish_constructor/blockade_capacity.py); do not edit.",
        f"# Blockade capacity x{scale:g} for every ship that is not a levy ship ([blockade_capacity] in constructor.toml).",
        "",
    ]
    for ship in sorted(ships, key=lambda s: (s.category, s.unit)):
        note = "levy ship, vanilla" if ship.levy else f"vanilla {ship.vanilla:g}"
        lines += [
            f"TRY_INJECT:{ship.unit} = {{",
            f"\tblockade_capacity = {ship.new:.{DECIMALS}f}".rstrip("0").rstrip(".") + f"  # {note}",
            "}",
        ]
    return "\n".join(lines) + "\n"


def apply(repo: Path, project: Path, *, write: bool = True) -> tuple[list[Ship], bool]:
    """Returns the plan and whether the file was (or would be) changed."""
    ships = plan(repo, project)
    path = Path(repo) / "mod" / MOD_FOLDER / OUTPUT
    text = render(ships, factor(project))
    current = path.read_text(encoding="utf-8-sig") if path.exists() else None
    changed = current != text
    if write and changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8-sig")
    return ships, changed
