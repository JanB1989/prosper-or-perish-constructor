def _population_capacity_train(
    args: argparse.Namespace, extra: Sequence[str], repo: Path, project: Path
) -> int:
    _reject_extra_population_capacity_args("train", extra)
    config = _population_capacity_pipeline_config(args, repo, project)
    paths = _population_capacity_model_paths(repo, config)
    # Compare writes a separate clean pre-scenario frame.  Train on that exact
    # frame so the learned model fingerprint matches the comparison gate rather
    # than a table whose output quantiles were rewritten by uncertainty passes.
    frame_path = paths["comparison_dir"] / "location_candidates_base.parquet"
    if not frame_path.is_file():
        frame_path = paths["comparison_dir"] / "location_candidates.parquet"
    output_path = paths["comparison_dir"] / "torch_residual_model.json"
    research_audit_path = paths["comparison_dir"] / "research_audit.json"
    crosswalk_audit_path = paths["comparison_dir"] / "crosswalk_audit.json"
    evidence_audit_path = paths["comparison_dir"] / "evidence_registry_audit.json"
    physical_closure_path = paths["comparison_dir"] / "physical_closure_manifest.json"
    _require_population_capacity_inputs(
        "train",
        {
            "physical comparison frame": frame_path,
            "benchmark registry": paths["benchmarks"],
            "research audit": research_audit_path,
            "crosswalk audit": crosswalk_audit_path,
            "evidence merge audit": evidence_audit_path,
            "physical closure manifest": physical_closure_path,
        },
    )
    research_audit = json.loads(research_audit_path.read_text(encoding="utf-8"))
    crosswalk_audit = json.loads(crosswalk_audit_path.read_text(encoding="utf-8"))
    evidence_audit = json.loads(evidence_audit_path.read_text(encoding="utf-8"))
    physical_closure = json.loads(physical_closure_path.read_text(encoding="utf-8"))
    preflight = {
        "research_contract_complete": bool(research_audit.get("research_contract_complete")),
        "crosswalk_complete": bool(crosswalk_audit.get("crosswalk_complete")),
        "training_eligible_count": int(evidence_audit.get("training_eligible_count", 0)),
        "two_sided_interval_count": int(evidence_audit.get("two_sided_interval_count", 0)),
        "lower_bound_count": int(evidence_audit.get("lower_bound_count", 0)),
        "source_family_count": int(evidence_audit.get("source_family_count", 0)),
        "super_region_count": int(evidence_audit.get("super_region_count", 0)),
        "physical_labels_complete": bool(physical_closure.get("physical_labels_complete")),
        "physical_scientific_validation_complete": bool(
            all(physical_closure.get("scientific_validation", {}).values())
        ),
        "physical_training_allowed": bool(
            physical_closure.get(
                "physical_training_allowed", physical_closure.get("training_allowed")
            )
        ),
        "physical_training_blockers": physical_closure.get("training_blockers", []),
        "physical_scientific_blockers": physical_closure.get("scientific_blockers", {}),
        "minimum_training_groups": 12,
        "minimum_source_families": 8,
        "minimum_super_regions": 5,
    }
    preflight["training_evidence_complete"] = bool(
        preflight["research_contract_complete"]
        and preflight["crosswalk_complete"]
        and preflight["training_eligible_count"] >= preflight["minimum_training_groups"]
        and preflight["source_family_count"] >= preflight["minimum_source_families"]
        and preflight["super_region_count"] >= preflight["minimum_super_regions"]
        and preflight["physical_labels_complete"]
        and preflight["physical_scientific_validation_complete"]
        and preflight["physical_training_allowed"]
    )
    if not preflight["training_evidence_complete"]:
        print(json.dumps({"status": "blocked", "reason": "evidence_preflight_failed", **preflight}, indent=2, sort_keys=True), flush=True)
        return 1
    from prosper_or_perish_population_capacity import train_aggregate_torch_residual

    print(
        train_aggregate_torch_residual(
            frame_path=frame_path,
            benchmarks_path=paths["benchmarks"],
            output_path=output_path,
            device=args.device,
            epochs=args.epochs,
            learning_rate=args.learning_rate,
            seed=args.seed,
            evidence_registry_path=paths["comparison_dir"] / "evidence_registry.json",
        ),
        flush=True,
    )
    return 0


