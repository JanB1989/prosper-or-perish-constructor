def _population_capacity_crosswalk_audit(
    args: argparse.Namespace, extra: Sequence[str], repo: Path, project: Path
) -> int:
    _reject_extra_population_capacity_args("crosswalk-audit", extra)
    config = _population_capacity_pipeline_config(args, repo, project)
    paths = _population_capacity_model_paths(repo, config)
    import polars as pl
    from prosper_or_perish_population_capacity import write_crosswalk_audit

    packet_root = _population_capacity_evidence_root(repo) / "evidence_packets"
    output = paths["comparison_dir"] / "crosswalk_audit.json"
    # Prefer the current comparison frame only when it attests the bounded
    # area-calibration method.  Otherwise fall back to the verified geometry
    # contract; this rejects stale full-pixel snapshots without discarding
    # exact island/region area corrections already materialized by compare.
    candidate_geometry = paths["comparison_dir"] / "location_candidates.parquet"
    geometry = candidate_geometry
    if candidate_geometry.is_file():
        try:
            columns = set(pl.read_parquet(candidate_geometry, n_rows=0).columns)
            methods = set(
                str(value)
                for value in pl.read_parquet(candidate_geometry, columns=["area_method"])["area_method"].unique().to_list()
            ) if "area_method" in columns else set()
            if "area_km2" not in columns or not any("bounded_exact_crosswalks" in value for value in methods):
                geometry = _preferred_population_geometry(paths)
        except Exception:
            geometry = _preferred_population_geometry(paths)
    else:
        geometry = _preferred_population_geometry(paths)
    audit = write_crosswalk_audit(
        packet_root=packet_root,
        geometry_path=geometry,
        output_path=output,
    )
    print(json.dumps(audit, indent=2, sort_keys=True), flush=True)
    return 0 if audit["crosswalk_complete"] else 1


