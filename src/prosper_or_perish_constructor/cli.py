def _setup_corrections(
    args: argparse.Namespace,
    extra: Sequence[str],
    repo: Path,
    project: Path,
) -> int:
    if extra:
        raise SystemExit("setup-corrections does not accept extra arguments.")
    if args.disable and args.write:
        raise SystemExit("setup-corrections accepts either --disable or --write, not both.")

    if args.disable:
        return _disable_setup_corrections(repo, project, force=args.force)

    script = repo / SETUP_CORRECTION_SCRIPT
    if not script.is_file():
        raise SystemExit(f"Missing setup correction generator: {script}")

    command: list[str | Path] = [
        sys.executable,
        script,
        "--repo",
        repo,
        "--project",
        project,
        "--load-order",
        _resolve_repo_relative_path(repo, args.load_order),
    ]
    if args.write:
        command.append("--write")
    if args.force:
        command.append("--force")
    if args.log is not None:
        command.extend(["--log", args.log])
    if args.vanilla_root is not None:
        command.extend(["--vanilla-root", args.vanilla_root])
    for building in args.building:
        command.extend(["--building", building])
    if args.direct_building_manager_only:
        command.append("--direct-building-manager-only")
    return _run(command, repo)


