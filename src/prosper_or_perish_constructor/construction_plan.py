def _can_build(name: str) -> str:
    return f"location_and_owner_can_build = {{ building_type = {name} }}"


def _not_never(good: str) -> str:
    return f"scope:pp_cplan_country = {{ pp_cplan_mode_{good} < 2.5 }}"


def render_effects(config: Config, farm_lines: dict[str, list[str]], farm_goods: dict[str, str],
                   goods: list[str], producers: dict[str, list[str]]) -> str:
    parts = [HEADER]
    # --- farm picker
    parts.append(
        "\n# Location scope (owned by scope:pp_cplan_country). Picks the crop farm line to grow here: a line that stands\n"
        "# grows its own standing tier, a new line starts at its highest buildable tier; the best score wins\n"
        "# (pp_cplan_farm_score_<line>). Lines of a good set to Never are skipped.\n"
        "pp_cplan_try_farm_here = {\n"
        "\tset_variable = { name = pp_cplan_best value = 1 }\n"
        "\tset_variable = { name = pp_cplan_pick value = 1 }\n"
    )
    index = 2
    pick: list[tuple[int, str]] = []
    for line, tiers in farm_lines.items():
        good = farm_goods[line]
        numbers = {tier: index + position for position, tier in enumerate(tiers)}
        index += len(tiers)
        pick += [(numbers[tier], tier) for tier in tiers]
        standing_any = " ".join(f"has_building = building_type:{tier}" for tier in tiers)
        parts.append(f"\t# {line} ({good})\n\tif = {{\n\t\tlimit = {{ {_not_never(good)} }}\n")
        # a standing line grows its highest standing tier that can be built
        parts.append(f"\t\tif = {{\n\t\t\tlimit = {{ OR = {{ {standing_any} }} }}\n")
        for position, tier in enumerate(reversed(tiers)):
            parts.append(
                f"\t\t\t{'if' if position == 0 else 'else_if'} = {{\n"
                f"\t\t\t\tlimit = {{ has_building = building_type:{tier} {_can_build(tier)} }}\n"
                f"\t\t\t\tset_variable = {{ name = pp_cplan_cand value = {numbers[tier]} }}\n\t\t\t}}\n"
            )
        parts.append("\t\t}\n\t\telse = {\n")
        # a new line starts at its highest buildable tier
        for position, tier in enumerate(reversed(tiers)):
            parts.append(
                f"\t\t\t{'if' if position == 0 else 'else_if'} = {{\n"
                f"\t\t\t\tlimit = {{ {_can_build(tier)} }}\n"
                f"\t\t\t\tset_variable = {{ name = pp_cplan_cand value = {numbers[tier]} }}\n\t\t\t}}\n"
            )
        parts.append("\t\t}\n")
        parts.append(
            "\t\tif = {\n\t\t\tlimit = { has_variable = pp_cplan_cand }\n"
            f"\t\t\tset_variable = {{ name = pp_cplan_score value = pp_cplan_farm_score_{line} }}\n"
            "\t\t\tif = {\n\t\t\t\tlimit = { var:pp_cplan_score > var:pp_cplan_best }\n"
            "\t\t\t\tset_variable = { name = pp_cplan_best value = var:pp_cplan_score }\n"
            "\t\t\t\tset_variable = { name = pp_cplan_pick value = var:pp_cplan_cand }\n"
            "\t\t\t}\n\t\t\tremove_variable = pp_cplan_cand\n\t\t\tremove_variable = pp_cplan_score\n\t\t}\n"
            "\t}\n"
        )
    for number, tier in pick:
        parts.append(
            f"\tif = {{\n\t\tlimit = {{ var:pp_cplan_pick > {number - 0.5:g} var:pp_cplan_pick < {number + 0.5:g} }}\n"
            f"\t\tpp_cplan_construct_food = {{ type = {tier} }}\n\t}}\n"
        )
    parts.append("\tremove_variable = pp_cplan_best\n\tremove_variable = pp_cplan_pick\n}\n")

    # --- capital food buildings
    for name, buildings, comment in (
        ("pp_cplan_try_kitchen_here", config.kitchens, "a kitchen level (the province's Cookshop budget is its max level)"),
        ("pp_cplan_try_tavern_here", config.taverns, "a Tavern level"),
        ("pp_cplan_try_granary_here", config.granaries, "a Granary level"),
    ):
        parts.append(f"\n# Location scope (the province capital): {comment}, first that can be built.\n{name} = {{\n")
        for position, building in enumerate(buildings):
            keyword = "if" if position == 0 else "else_if"
            parts.append(
                f"\t{keyword} = {{\n\t\tlimit = {{ {_can_build(building)} }}\n"
                f"\t\tpp_cplan_construct_food = {{ type = {building} }}\n\t}}\n"
            )
        parts.append("}\n")

    # --- logistics
    parts.append("\n# Location scope: the first logistics building that can be built here ([construction_plan] logistics_order).\n"
                 "pp_cplan_try_logistics_here = {\n")
    for position, building in enumerate(config.logistics_order):
        keyword = "if" if position == 0 else "else_if"
        parts.append(
            f"\t{keyword} = {{\n\t\tlimit = {{ {_can_build(building)} }}\n"
            f"\t\tpp_cplan_construct = {{ type = {building} why = {WHY_LOGISTICS} }}\n\t}}\n"
        )
    parts.append("}\n")

    # --- goods
    parts.append("\n# ---- Goods ----\n")
    for good in goods:
        names = producers[good]
        parts.append(f"\n# Location scope: a producer of {good}, a standing one first.\npp_cplan_try_goods_{good} = {{\n")
        first = True
        for name in names:
            parts.append(
                f"\t{'if' if first else 'else_if'} = {{\n\t\tlimit = {{ has_building = building_type:{name} {_can_build(name)} }}\n"
                f"\t\tpp_cplan_construct = {{ type = {name} why = {WHY_GOODS} }}\n\t}}\n"
            )
            first = False
        for name in names:
            parts.append(
                f"\telse_if = {{\n\t\tlimit = {{ {_can_build(name)} }}\n"
                f"\t\tpp_cplan_construct = {{ type = {name} why = {WHY_GOODS} }}\n\t}}\n"
            )
        parts.append("}\n")
        parts.append(f"# Location scope: one more level of a standing {good} producer that earns.\npp_cplan_expand_goods_{good} = {{\n")
        first = True
        for name in names:
            parts.append(
                f"\t{'if' if first else 'else_if'} = {{\n\t\tlimit = {{\n"
                f"\t\t\tany_buildings_in_location = {{ building_type = building_type:{name} building_profit > 0 is_at_max_level = no }}\n"
                f"\t\t\t{_can_build(name)}\n\t\t}}\n"
                f"\t\tpp_cplan_construct = {{ type = {name} why = {WHY_GOODS} }}\n\t}}\n"
            )
            first = False
        parts.append("}\n")

    parts.append(
        "\n# Country scope (scope:pp_cplan_country): one construction per good and month at most, while the budget lasts.\n"
        "pp_cplan_goods_run = {\n"
    )
    for good in goods:
        parts.append(
            f"\t# {good}\n"
            f"\tif = {{\n\t\tlimit = {{ pp_cplan_mode_{good} > 0.5 pp_cplan_mode_{good} < 1.5 pp_cplan_budget_left = yes }}\n"
            "\t\tremove_variable = pp_cplan_hit\n"
            "\t\tordered_owned_location = {\n"
            f"\t\t\tlimit = {{ pp_cplan_location_ok = yes pp_cplan_months_{good} < scope:pp_cplan_country.pp_cplan_keep_months }}\n"
            f"\t\t\torder_by = pp_cplan_site_{good}\n"
            "\t\t\tmax = 30\n\t\t\tcheck_range_bounds = no\n"
            "\t\t\tif = {\n\t\t\t\tlimit = { pp_cplan_may_try = yes }\n"
            f"\t\t\t\tpp_cplan_try_goods_{good} = yes\n\t\t\t}}\n"
            "\t\t}\n\t}\n"
            f"\telse_if = {{\n\t\tlimit = {{ pp_cplan_mode_{good} > 1.5 pp_cplan_mode_{good} < 2.5 pp_cplan_budget_left = yes }}\n"
            "\t\tremove_variable = pp_cplan_hit\n"
            "\t\tordered_owned_location = {\n"
            f"\t\t\tlimit = {{ pp_cplan_location_ok = yes pp_cplan_has_earner_{good} = yes }}\n"
            f"\t\t\torder_by = pp_cplan_site_{good}\n"
            "\t\t\tmax = 30\n\t\t\tcheck_range_bounds = no\n"
            "\t\t\tif = {\n\t\t\t\tlimit = { pp_cplan_may_try = yes }\n"
            f"\t\t\t\tpp_cplan_expand_goods_{good} = yes\n\t\t\t}}\n"
            "\t\t}\n\t}\n"
        )
    parts.append("\tremove_variable = pp_cplan_hit\n}\n")

    # --- goods mode setter (scripted GUI pp_cplan_good_mode)
    parts.append(
        "\n# Country scope: sets the mode of the good named by the flag scope:pp_good to the flag scope:pp_mode\n"
        "# (off / keep / expand / never). Called by the scripted GUI pp_cplan_good_mode.\n"
        "pp_cplan_set_good_mode = {\n\tswitch = {\n\t\ttrigger = scope:pp_good\n"
    )
    for good in goods:
        parts.append(f"\t\tflag:{good} = {{ pp_cplan_apply_mode = {{ var = pp_cplan_g_{good} }} }}\n")
    parts.append("\t}\n}\n")
    return "".join(parts)



def render_triggers(goods: list[str], producers: dict[str, list[str]]) -> str:
    parts = [HEADER]
    for good in goods:
        parts.append(
            f"\n# Location scope: a standing {good} producer that earns and can grow here.\n"
            f"pp_cplan_has_earner_{good} = {{\n"
            "\tOR = {\n"
            + "".join(
                f"\t\tany_buildings_in_location = {{ building_type = building_type:{name} building_profit > 0 is_at_max_level = no }}\n"
                for name in producers[good]
            )
            + "\t}\n}\n"
        )
    return "".join(parts)


