def upgrade_pairs(buildings: dict[str, Entry]) -> list[tuple[str, str]]:
    """(older tier, its direct successor) for every building type that names an older tier with ``obsolete = <older>``,
    in database order of the successors (where several types name the same older tier, e.g. regional variants, the
    rule tries them in this order). Keys only a DLC folder defines are left out."""
    pairs: list[tuple[str, str]] = []
    for name, entry in buildings.items():
        if entry.dlc_only:
            continue
        for body in entry.bodies:
            for older in top_values(body, "obsolete"):
                if older in buildings and not buildings[older].dlc_only and older != name and (older, name) not in pairs:
                    pairs.append((older, name))
    return pairs



def building_lines(buildings: dict[str, Entry], keys: tuple[str, ...]) -> tuple[dict[str, tuple[str, ...]], list[str], list[str]]:
    """Configured key -> its upgrade line, highest tier first (every building that makes it obsolete, directly or
    through a tier between, then the key itself), with the keys the game does not have and the keys that are a later
    tier of another configured key (one tile per line)."""
    newer: dict[str, set[str]] = {}
    for name, entry in buildings.items():
        if entry.dlc_only:
            continue
        for body in entry.bodies:
            for older in top_values(body, "obsolete"):
                newer.setdefault(older, set()).add(name)

    def above(name: str, seen: frozenset[str]) -> dict[str, int]:
        """Later tiers of name -> their distance."""
        found: dict[str, int] = {}
        for later in sorted(newer.get(name, ())):
            if later in seen:
                continue
            found[later] = max(found.get(later, 0), 1)
            for further, distance in above(later, seen | {later}).items():
                found[further] = max(found.get(further, 0), distance + 1)
        return found

    lines: dict[str, tuple[str, ...]] = {}
    missing: list[str] = []
    duplicates: list[str] = []
    taken: set[str] = set()
    for key in keys:
        if key not in buildings or buildings[key].dlc_only:
            missing.append(key)
            continue
        later = above(key, frozenset({key}))
        tiers = tuple(sorted(later, key=lambda name: (-later[name], name))) + (key,)
        if taken.intersection(tiers):
            duplicates.append(key)
            continue
        lines[key] = tiers
        taken.update(tiers)
    return lines, missing, duplicates


