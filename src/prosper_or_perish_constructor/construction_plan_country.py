def switched_off(blocks: tuple[str, ...]) -> bool:
    return any(_tokens(block) == "always = no" for block in blocks)


def read_rights(mod_root: Path, vanilla_root: Path) -> tuple[list[Right], list[str], list[str]]:
    """The town rights the plan can grant, in database order, with the rights that are switched off (a potential or
    allow that is exactly ``always = no``) and the rights only a DLC folder defines (left out: the mod's script names
    no DLC-only key)."""
    unlocks: dict[str, list[str]] = {}
    for advance, entry in database(mod_root, vanilla_root, ADVANCES).items():
        if entry.dlc_only:
            continue
        for body in entry.bodies:
            for right in top_values(body, "unlock_town_rights"):
                if advance not in unlocks.setdefault(right, []):
                    unlocks[right].append(advance)
    rights: list[Right] = []
    off: list[str] = []
    dlc: list[str] = []
    for key, entry in database(mod_root, vanilla_root, TOWN_RIGHTS).items():
        potential = tuple(block for body in entry.bodies for block in inner_blocks(body, "potential"))
        allow = tuple(block for body in entry.bodies for block in inner_blocks(body, "allow"))
        if switched_off(potential) or switched_off(allow):
            off.append(key)
            continue
        if entry.dlc_only:
            dlc.append(key)
            continue
        specialization = [value for body in entry.bodies for value in top_values(body, "is_specialization")]
        upgrades = [value for body in entry.bodies for value in top_values(body, "upgrades_to")]
        icon = (icon_texture(RIGHT_ICONS, key, mod_root, vanilla_root)
                or icon_texture(RIGHT_ICONS, DEFAULT_RIGHT_ICON, mod_root, vanilla_root) or "")
        rights.append(Right(key=key, potential=potential, allow=allow,
                            specialization=bool(specialization) and specialization[-1] == "yes",
                            upgrades_to=upgrades[-1] if upgrades else None,
                            advances=tuple(unlocks.get(key, ())), icon=icon))
    known = {right.key for right in rights}
    rights = [right if right.upgrades_to in known else replace(right, upgrades_to=None) for right in rights]
    return rights, off, dlc


def order_rights(rights: list[Right], first: tuple[str, ...]) -> tuple[list[Right], list[str]]:
    """The order the rule goes through the rights: the keys of ``rights_order`` first, then the specialization rights,
    then the rest, each in database order. The game loads a right before the charter that upgrades into it, so a
    location that qualifies for both gets the stronger right."""
    by_key = {right.key: right for right in rights}
    unknown = [key for key in first if key not in by_key]
    head = [by_key[key] for key in dict.fromkeys(first) if key in by_key]
    named = {right.key for right in head}
    rest = [right for right in rights if right.key not in named]
    return head + [r for r in rest if r.specialization] + [r for r in rest if not r.specialization], unknown


def upgrade_sources(rights: list[Right]) -> dict[str, list[str]]:
    """Right -> the rights that upgrade into it."""
    found: dict[str, list[str]] = {}
    for right in rights:
        if right.upgrades_to:
            found.setdefault(right.upgrades_to, []).append(right.key)
    return found


def tile_order(rights: list[Right]) -> list[Right]:
    """The tiles' order: the rights every country sees first (full rows), then the rest; each in the rule's order."""
    return [right for right in rights if right.always_shown] + [right for right in rights if not right.always_shown]


def explicit_nor(text: str) -> str:
    """``NOT = { a b }`` means neither a nor b in the engine; the copy spells such a block ``NOR`` (the plan's scripts
    never hold a NOT with several conditions: tests/test_construction_plan.py). Nothing else of the text changes."""
    out: list[str] = []
    index = 0
    for match in re.finditer(r"\bNOT(\s*=\s*\{)", text):
        level, end = 1, match.end()
        while end < len(text) and level:
            level += {"{": 1, "}": -1}.get(text[end], 0)
            end += 1
        conditions, depth = 0, 0
        for token in re.finditer(r"\{|\}|[A-Za-z_:.\"()0-9?]+\s*(?:[<>=!?]+)", text[match.end():end - 1]):
            if token.group(0) == "{":
                depth += 1
            elif token.group(0) == "}":
                depth -= 1
            elif depth == 0:
                conditions += 1
        out.append(text[index:match.start()] + ("NOR" if conditions > 1 else "NOT"))
        index = match.start() + 3
    return "".join(out) + text[index:]


def trigger_lines(blocks: tuple[str, ...], tab: str = "\t") -> list[str]:
    """Database blocks as the lines of a scripted trigger body: the text as written (a NOT with several conditions
    spelled NOR, which is what it means), re-indented."""
    lines: list[str] = []
    for block in blocks:
        raw = [line.rstrip() for line in explicit_nor(block).splitlines() if line.strip()]
        indent = min((len(line) - len(line.lstrip("\t ")) for line in raw), default=0)
        lines += [tab + line[indent:] for line in raw]
    return lines


def potential_lines(right: Right) -> list[str]:
    """The body of the right's potential trigger (country scope): one of its unlocking advances, then its potential."""
    lines: list[str] = []
    if len(right.advances) == 1:
        lines.append(f"\thas_advance = {right.advances[0]}")
    elif right.advances:
        lines.append("\tOR = {")
        lines += [f"\t\thas_advance = {advance}" for advance in right.advances]
        lines.append("\t}")
    lines += trigger_lines(right.potential)
    return lines or ["\talways = yes"]


