"""Construction Plan, the country rules (Jan 2026-11-10): the "Towns and Buildings" tab.

Jan: "I also want the functionality to decide on global buildings to be built. We can say: we want universities and
stuff like that. Upgrading cities and applying town rights. We have to be very careful to keep the UI tight."

Three sections, all off until the player ticks something; nothing is kept between passes:

* Upgrade buildings (one switch in the public buildings' row): every standing, open building whose successor
  (``obsolete = <older tier>``) the country has researched is upgraded, one level and one location at a time, highest
  control first (in game 2026-11-10: ``construct_building`` with the successor is the game's Upgrade button).
* Public buildings: a tile per building of ``[construction_plan_country] public_buildings`` (a building with later
  tiers, ``obsolete = <older tier>``, is one tile: the plan builds the highest tier the country can build and never
  where a tier of the line stands). Ticked types get one level in every owned location that can have it, whose maximum
  control reaches the player's line, highest control first.
* Towns and cities: rural settlements to towns (from the player's population line) and towns to cities, where the
  rank's own conditions pass (the rank below, the game's population minimum, no modifier that forbids it) and the
  market holds the construction goods, biggest population first (``construct_location_rank``, which charges the
  game's price itself; booked only when gold was paid).
* Urban rights: the ticked town rights wherever a location qualifies, biggest population first, while the country keeps
  the player's amount of political influence. The rights are read from the game's and the mod's town rights files in
  load order (rights switched off with ``always = no`` are left out); a right an advance unlocks
  (``unlock_town_rights``) needs one of those advances.

The first three are the gold rule group ``pp_cplan_group_country`` (construction code 107, inside ``pp_cplan_run``); the
rights cost no gold and run once after the groups (``pp_cplan_country_rights``). The monthly pass, the budgets that
save (the group pays from its purse and saves for the first thing it cannot pay for: a building or an upgrade), the
ledger and the weights are ``construction_plan.py``'s and the hand-written ``pp_construction_plan.txt``; this module
writes only its own files (docs/construction_plan_country.md):

* ``scripted_effects/pp_construction_plan_country.txt``, ``scripted_triggers/...``, ``script_values/...``,
  ``scripted_guis/...`` (the tab's buttons), ``gui/pp_construction_plan_country.gui`` (the tab, type
  ``pp_cplan_country_tab``) and ``localization/english/pp_construction_plan_country_l_english.yml``.

Variables carry + 100 (a variable at 0 counts as unset; ``var:x = n`` compares scopes).
"""

