def build(repo: Path, project: Path, mod_root: Path, vanilla_root: Path) -> tuple[Result, dict[Path, str]]:
    """What the module finds and the files it writes (relative to the mod root)."""
    config = load_config(project)
    result = Result()
    types = database(mod_root, vanilla_root, BUILDING_TYPES)
    lines, result.missing, result.duplicate_lines = building_lines(types, config.public_buildings)
    for key, tiers in lines.items():
        icon = icon_texture(BUILDING_ICONS, key, mod_root, vanilla_root)
        if icon is None:
            result.missing_icons.append(key)
            continue
        result.buildings.append(Building(key=key, tiers=tiers, icon=icon))
    found, result.switched_off, result.dlc_rights = read_rights(mod_root, vanilla_root)
    result.missing_icons += [right.key for right in found if not right.icon]
    found = [right for right in found if right.icon]
    result.rights, result.unknown_order = order_rights(found, config.rights_order)

    prices = database(mod_root, vanilla_root, PRICES)
    result.prices = {price: price_amount(prices, price, "gold") for _, price in RANKS.values()}
    result.prices[GRANT_PRICE] = price_amount(prices, GRANT_PRICE, "political_influence")
    result.ranks = read_ranks(mod_root, vanilla_root)
    costs, _ = cp.building_costs(mod_root, vanilla_root)
    # the successors the plan's cost data knows (the base game's and the mod's building types)
    result.upgrades = [(older, successor) for older, successor in upgrade_pairs(types) if successor in costs]
    goods_months = cp.load_config(project).construction_goods_months
    bounds = cp.price_impact_bounds(mod_root, vanilla_root)

    files = {
        VALUES: render_values(config, result.buildings, result.rights, result.prices, result.ranks, bounds),
        TRIGGERS: render_triggers(result.buildings, result.rights, result.ranks, goods_months),
        EFFECTS: render_effects(result.buildings, result.rights, costs, result.ranks, result.upgrades),
        SCRIPTED_GUIS: render_scripted_guis(config, result.buildings, result.rights),
        GUI: render_gui(config, result.buildings, result.rights),
        LOC: render_loc(result.buildings, result.rights),
    }
    return result, files


def apply(repo: Path, project: Path, mod_root: Path, vanilla_root: Path, write: bool = True) -> Result:
    result, files = build(repo, project, mod_root, vanilla_root)
    for path, text in files.items():
        if cp._write(mod_root / path, text, write):
            result.files_changed += 1
    return result


def summary(result: Result) -> str:
    """The line ``ppc build`` prints."""
    problems = []
    if result.missing:
        problems.append(f"UNKNOWN buildings: {', '.join(result.missing)}")
    if result.duplicate_lines:
        problems.append(f"listed beside an earlier tier of their line: {', '.join(result.duplicate_lines)}")
    if result.missing_icons:
        problems.append(f"NO ICON (tile left out): {', '.join(result.missing_icons)}")
    if result.unknown_order:
        problems.append(f"rights_order names no right: {', '.join(result.unknown_order)}")
    return (
        f"Construction Plan, Towns and Buildings: {len(result.buildings)} public buildings, {len(result.upgrades)} "
        f"building upgrades, {len(result.rights)} urban "
        f"rights ({len(result.switched_off)} switched off, {len(result.dlc_rights)} DLC-only left out), "
        f"{result.files_changed} files changed" + ("; " + "; ".join(problems) if problems else "") + "."
    )
