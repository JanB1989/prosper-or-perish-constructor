@dataclass(frozen=True)
class Config:
    public_buildings: tuple[str, ...]
    control_pct: int = 50
    control_step: int = 10
    town_population: int = 30
    town_population_step: int = 5
    town_population_min: int = 5
    town_population_max: int = 100
    keep_influence: int = 50
    keep_influence_step: int = 5
    keep_influence_max: int = 100
    rights_order: tuple[str, ...] = ()
    tiles_per_row: int = 11


@dataclass
class Entry:
    """One object of a database folder after the load order: its definition and what was injected into it."""

    bodies: list[str]
    dlc_only: bool  # first defined in a DLC folder: its key must not appear in the mod's script (AGENTS, DLC Content)


@dataclass(frozen=True)
class Right:
    key: str
    potential: tuple[str, ...]  # the potential blocks' bodies (comments stripped), the definition's then the injected ones
    allow: tuple[str, ...]
    specialization: bool
    upgrades_to: str | None
    advances: tuple[str, ...]  # the advances that unlock it (any one of them); none = unlocked from the start
    icon: str  # the texture the tile draws

    @property
    def always_shown(self) -> bool:
        return not self.potential and not self.advances


@dataclass(frozen=True)
class Building:
    key: str  # the configured key: the tile, its toggle variable and its name
    tiers: tuple[str, ...]  # the line, highest tier first (the key itself last)
    icon: str


@dataclass(frozen=True)
class Rank:
    """A location rank the plan upgrades to, as the game's files give it."""

    key: str  # town, city
    variable: str  # the toggle
    source: str  # the rank it is upgraded from
    price: float  # gold, before the construction goods' price factor
    population: float  # the game's own minimum (population >= N in the rank's allow), thousands; 0 = none
    goods: tuple[tuple[str, float], ...]  # the construction goods of its demand (good, amount)


@dataclass
class Result:
    buildings: list[Building] = field(default_factory=list)
    upgrades: list[tuple[str, str]] = field(default_factory=list)  # (older tier, its direct successor), the rule's order
    ranks: list[Rank] = field(default_factory=list)
    rights: list[Right] = field(default_factory=list)
    missing: list[str] = field(default_factory=list)  # configured buildings the game does not have
    duplicate_lines: list[str] = field(default_factory=list)  # configured buildings that are a tier of another one
    missing_icons: list[str] = field(default_factory=list)  # tiles left out because nothing would draw
    switched_off: list[str] = field(default_factory=list)  # rights whose potential or allow is always = no
    dlc_rights: list[str] = field(default_factory=list)  # rights only a DLC folder defines (left out)
    unknown_order: list[str] = field(default_factory=list)  # rights_order keys that are no right
    prices: dict[str, float] = field(default_factory=dict)
    files_changed: int = 0


def load_config(project: Path) -> Config:
    data = tomllib.loads(project.read_text(encoding="utf-8"))[CONFIG_KEY]
    config = Config(
        public_buildings=tuple(data["public_buildings"]),
        control_pct=int(data["control_pct"]),
        control_step=int(data["control_step"]),
        town_population=int(data["town_population"]),
        town_population_step=int(data["town_population_step"]),
        town_population_min=int(data["town_population_min"]),
        town_population_max=int(data["town_population_max"]),
        keep_influence=int(data["keep_influence"]),
        keep_influence_step=int(data["keep_influence_step"]),
        keep_influence_max=int(data["keep_influence_max"]),
        rights_order=tuple(data.get("rights_order", ())),
        tiles_per_row=int(data.get("tiles_per_row", 11)),
    )
    if len(set(config.public_buildings)) != len(config.public_buildings):
        raise ValueError(f"[{CONFIG_KEY}] public_buildings: a key is listed twice")
    if not 0 <= config.control_pct <= 100 or config.control_step < 1:
        raise ValueError(f"[{CONFIG_KEY}] control_pct: 0..100, control_step from 1")
    if not config.town_population_min <= config.town_population <= config.town_population_max:
        raise ValueError(f"[{CONFIG_KEY}] town_population: between town_population_min and town_population_max")
    if not 0 <= config.keep_influence <= config.keep_influence_max:
        raise ValueError(f"[{CONFIG_KEY}] keep_influence: 0..keep_influence_max")
    if config.tiles_per_row < 1:
        raise ValueError(f"[{CONFIG_KEY}] tiles_per_row: from 1")
    return config


