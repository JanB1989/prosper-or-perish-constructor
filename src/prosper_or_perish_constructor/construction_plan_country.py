# reading the game's and the mod's database files (the base game, its DLC folders, then the mod)


def game_files(mod_root: Path, vanilla_root: Path, folder: Path) -> list[tuple[Path, bool]]:
    """The folder's ``*.txt`` files in load order (by name; a later root's file of the same name replaces the earlier
    one), each with whether it comes from a DLC folder."""
    from prosper_or_perish_constructor import building_footprint

    roots = building_footprint.vanilla_game_roots(vanilla_root)
    by_name: dict[str, tuple[Path, bool]] = {}
    for root, dlc in [(roots[0], False), *((root, True) for root in roots[1:]), (mod_root, False)]:
        directory = root / folder
        if directory.is_dir():
            for path in directory.glob("*.txt"):
                by_name[path.name] = (path, dlc)
    return [by_name[name] for name in sorted(by_name)]


def database(mod_root: Path, vanilla_root: Path, folder: Path) -> dict[str, Entry]:
    """name -> its entry after the load order, in database order (where the name was first defined): a later plain,
    ``REPLACE:`` or ``TRY_REPLACE:`` definition replaces the earlier one (and what was injected into it), ``INJECT:`` /
    ``TRY_INJECT:`` adds its body to the standing one."""
    data: dict[str, Entry] = {}
    for path, dlc in game_files(mod_root, vanilla_root, folder):
        for block, body in cp._blocks(path.read_text(encoding="utf-8-sig", errors="replace")):
            mode, _, name = block.rpartition(":")
            standing = data.get(name)
            if mode in INJECT_MODES:
                if standing is not None:
                    standing.bodies.append(body)
                elif mode == "INJECT_OR_CREATE":
                    data[name] = Entry([body], dlc)
                continue
            if mode == "TRY_REPLACE" and standing is None:
                continue
            data[name] = Entry([body], standing.dlc_only if standing is not None else dlc)
    return data


def inner_blocks(body: str, key: str) -> list[str]:
    """The bodies of every ``key = { ... }`` at the top level of a block body, as written."""
    found: list[str] = []
    pattern = re.compile(r"\{|\}|(?<![A-Za-z0-9_:.])" + re.escape(key) + r"\s*=\s*\{")
    depth, index = 0, 0
    while True:
        match = pattern.search(body, index)
        if not match:
            return found
        index = match.end()
        if match.group(0) == "{":
            depth += 1
        elif match.group(0) == "}":
            depth -= 1
        elif depth > 0:
            depth += 1
        else:
            level, end = 1, match.end()
            while end < len(body) and level:
                level += {"{": 1, "}": -1}.get(body[end], 0)
                end += 1
            found.append(body[match.end():end - 1])
            index = end


def top_values(body: str, key: str) -> list[str]:
    """Every ``key = scalar`` at the top level of a block body."""
    found: list[str] = []
    depth = 0
    for token in re.finditer(r"\{|\}|(?<![A-Za-z0-9_:.])([A-Za-z0-9_]+)\s*=\s*([A-Za-z0-9_.\-]+)(?!\s*\{)", body):
        if token.group(0) == "{":
            depth += 1
        elif token.group(0) == "}":
            depth -= 1
        elif depth == 0 and token.group(1) == key:
            found.append(token.group(2))
    return found


def _tokens(text: str) -> str:
    return " ".join(text.split())


def icon_texture(folder: str, name: str, mod_root: Path, vanilla_root: Path) -> str | None:
    """The texture path of an icon the mod or the base game has (DLC folders are not looked at: a path only a DLC
    serves would draw nothing without it)."""
    for root in (mod_root, Path(vanilla_root) / "game"):
        for icons in ICON_ROOTS:
            if (root / icons / folder / f"{name}.dds").is_file():
                return TEXTURE.format(folder=folder, name=name)
    return None


def price_amount(prices: dict[str, Entry], key: str, currency: str) -> float:
    """The amount of one currency in a price of the game's price database (the standing definition and its injects:
    the last line wins)."""
    entry = prices.get(key)
    values = [value for body in (entry.bodies if entry else ()) for value in top_values(body, currency)]
    if not values:
        raise ValueError(f"price {key}: no {currency} amount in {PRICES}")
    return float(values[-1])


def rank_sources(ranks: dict[str, Entry]) -> dict[str, str]:
    """Target rank -> the rank it is upgraded from: its ``upgrade_from``, else the rank listed after it (vanilla's
    file lists the ranks from the highest down: "anything below a rank in the list is worse")."""
    order = list(ranks)
    found: dict[str, str] = {}
    for position, name in enumerate(order):
        named = [value for body in ranks[name].bodies for value in top_values(body, "upgrade_from")]
        if named:
            found[name] = named[-1]
        elif position + 1 < len(order):
            found[name] = order[position + 1]
    return found


def rank_minimum_population(entry: Entry) -> float:
    """The game's own population minimum of a rank: ``population >= N`` in its ``allow`` (the standing definition and
    its injects: the highest counts, every allow block must pass); 0 where it names none."""
    found = [float(value) for body in entry.bodies for block in inner_blocks(body, "allow")
             for value in re.findall(r"(?<![A-Za-z0-9_:.])population\s*>=\s*([0-9.]+)", block)]
    return max(found, default=0.0)


def read_ranks(mod_root: Path, vanilla_root: Path) -> list[Rank]:
    """The town and the city as the game's files give them: the rank below, the gold price (price database), the
    population minimum and the construction goods (the rank's ``construction_demand`` in the goods demand database)."""
    ranks = database(mod_root, vanilla_root, LOCATION_RANKS)
    sources = rank_sources(ranks)
    prices = database(mod_root, vanilla_root, PRICES)
    demands = database(mod_root, vanilla_root, GOODS_DEMAND)
    found: list[Rank] = []
    for key, (variable, price) in RANKS.items():
        if key not in ranks or key not in sources:
            raise ValueError(f"location rank {key}: not in {LOCATION_RANKS}, or nothing to upgrade from")
        named = [value for body in ranks[key].bodies for value in top_values(body, "construction_demand")]
        goods: dict[str, float] = {}
        for body in (demands[named[-1]].bodies if named and named[-1] in demands else ()):
            for good, amount in re.findall(r"(?m)^\s*([A-Za-z0-9_]+)\s*=\s*([0-9.]+)\s*$", body):
                if float(amount) > 0:
                    goods[good] = float(amount)
        found.append(Rank(key=key, variable=variable, source=sources[key], price=price_amount(prices, price, "gold"),
                          population=rank_minimum_population(ranks[key]), goods=tuple(sorted(goods.items()))))
    return found


