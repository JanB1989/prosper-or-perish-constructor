def render_loc(buildings: list[Building], rights: list[Right]) -> str:
    def quote(text: str) -> str:
        return '"' + text.replace('"', '\\"').replace("\n", "\\n") + '"'

    lines = ["\ufeffl_english:", f"  {LOC_HEADER}",
             "  # The Construction Plan window's Towns and Buildings tab (gui/pp_construction_plan_country.gui)"]
    lines += [f"  {key}: {quote(text)}" for key, text in texts(buildings, rights).items()]
    return "\n".join(lines) + "\n"


def name_keys(buildings: list[Building], rights: list[Right]) -> list[str]:
    """The game's localization keys the tiles' names come from (a building's and a town right's name is its key)."""
    return [building.key for building in buildings] + [right.key for right in rights]


def missing_names(keys: list[str], mod_root: Path, vanilla_root: Path) -> list[str]:
    """Keys without an English text in the mod's or the base game's localization (a tile's name would show its key)."""
    wanted = set(keys)
    for root in (mod_root, Path(vanilla_root) / "game"):
        directory = root / LOCALIZATION
        if not directory.is_dir():
            continue
        for path in sorted(directory.rglob("*.yml")):
            text = path.read_text(encoding="utf-8-sig", errors="replace")
            wanted -= set(re.findall(r"(?m)^\s*([A-Za-z0-9_.\-]+):\d*\s*\"", text))
            if not wanted:
                return []
    return sorted(wanted)


