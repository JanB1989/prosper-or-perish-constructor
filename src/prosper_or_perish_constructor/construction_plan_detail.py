def render_loc() -> str:
    def quote(text: str) -> str:
        return '"' + text.replace('"', '\\"').replace("\n", "\\n") + '"'

    lines = ["\ufeffl_english:", f"  {LOC_HEADER}",
             "  # The Construction Plan window's detail panes (gui/pp_construction_plan_detail.gui)"]
    lines += [f"  {key}: {quote(text)}" for key, text in texts().items()]
    return "\n".join(lines) + "\n"


