def _block(head: str, body: list[str]) -> list[str]:
    """``head = { body }``; ``type x = base {``, ``block "x" {``, ``blockoverride "x" {`` and ``types X`` take no
    ``=`` of their own."""
    word = head.split(" ", 1)[0]
    if not body and word != "types":
        return [f"{head} {{}}" if word in ("block", "blockoverride") else f"{head} = {{}}"]
    if word == "types":
        opener = [head, "{"]
    elif word in ("type", "block", "blockoverride"):
        opener = [f"{head} {{"]
    else:
        opener = [f"{head} = {{"]
    return [*opener, *(f"\t{line}" if line else line for line in body), "}"]


def _line(key: str, visible: str | None = None, kind: str = "pp_cplan_d_line") -> list[str]:
    return _block(kind, ([f'visible = "[{visible}]"'] if visible else []) + [f'text = "{key}"'])


def _button(group: str) -> list[str]:
    shown = f"GetVariableSystem.HasValue('pp_cplan_detail', '{group}')"
    closed = _block("button_automation_shortcut", [
        f'visible = "[{_not(shown)}]"',
        "parentanchor = center",
        "size = { 24 24 }",
        *_block("action_tooltip", [
            'title = "PP_CPLAN_D_SHOW"',
            f"on_action = \"[GetVariableSystem.Set('pp_cplan_detail', '{group}')]\"",
        ]),
    ])
    opened = _block("button_automation_shortcut", [
        f'visible = "[{shown}]"',
        "parentanchor = center",
        "size = { 24 24 }",
        "# open: vanilla's selected colour (its sort buttons)",
        *_block('blockoverride "bg_button_color"', ["using = color_sortby_on"]),
        *_block("action_tooltip", [
            'title = "PP_CPLAN_D_HIDE"',
            "on_action = \"[GetVariableSystem.Clear('pp_cplan_detail')]\"",
        ]),
    ])
    return [f"# the {group} group's cog: opens its pane, or closes it while open",
            *_block(f"type pp_cplan_detail_button_{group} = widget", ["size = { 26 26 }", *closed, *opened])]


def _header(group: str) -> list[str]:
    close = _block("button_close_alt", [
        "size = { 22 22 }",
        *_block('blockoverride "close_properties"', []),
        *_block('blockoverride "close_inputaction"', []),
        *_block('blockoverride "close_title"', ['title = "PP_CPLAN_D_HIDE"']),
        *_block('blockoverride "close_on_action"', ["on_action = \"[GetVariableSystem.Clear('pp_cplan_detail')]\""]),
    ])
    return _block("hbox", [
        "layoutpolicy_horizontal = expanding",
        "spacing = 6",
        f'pp_cplan_title = {{ text = "PP_CPLAN_D_TITLE_{group.upper()}" tooltip = "{rule_tooltip(group)}" }}',
        "expand = {}",
        *close,
    ])


def _situation(group: str) -> list[str]:
    d = detail_value
    if group == "food":
        return _line("PP_CPLAN_D_FOOD_SIT") + _line("PP_CPLAN_D_FOOD_SIT_2")
    if group in ("logistics", "improve"):
        count = _country(d(group, "below" if group == "logistics" else "over"))
        key = group.upper()
        return (_line(f"PP_CPLAN_D_{key}_SIT", _above(count))
                + _line(f"PP_CPLAN_D_{key}_NONE", _not(_above(count))))
    if group == "business":
        sites = _country(d(group, "sites"))
        # the quickest payback is kept only over the sites within the line (a running minimum); a month the group
        # started without gold it did not look, and says so instead of "no business pays back"
        return (_line("PP_CPLAN_D_BUSINESS_SIT", _above(sites))
                + _line("PP_CPLAN_D_BUSINESS_NONE", _both(_not(_above(sites)), _not(_skipped())))
                + _line("PP_CPLAN_D_BUSINESS_SKIPPED", _skipped()))
    if group != "profiles":
        return []  # towns and buildings: the gold lines are enough
    # profiles: the rules by state, three to a row
    out = _line("PP_CPLAN_D_PROFILES_SIT")
    states = list(PROFILE_STATES)
    for start in range(0, len(states), 3):
        cells = [f'pp_cplan_d_cell = {{ text = "PP_CPLAN_D_PROFILES_ST{state}" tooltip = "PP_LPROF_ST_{state}" }}'
                 for state in states[start:start + 3]]
        out += _block("hbox", ["layoutpolicy_horizontal = expanding", "spacing = 4", *cells, "expand = {}"])
    return out


def _chart(group: str) -> list[str]:
    tooltip = f"PP_CPLAN_D_CHART_TT_{group.upper()}"
    columns: list[str] = []
    for month in range(cp.HISTORY_MONTHS, 0, -1):  # the oldest left, last month right
        need = history_value(group, "needp", month)
        spent = history_value(group, "spentp", month)
        columns += _block("pp_cplan_d_column", [
            f'tooltip = "{tooltip}"',
            *_block('blockoverride "pp_cplan_d_need"', [f'value = "[FixedPointToFloat({_country(need)})]"']),
            *_block('blockoverride "pp_cplan_d_spent"', [f'value = "[FixedPointToFloat({_country(spent)})]"']),
        ])
    axis = _block("hbox", [
        "layoutpolicy_horizontal = expanding",
        'pp_cplan_label = { text = "PP_CPLAN_D_YEAR_AGO" default_format = "#weak" }',
        "expand = {}",
        'pp_cplan_label = { text = "PP_CPLAN_D_LAST_MONTH" default_format = "#weak" }',
    ])
    legend: list[str] = ["spacing = 4"]
    for kind in ("need", "spent"):
        label = f'pp_cplan_label = {{ text = "PP_CPLAN_D_SUM_{kind.upper()}_{group.upper()}" tooltip = "{tooltip}" }}'
        legend += _block("hbox", ["spacing = 6", f"pp_cplan_d_swatch_{kind} = {{}}", label])
    legend = _block("vbox", legend)
    return _block("hbox", [
        "layoutpolicy_horizontal = expanding",
        "spacing = 16",
        *_block("vbox", ["spacing = 2", *_block("hbox", [f"spacing = {COLUMN_SPACING}", *columns]), *axis]),
        *legend,
        "expand = {}",
    ])


def log_value(group: str, name: str) -> str:
    """A list item's number (location scope): what the rule group left there in the last pass (``name``: cost, val,
    step; script values pp_cplan_log_<name>_<why>_n over the location's pp_cplan_log_<name>_<why>)."""
    return _item(f"pp_cplan_log_{name}_{cp.GROUP_WHY[group]}_n")


def _names(group: str) -> list[str]:
    """The buildings the rule group started in the item's location (its own list: a location with two construction
    slots can hold another group's construction of the same pass). Towns and Buildings: a town or city upgrade is no
    building, so the list is empty then and takes no room (step 2 is left only where the group built nothing else)."""
    hidden = [f'visible = "[{_not(_equals(log_value(group, "step"), 2))}]"'] if group == "country" else []
    return _block("flowcontainer", [
        *hidden,
        "direction = horizontal",
        f"datamodel = \"[Scope.GetList('pp_cplan_log_types_{cp.GROUP_WHY[group]}')]\"",
        "spacing = 4",
        *_block("item", ['pp_cplan_label = { raw_text = "[Scope.GetBuildingType.GetName]" }']),
    ])


def _row(group: str, tail: list[str]) -> list[str]:
    """One line of a list: the group's buildings in the location (and its town or city upgrade), the location, then
    ``tail``."""
    return _block("flowcontainer", [
        "direction = horizontal",
        "ignoreinvisible = yes",
        "spacing = 4",
        "margin = { 2 1 }",
        *_names(group),
        *(_block(RANK_UPGRADE, []) if group == "country" else []),
        'pp_cplan_label = { text = "PP_CPLAN_IN_LOCATION" }',
        *tail,
    ])


def _list(group: str) -> list[str]:
    why = cp.GROUP_WHY[group]
    reasons: list[str] = []
    step = log_value(group, "step")

    def label(key: str, visible: str | None = None) -> list[str]:
        return _block("pp_cplan_label", ([f'visible = "[{visible}]"'] if visible else []) + [f'text = "{key}"'])

    if group == "food":
        for n in FOOD_STEPS:
            reasons += label(f"PP_CPLAN_D_FOOD_WHY_{n}", _equals(step, n))
    elif group == "profiles":
        # a rule of the location's profile (step = its number) or one of the location's marks (step 0)
        reasons += label("PP_CPLAN_D_PROFILES_WHY", _above(step))
        reasons += label("PP_CPLAN_D_PROFILES_WHY_MARK", _not(_above(step)))
    elif group == "country":
        for n in COUNTRY_KINDS:
            reasons += label(f"PP_CPLAN_D_COUNTRY_WHY_{n}", _equals(step, n))
    else:
        reasons.append(f'pp_cplan_label = {{ text = "PP_CPLAN_D_{group.upper()}_WHY" }}')
    row = _row(group, [f'pp_cplan_label = {{ text = "PP_CPLAN_D_COST_{group.upper()}" }}', *reasons])
    return _block("scrollarea", [
        "layoutpolicy_horizontal = expanding",
        "layoutpolicy_vertical = expanding",
        "scrollbarpolicy_horizontal = always_off",
        "scrollbar_vertical = { using = Scrollbar_Vertical }",
        *_block("scrollwidget", _block("flowcontainer", [
            "direction = vertical",
            f"datamodel = \"[GetPlayer.MakeScope.GetList('pp_cplan_log_{why}')]\"",
            *_block("item", row),
        ])),
    ])


def _last_list() -> list[str]:
    """The window's "Last month" list: every construction of the last pass, a line per rule group and location (the
    groups in the window's order), each with its group's name."""
    groups: list[str] = []
    for group in cp.GROUPS:
        groups += _block("flowcontainer", [
            "direction = vertical",
            f"datamodel = \"[GetPlayer.MakeScope.GetList('pp_cplan_log_{cp.GROUP_WHY[group]}')]\"",
            *_block("item", _row(group, [f'pp_cplan_label = {{ text = "{LAST_WHY[group]}" }}'])),
        ])
    return ["# the window's \"Last month\" list: what the last pass built, a line per rule group and location",
            *_block(f"type {LAST_LIST} = scrollarea", [
                "layoutpolicy_horizontal = expanding",
                "layoutpolicy_vertical = expanding",
                "scrollbarpolicy_horizontal = always_off",
                "scrollbar_vertical = { using = Scrollbar_Vertical }",
                *_block("scrollwidget", _block("flowcontainer", ["direction = vertical", *groups])),
            ])]


def _pane(group: str) -> list[str]:
    d = detail_value
    ran = _above(_country(d(group, "ran")))
    waited = _above(_country(d(group, "waitn")))
    started = _above(_country(d(group, "started")))
    off = {"profiles": "PP_CPLAN_D_OFF_PROFILES", "country": "PP_CPLAN_D_OFF_COUNTRY"}.get(group, "PP_CPLAN_D_OFF")
    # "nothing waited for gold" only where the group looked (the business group does not without gold)
    quiet = _both(_not(waited), _not(_skipped())) if group == "business" else _not(waited)
    # what it saves for (the first thing of the pass it could not pay for): a building, or for Towns and Buildings a
    # town or city upgrade (pp_cplan_save_rank_107 - 100 = SAVE_RANKS)
    why = cp.GROUP_WHY[group]
    saves = _above(_country(f"pp_cplan_saves_{why}"))
    rank = _country(f"pp_cplan_save_rank_n_{why}")
    saving = _line(f"PP_CPLAN_D_SAVE_{group.upper()}", _both(saves, _not(_above(rank))) if group == "country" else saves)
    if group == "country":
        for number in SAVE_RANKS:
            saving += _line(f"PP_CPLAN_D_SAVE_RANK_{number}", _both(saves, _equals(rank, number)))
    # things it wanted that were stopped for another reason than gold, in plain words (shown only when there are any)
    # (the Locations group shows both among its rule states: 8 and 10)
    held = [] if group == "profiles" else _line(f"PP_CPLAN_D_GOODS_{group.upper()}", _above(_country(d(group, "goods"))))
    if group == "business":
        held += _line("PP_CPLAN_D_LIMITED_BUSINESS", _above(_country(d(group, "limited"))))
    shown = _block("vbox", [
        f'visible = "[{ran}]"',
        "layoutpolicy_horizontal = expanding",
        "layoutpolicy_vertical = expanding",
        "ignoreinvisible = yes",
        "spacing = 6",
        *_line(f"PP_CPLAN_D_GOLD_{group.upper()}"),
        *_line(f"PP_CPLAN_D_WAIT_{group.upper()}", waited),
        *_line("PP_CPLAN_D_NO_WAIT", quiet),
        *saving,
        *held,
        *_situation(group),
        *_chart(group),
        *_block("hbox", ["layoutpolicy_horizontal = expanding",
                         'pp_cplan_title = { text = "PP_CPLAN_D_BUILT" }', "expand = {}"]),
        *_line("PP_CPLAN_D_NOTHING", _not(started)),
        *_list(group),
    ])
    return [f"# the {group} group's pane (its construction code {cp.GROUP_WHY[group]})",
            *_block(f"type pp_cplan_detail_{group} = vbox", [
                "layoutpolicy_horizontal = expanding",
                "layoutpolicy_vertical = expanding",
                "ignoreinvisible = yes",
                "spacing = 6",
                *_header(group),
                *_line(off, _not(ran)),
                *shown,
                f'expand = {{ visible = "[{_not(ran)}]" }}',
            ])]


