"""Construction Plan detail panes (Jan 2026-11-09: "we don't know how much investment is missing given the current
settings, why something was built ... a little cog symbol you can click, and there you see what's happening under the
hood ... and what was actually built. Maybe some graph. A really minimalistic, clean solution.").

Each rule group row of the window's Global Settings tab (``pp_construction_plan.gui``) ends in a cog
(``pp_cplan_detail_button_<group>``, vanilla's ``button_automation_shortcut``). It sets the GUI variable
``pp_cplan_detail`` to the group, and the group's pane (``pp_cplan_detail_<group>``) takes the place of the window's
"Last month" list: what the group could spend, wanted and spent in the last pass, what waited for gold, its situation
(the numbers its rule reads), the last ``HISTORY_MONTHS`` passes as a chart (grey: wanted, gold: spent, both against the
largest month), and what it built, where, for how much and why. The cog of the open pane (gold) and the pane's close
button clear the variable.

Every number is a script value the monthly pass leaves behind (``pp_construction_plan*.txt``, the script side):
country ``pp_cplan_d_<group>_*`` (the last pass), ``pp_cplan_h_<group>_*`` (the history), location
``pp_cplan_log_*_n`` (the list items, the locations of the list ``pp_cplan_log_<why>``). The rules never read any of
it. ``construction_plan.apply`` writes the two files below (``render_gui``, ``render_loc``).
"""

