# ---- names and data functions ----------------------------------------------------------------------------------


def rule_tooltip(group: str) -> str:
    return f"PP_CPLAN_{group.upper()}_RULE_TT"


def detail_value(group: str, name: str) -> str:
    return f"pp_cplan_d_{group}_{name}"


def history_value(group: str, name: str, month: int | None = None) -> str:
    return f"pp_cplan_h_{group}_{name}" + ("" if month is None else f"_{month}")


def _country(name: str) -> str:
    return f"GetPlayer.MakeScope.ScriptValue('{name}')"


def _var(name: str) -> str:
    """A variable of the player's country (a scope it holds: .GetLocation, .GetBuildingType; .IsSet)."""
    return f"GetPlayer.MakeScope.Var('{name}')"


def _item(name: str) -> str:
    return f"Scope.ScriptValue('{name}')"


def _above(value: str, limit: float = 0.5) -> str:
    return f"GreaterThan_CFixedPoint({value}, '(CFixedPoint){limit:g}')"


def _not(condition: str) -> str:
    return f"Not({condition})"


def _equals(value: str, number: int) -> str:
    return f"EqualTo_CFixedPoint({value}, '(CFixedPoint){number}')"


def _both(first: str, second: str) -> str:
    return f"And({first}, {second})"


def _either(first: str, second: str) -> str:
    return f"Or({first}, {second})"


def _show(name: str, digits: int = 0) -> str:
    return f"[{_country(name)}|{digits}]"


def _skipped() -> str:
    """The business group started without gold last month and did not look for businesses."""
    return _above(_country(detail_value("business", "skipped")))


def _ago() -> str:
    return "a year ago" if cp.HISTORY_MONTHS == 12 else f"{cp.HISTORY_MONTHS} months ago"


