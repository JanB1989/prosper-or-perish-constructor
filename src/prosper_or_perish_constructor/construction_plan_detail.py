def _bar(texture: str, block: str) -> list[str]:
    return [
        "size = { 100% 100% }",
        "direction = vertical",
        "texture_density = 2",
        "spriteType = corneredstretched",
        "spriteborder = { 0 12 }",
        "min = 0",
        "max = 100",
        *_block(f'block "{block}"', ["value = 0"]),
        f'progresstexture = "{texture}"',
        f'noprogresstexture = "{TRANSPARENT}"',
    ]


def render_gui() -> str:
    """The cogs and the panes, one each per rule group (cp.GROUPS)."""
    body = _shared_types()
    for group in cp.GROUPS:
        body += ["", *_button(group), "", *_pane(group)]
    out = [
        cp.HEADER.rstrip("\n"),
        "# The Construction Plan window's detail panes (construction_plan_detail.py; Jan 2026-11-09: what each",
        "# rule group did under the hood). Per rule group a cog for its row (pp_cplan_detail_button_<group>) and a",
        "# pane (pp_cplan_detail_<group>) that the window shows instead of its \"Last month\" list while the GUI",
        "# variable pp_cplan_detail = <group>: the gold it had, wanted and spent, what waited for gold, the situation",
        f"# its rule read, the last {cp.HISTORY_MONTHS} months (grey wanted, gold spent) and what it built and why.",
        "# Every number is a script value the monthly pass leaves (pp_cplan_d_*, pp_cplan_h_*, the list items'",
        "# pp_cplan_log_*_n).",
        "",
        *_block("types PPConstructionPlanDetail", body),
    ]
    return "\n".join(out) + "\n"
