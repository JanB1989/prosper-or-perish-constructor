def _province_allowed(province: Mapping[str, Any], rule: BuildingRule) -> bool:
    rural_share = float(province.get("rural_population_share") or 0.0)
    urban_share = float(province.get("urban_population_share") or 0.0)
    peasant_share = float(province.get("peasant_population_share") or 0.0)
    development_per_1000 = float(province.get("development_per_1000_population") or 0.0)
    if rural_share < rule.min_province_rural_population_share:
        return False
    if rule.max_province_rural_population_share is not None and rural_share > rule.max_province_rural_population_share:
        return False
    if urban_share < rule.min_province_urban_population_share:
        return False
    if rule.max_province_urban_population_share is not None and urban_share > rule.max_province_urban_population_share:
        return False
    if rule.max_province_peasant_population_share is not None and peasant_share > rule.max_province_peasant_population_share:
        return False
    if development_per_1000 < rule.min_province_development_per_1000_population:
        return False
    raw_materials = {str(item) for item in (province.get("raw_materials") or []) if item is not None}
    if rule.required_province_raw_materials and raw_materials.isdisjoint(rule.required_province_raw_materials):
        return False
    return True


def _target_base(province: Mapping[str, Any], rule: BuildingRule) -> float:
    if rule.target_basis == "consumption":
        return float(province.get("food_consumption") or 0.0)
    if rule.target_basis == "shortfall":
        return float(province.get("food_shortfall") or 0.0)
    if rule.target_basis == "negative_balance":
        return max(-float(province.get("food_balance") or 0.0), 0.0)
    raise FoodStartupError(f"unsupported target basis {rule.target_basis!r} for {rule.key}")


def _province_target_scale(province: Mapping[str, Any], rule: BuildingRule) -> float:
    scale = 1.0
    peasant_share = float(province.get("peasant_population_share") or 0.0)
    development_per_1000 = float(province.get("development_per_1000_population") or 0.0)
    scale *= _falling_scale(
        peasant_share,
        start=rule.peasant_share_scale_start,
        end=rule.peasant_share_scale_end,
        floor=rule.target_scale_min,
    )
    scale *= _rising_scale(
        development_per_1000,
        start=rule.development_per_1000_scale_end,
        end=rule.development_per_1000_scale_start,
        floor=rule.target_scale_min,
    )
    return max(rule.target_scale_min, min(1.0, scale))


def _falling_scale(value: float, *, start: float | None, end: float | None, floor: float) -> float:
    if start is None or end is None:
        return 1.0
    if value <= start:
        return 1.0
    if value >= end:
        return floor
    span = end - start
    if span <= 0.0:
        return floor
    progress = (value - start) / span
    return 1.0 - progress * (1.0 - floor)


def _rising_scale(value: float, *, start: float | None, end: float | None, floor: float) -> float:
    if start is None or end is None:
        return 1.0
    if value <= start:
        return floor
    if value >= end:
        return 1.0
    span = end - start
    if span <= 0.0:
        return floor
    progress = (value - start) / span
    return floor + progress * (1.0 - floor)


def _allocate_locations(
    locations: Sequence[Mapping[str, Any]],
    rule: BuildingRule,
    levels_needed: int,
    remaining_peasants_by_location: dict[str, float],
    employment_size: float,
    existing_levels: Mapping[tuple[str, str], float],
) -> list[tuple[Mapping[str, Any], int, float]]:
    candidates = _candidate_locations(locations, rule)
    if not candidates or employment_size <= 0.0:
        return []
    remaining = levels_needed
    result: list[tuple[Mapping[str, Any], int, float]] = []
    for candidate in candidates:
        if remaining <= 0:
            break
        slug = str(candidate["slug"])
        existing = int(math.floor(existing_levels.get((slug, rule.key), 0.0)))
        location_capacity = max(rule.max_levels_per_location - existing, 0)
        if location_capacity <= 0:
            continue
        available_peasants = remaining_peasants_by_location.get(slug, 0.0)
        staffed_capacity = _staffable_startup_levels(available_peasants, employment_size)
        if staffed_capacity <= 0:
            continue
        levels = min(location_capacity, remaining, staffed_capacity)
        if levels <= 0:
            continue
        result.append((candidate, levels, available_peasants))
        remaining_peasants_by_location[slug] = max(available_peasants - levels * employment_size, 0.0)
        remaining -= levels
    return result


def _candidate_locations(
    locations: Sequence[Mapping[str, Any]],
    rule: BuildingRule,
) -> list[Mapping[str, Any]]:
    candidates = [location for location in locations if _location_allowed(location, rule)]
    if rule.placement == "province_capital":
        capital_candidates = [location for location in candidates if bool(location.get("province_capital"))]
        candidates = capital_candidates or candidates
    elif rule.placement not in {"highest_population", "highest_development", "score"}:
        raise FoodStartupError(f"unsupported placement mode {rule.placement!r} for {rule.key}")

    if rule.placement == "highest_population":
        return sorted(candidates, key=lambda row: (float(row.get("total_population") or 0.0), _score(row, rule)), reverse=True)
    if rule.placement == "highest_development":
        return sorted(candidates, key=lambda row: (float(row.get("development") or 0.0), _score(row, rule)), reverse=True)
    return sorted(candidates, key=lambda row: _score(row, rule), reverse=True)


def _location_allowed(location: Mapping[str, Any], rule: BuildingRule) -> bool:
    if location.get("owner") is None and location.get("owner_country_id") is None:
        return False
    rank = str(location.get("location_rank") or location.get("rank") or "")
    if rule.allowed_ranks and rank not in rule.allowed_ranks:
        return False
    checks = (
        (rule.allowed_regions, "region"),
        (rule.allowed_macro_regions, "macro_region"),
        (rule.allowed_super_regions, "super_region"),
        (rule.allowed_country_tags, "country_tag"),
    )
    for allowed, column in checks:
        if allowed and str(location.get(column) or "") not in allowed:
            return False
    raw_material = str(location.get("raw_material") or "")
    if rule.required_raw_materials and raw_material not in rule.required_raw_materials:
        return False
    if rule.excluded_raw_materials and raw_material in rule.excluded_raw_materials:
        return False
    if float(location.get("total_population") or 0.0) < rule.min_location_population:
        return False
    if float(location.get("development") or 0.0) < rule.min_location_development:
        return False
    return True


def _score(location: Mapping[str, Any], rule: BuildingRule) -> float:
    return (
        float(location.get("total_population") or 0.0) * rule.score.population
        + float(location.get("development") or 0.0) * rule.score.development
        + (rule.score.province_capital_bonus if bool(location.get("province_capital")) else 0.0)
    )


def _summary(
    locations: pl.DataFrame,
    provinces: pl.DataFrame,
    plan: pl.DataFrame,
    building_outputs: pl.DataFrame,
) -> dict[str, Any]:
    plan_by_building = []
    plan_by_coverage_group = []
    plan_by_startup_source = []
    if not plan.is_empty():
        plan_by_building = (
            plan.group_by("building")
            .agg(
                [
                    pl.col("levels").sum().alias("levels"),
                    pl.col("estimated_food_added").sum().alias("estimated_food_added"),
                    pl.col("worker_peasant_requirement").sum().alias("worker_peasant_requirement"),
                    pl.len().alias("placements"),
                ]
            )
            .sort("building")
            .to_dicts()
        )
        plan_by_coverage_group = (
            plan.group_by("coverage_group")
            .agg(
                [
                    pl.col("levels").sum().alias("levels"),
                    pl.col("estimated_food_added").sum().alias("estimated_food_added"),
                    pl.col("worker_peasant_requirement").sum().alias("worker_peasant_requirement"),
                    pl.len().alias("placements"),
                ]
            )
            .sort("coverage_group")
            .to_dicts()
        )
        if "startup_source" in plan.columns:
            plan_by_startup_source = (
                plan.group_by("startup_source")
                .agg(
                    [
                        pl.col("levels").sum().alias("levels"),
                        pl.col("estimated_food_added").sum().alias("estimated_food_added"),
                        pl.col("worker_peasant_requirement").sum().alias("worker_peasant_requirement"),
                        pl.len().alias("placements"),
                    ]
                )
                .sort("startup_source")
                .to_dicts()
            )
    return {
        "locations": locations.height,
        "provinces": provinces.height,
        "total_population": float(locations["total_population"].sum() or 0.0),
        "total_food_consumption": float(locations["food_consumption"].sum() or 0.0),
        "total_food_production": float(locations["food_production"].sum() or 0.0),
        "total_food_balance": float(locations["food_balance"].sum() or 0.0),
        "planned_levels": int(plan["levels"].sum()) if not plan.is_empty() else 0,
        "planned_estimated_food": float(plan["estimated_food_added"].sum()) if not plan.is_empty() else 0.0,
        "planned_worker_peasant_requirement": float(plan["worker_peasant_requirement"].sum()) if not plan.is_empty() else 0.0,
        "plan_by_building": plan_by_building,
        "plan_by_coverage_group": plan_by_coverage_group,
        "plan_by_startup_source": plan_by_startup_source,
        "building_outputs": building_outputs.to_dicts(),
    }


