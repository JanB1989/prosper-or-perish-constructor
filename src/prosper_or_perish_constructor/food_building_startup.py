def plan_compiler_startup_buildings(
    locations: pl.DataFrame,
    buildings: pl.DataFrame,
    *,
    existing_levels: Mapping[tuple[str, str], float] | None = None,
    remaining_peasants_by_location: dict[str, float] | None = None,
) -> pl.DataFrame:
    _require_columns(
        locations,
        {
            "location_id",
            "slug",
            "province",
            "development",
            "total_population",
            "raw_material",
            "population_peasants",
            "location_rank",
        },
    )
    _require_columns(buildings, {"name", "pop_type", "employment_size"})
    existing_levels = existing_levels or {}
    if remaining_peasants_by_location is None:
        remaining_peasants_by_location = _initial_remaining_peasants(locations)
    building_metadata = _building_worker_metadata(buildings)
    desired: dict[tuple[str, str], dict[str, Any]] = {}
    location_rows = locations.filter(pl.col("province").is_not_null()).to_dicts()

    for location in location_rows:
        for rule in _compiler_startup_rules():
            if not _compiler_startup_location_allowed(location, rule):
                continue
            slug = str(location["slug"])
            existing = int(math.floor(existing_levels.get((slug, rule.building), 0.0)))
            planned = desired.get((slug, rule.building))
            if planned is None or rule.target_level > int(planned["target_level"]):
                desired[(slug, rule.building)] = {
                    "location": location,
                    "rule": rule,
                    "existing_levels": existing,
                    "target_level": rule.target_level,
                }
            elif rule.target_level == int(planned["target_level"]) and rule.order < int(planned["rule"].order):
                planned["rule"] = rule

    rows: list[dict[str, object]] = []
    for (slug, building), item in sorted(
        desired.items(),
        key=lambda pair: (
            int(pair[1]["rule"].order),
            str(pair[1]["location"].get("province") or ""),
            str(pair[0][0]),
            str(pair[0][1]),
        ),
    ):
        rule = item["rule"]
        location = item["location"]
        existing = int(item["existing_levels"])
        target_level = int(item["target_level"])
        levels_needed = max(target_level - existing, 0)
        if levels_needed <= 0:
            continue
        worker_pop_type, employment_size = building_metadata.get(building, ("", 0.0))
        if not worker_pop_type or employment_size <= 0.0:
            raise FoodStartupError(f"missing parser employment metadata for startup building {building!r}")
        available_peasants = remaining_peasants_by_location.get(slug, 0.0)
        staffed_levels = _staffable_startup_levels(available_peasants, employment_size)
        levels = min(levels_needed, staffed_levels)
        if levels <= 0:
            continue
        worker_peasant_requirement = levels * employment_size
        remaining_peasants_by_location[slug] = max(available_peasants - worker_peasant_requirement, 0.0)
        rows.append(
            {
                "building": building,
                "coverage_group": "compiler_startup",
                "province": _province_key(location["province"]),
                "location_id": int(location["location_id"]),
                "location_slug": slug,
                "levels": int(levels),
                "worker_pop_type": worker_pop_type,
                "employment_size": employment_size,
                "worker_peasant_requirement": worker_peasant_requirement,
                "available_peasants_before": available_peasants,
                "remaining_peasants_after": remaining_peasants_by_location[slug],
                "food_per_level": 0.0,
                "estimated_food_added": 0.0,
                "province_food_consumption": 0.0,
                "province_food_production": 0.0,
                "province_food_balance": 0.0,
                "province_food_shortfall": 0.0,
                "target_basis": rule.source,
                "target_base": float(target_level),
                "target_scale": 1.0,
                "target_food": 0.0,
                "needed_food_before": 0.0,
                "placement": "compiler_startup",
                "province_capital": bool(location.get("province_capital")),
                "location_rank": str(location.get("location_rank") or location.get("rank") or ""),
                "total_population": float(location.get("total_population") or 0.0),
                "development": float(location.get("development") or 0.0),
                "region": str(location.get("region") or ""),
                "macro_region": str(location.get("macro_region") or ""),
                "super_region": str(location.get("super_region") or ""),
                "country_tag": str(location.get("country_tag") or ""),
                "raw_material": str(location.get("raw_material") or ""),
                "province_rural_population_share": 0.0,
                "province_urban_population_share": 0.0,
                "province_peasant_population_share": 0.0,
                "province_development_per_1000_population": 0.0,
                "startup_source": rule.source,
                "startup_order": rule.order,
                "existing_levels": float(existing),
                "target_level": int(target_level),
                "startup_constructible": bool(location.get("startup_constructible_owner", True)),
            }
        )
    return _filter_startup_constructible_rows(
        pl.DataFrame(rows, schema=_startup_plan_schema()).sort(["building", "province", "location_slug"])
    )


