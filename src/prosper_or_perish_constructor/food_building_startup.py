    owners = _load_start_location_owners(config)
    frame = locations.join(population, on="slug", how="left").join(owners, on="slug", how="left")
    population_columns = [column for column in frame.columns if column.startswith(POPULATION_PREFIX)]
    if "population_peasants" not in population_columns:
        frame = frame.with_columns(pl.lit(0.0).alias("population_peasants"))
        population_columns.append("population_peasants")
    if "population_unknown" not in population_columns:
        frame = frame.with_columns(pl.lit(0.0).alias("population_unknown"))
        population_columns.append("population_unknown")
    frame = frame.with_columns(
        [pl.col(column).fill_null(0.0).cast(pl.Float64).alias(column) for column in sorted(set(population_columns))]
    )
    population_columns = [column for column in frame.columns if column.startswith(POPULATION_PREFIX)]
    return frame.with_columns(
        [
            pl.sum_horizontal([pl.col(column) for column in population_columns]).alias("total_population"),
            pl.col("population_peasants").alias("unemployed_peasants"),
        ]
    )


