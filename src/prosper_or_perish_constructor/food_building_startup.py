def _compiler_startup_location_allowed(location: Mapping[str, Any], rule: CompilerStartupRule) -> bool:
    if location.get("owner") is None and location.get("owner_country_id") is None:
        return False
    rank = str(location.get("location_rank") or location.get("rank") or "")
    if rule.allowed_ranks and rank not in rule.allowed_ranks:
        return False
    raw_material = str(location.get("raw_material") or "")
    if rule.raw_materials and raw_material not in rule.raw_materials:
        return False
    if rule.province_capital is not None and bool(location.get("province_capital")) != rule.province_capital:
        return False
    if rule.coastal is not None and _as_bool(location.get("is_coastal")) != rule.coastal:
        return False
    if rule.min_population is not None and not _compare_threshold(
        float(location.get("total_population") or 0.0),
        rule.population_operator,
        rule.min_population,
    ):
        return False
    if rule.min_development is not None and not _compare_threshold(
        float(location.get("development") or 0.0),
        rule.development_operator,
        rule.min_development,
    ):
        return False
    if rule.potential is not None and not _location_matches_compiler_potential(location, rule.potential):
        return False
    return True


def _location_matches_compiler_potential(location: Mapping[str, Any], potential: str) -> bool:
    if potential == "granary_startup":
        rank = str(location.get("location_rank") or location.get("rank") or "")
        population = float(location.get("total_population") or 0.0)
        return (
            (rank == "city" and population > 50.0)
            or (rank == "town" and population > 100.0)
            or (rank == "rural_settlement" and population > 300.0)
        )
    if potential == "salt_mine":
        return _salt_mine_potential(location)
    if potential == "inland_saltworks":
        return not _salt_mine_potential(location)
    raise FoodStartupError(f"unsupported compiler startup potential {potential!r}")


def _salt_mine_potential(location: Mapping[str, Any]) -> bool:
    slug = str(location.get("slug") or "")
    if slug in {
        "wieliczka",
        "khewra",
        "dina",
        "khushab",
        "dinkot",
        "cardona",
        "hallein",
        "salzburg",
        "chicaquicha",
    }:
        return True
    if slug in {"salins_les_bains", "moutiers", "anana", "hall"}:
        return False
    if str(location.get("region") or "") in {
        "south_china_region",
        "west_china_region",
        "tibet_region",
        "xinjiang_region",
    }:
        return False
    return (
        str(location.get("topography") or "") in {"hills", "mountains", "plateau"}
        and str(location.get("climate") or "") in {"continental", "oceanic", "mediterranean"}
        and str(location.get("vegetation") or "") in {"forest", "woods", "grasslands", "farmland"}
    )


def _compare_threshold(value: float, operator: str, threshold: float) -> bool:
    if operator == ">":
        return value > threshold
    if operator == ">=":
        return value >= threshold
    raise FoodStartupError(f"unsupported compiler startup threshold operator {operator!r}")


def _as_bool(value: object) -> bool:
    if isinstance(value, bool):
        return value
    if value is None:
        return False
    if isinstance(value, str):
        return value.lower() in {"yes", "true", "1"}
    return bool(value)


