def _load_start_population(config: FoodStartupConfig) -> pl.DataFrame:
    from eu5gameparser.clausewitz.parser import parse_file
    from eu5gameparser.clausewitz.syntax import CList

    rows_by_slug: dict[str, dict[str, float]] = {}
    for path in _setup_start_files(config, "06_pops.txt"):
        document = parse_file(path)
        for locations in document.values("locations"):
            if not isinstance(locations, CList):
                continue
            for location in locations.entries:
                if not isinstance(location.value, CList):
                    continue
                amounts: dict[str, float] = {}
                for pop in location.value.values("define_pop"):
                    if not isinstance(pop, CList):
                        continue
                    pop_type = _pop_type_name(pop.first("type"))
                    if not pop_type:
                        continue
                    amounts[pop_type] = amounts.get(pop_type, 0.0) + _numeric(pop.first("size"))
                rows_by_slug[str(location.key)] = amounts
    columns = {"slug": pl.String, "population_peasants": pl.Float64}
    for amounts in rows_by_slug.values():
        for pop_type in amounts:
            columns[f"population_{pop_type}"] = pl.Float64
    rows = [
        {"slug": slug, **{f"population_{pop_type}": amount for pop_type, amount in amounts.items()}}
        for slug, amounts in sorted(rows_by_slug.items())
    ]
    if not rows:
        return pl.DataFrame(schema=columns)
    return pl.DataFrame(rows, schema=columns).with_columns(
        [pl.col(column).fill_null(0.0).alias(column) for column in columns if column != "slug"]
    )


def _load_start_location_owners(config: FoodStartupConfig) -> pl.DataFrame:
    from eu5gameparser.clausewitz.parser import parse_file
    from eu5gameparser.clausewitz.syntax import CList

    rows_by_slug: dict[str, dict[str, str | bool]] = {}

    def mark_location(slug: str, tag: str, *, constructible: bool) -> None:
        existing = rows_by_slug.get(slug)
        if existing is None or constructible or not bool(existing["startup_constructible_owner"]):
            rows_by_slug[slug] = {
                "country_tag": tag,
                "owner": tag,
                "owner_country_id": tag,
                "startup_constructible_owner": constructible,
            }

    for path in _setup_start_files(config, "10_countries.txt"):
        document = parse_file(path)
        for countries in document.values("countries"):
            if not isinstance(countries, CList):
                continue
            for country in _country_entries(countries):
                tag = str(country.key)
                if not isinstance(country.value, CList):
                    continue
                for value in country.value.values("capital"):
                    if isinstance(value, str):
                        mark_location(value, tag, constructible=True)
                for entry in country.value.entries:
                    if not _country_location_list_marks_owner(entry.key) or not isinstance(entry.value, CList):
                        continue
                    constructible = _country_location_list_owns(entry.key)
                    for item in entry.value.items:
                        if isinstance(item, str):
                            mark_location(item, tag, constructible=constructible)
    schema = {
        "slug": pl.String,
        "country_tag": pl.String,
        "owner": pl.String,
        "owner_country_id": pl.String,
        "startup_constructible_owner": pl.Boolean,
    }
    rows = [
        {"slug": slug, **values}
        for slug, values in sorted(rows_by_slug.items())
    ]
    return pl.DataFrame(rows, schema=schema)


def _country_entries(countries):
    from eu5gameparser.clausewitz.syntax import CList

    for entry in countries.entries:
        if entry.key == "countries" and isinstance(entry.value, CList):
            yield from _country_entries(entry.value)
        elif isinstance(entry.value, CList):
            yield entry


def _country_location_list_owns(key: str) -> bool:
    return key.startswith("own_")


def _country_location_list_marks_owner(key: str) -> bool:
    return key == "add_pops_from_locations" or _country_location_list_owns(key)


def _load_existing_buildings(config: FoodStartupConfig) -> dict[tuple[str, str], float]:
    if config.load_order.is_file():
        return _load_start_existing_buildings(config)
    path = config.savegame_dir / "buildings.parquet"
    if not path.is_file():
        return {}
    frame = pl.read_parquet(path)
    if frame.is_empty():
        return {}
    _require_columns(frame, {"location_slug", "building_type", "level"})
    result: dict[tuple[str, str], float] = {}
    for row in frame.group_by(["location_slug", "building_type"]).agg(pl.col("level").sum().alias("level")).to_dicts():
        result[(str(row["location_slug"]), str(row["building_type"]))] = float(row["level"] or 0.0)
    return result


def _load_start_existing_buildings(config: FoodStartupConfig) -> dict[tuple[str, str], float]:
    from eu5gameparser.clausewitz.parser import parse_file
    from eu5gameparser.clausewitz.syntax import CList

    result: dict[tuple[str, str], float] = {}
    for path in _setup_start_files(config, "07_cities_and_buildings.txt"):
        document = parse_file(path)
        town_setups = _load_start_location_town_setups(document)
        if town_setups:
            definitions = _load_town_setup_definitions(config)
            for location, town_setup in town_setups.items():
                for building, level in _expand_start_town_setup(town_setup, definitions).items():
                    if level <= 0.0:
                        continue
                    key = (location, building)
                    result[key] = result.get(key, 0.0) + level
        for manager in document.values("building_manager"):
            if not isinstance(manager, CList):
                continue
            for entry in manager.entries:
                if not isinstance(entry.value, CList):
                    continue
                location = entry.value.first("location")
                if not isinstance(location, str):
                    continue
                level = _numeric(entry.value.first("level"))
                if level <= 0.0:
                    continue
                key = (location, str(entry.key))
                result[key] = result.get(key, 0.0) + level
    return result


def _load_start_location_town_setups(document: object) -> dict[str, str]:
    from eu5gameparser.clausewitz.syntax import CList

    result: dict[str, str] = {}
    for locations in document.values("locations"):
        if not isinstance(locations, CList):
            continue
        for entry in locations.entries:
            if not isinstance(entry.value, CList):
                continue
            town_setup = entry.value.first("town_setup")
            if isinstance(town_setup, str) and town_setup:
                result[str(entry.key)] = town_setup
    return result


def _load_town_setup_definitions(config: FoodStartupConfig) -> dict[str, StartTownSetupDefinition]:
    from eu5gameparser.clausewitz.parser import parse_file
    from eu5gameparser.clausewitz.syntax import CList

    definitions: dict[str, StartTownSetupDefinition] = {}
    for path in _town_setup_files(config):
        document = parse_file(path)
        for entry in document.entries:
            if not isinstance(entry.value, CList):
                continue
            copy_from: str | None = None
            levels: dict[str, float] = defaultdict(float)
            for child in entry.value.entries:
                if child.key == "copy_from" and isinstance(child.value, str):
                    copy_from = child.value
                    continue
                level = _numeric(child.value)
                if level > 0.0:
                    levels[str(child.key)] += level
            definitions[str(entry.key)] = StartTownSetupDefinition(copy_from=copy_from, levels=dict(levels))
    return definitions


def _expand_start_town_setup(
    key: str,
    definitions: Mapping[str, StartTownSetupDefinition],
    stack: tuple[str, ...] = (),
) -> dict[str, float]:
    if key in stack:
        chain = " -> ".join((*stack, key))
        raise FoodStartupError(f"recursive town_setup copy_from chain: {chain}")
    definition = definitions.get(key)
    if definition is None:
        raise FoodStartupError(f"unknown town_setup: {key}")
    expanded: dict[str, float] = {}
    if definition.copy_from is not None:
        expanded.update(_expand_start_town_setup(definition.copy_from, definitions, (*stack, key)))
    for building, level in definition.levels.items():
        expanded[building] = expanded.get(building, 0.0) + level
    return expanded


