def _mapping(value: object, label: str) -> Mapping[str, object]:
    if not isinstance(value, dict):
        raise FoodStartupError(f"{label} must be a table")
    return value


def _optional_mapping(value: object, label: str) -> Mapping[str, object]:
    if value is None:
        return {}
    return _mapping(value, label)


def _path(value: object, label: str) -> Path:
    return Path(_string(value, label))


def _string(value: object, label: str) -> str:
    if not isinstance(value, str) or not value:
        raise FoodStartupError(f"{label} must be a non-empty string")
    return value


def _optional_string(value: object, label: str) -> str | None:
    if value is None:
        return None
    return _string(value, label)


def _string_tuple(value: object, label: str) -> tuple[str, ...]:
    if isinstance(value, tuple):
        return tuple(str(item) for item in value)
    if not isinstance(value, list):
        raise FoodStartupError(f"{label} must be a list")
    return tuple(_string(item, f"{label}[]") for item in value)


def _bool(value: object, label: str) -> bool:
    if not isinstance(value, bool):
        raise FoodStartupError(f"{label} must be a boolean")
    return value


def _float(value: object, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise FoodStartupError(f"{label} must be a number")
    number = float(value)
    if not math.isfinite(number):
        raise FoodStartupError(f"{label} must be finite")
    return number


def _optional_float(value: object, label: str) -> float | None:
    if value is None:
        return None
    return _float(value, label)


def _repo_path(repo: Path, path: Path) -> Path:
    return path if path.is_absolute() else repo / path


def _optional_repo_path(repo: Path, value: object) -> Path | None:
    if value is None:
        return None
    return _repo_path(repo, Path(_string(value, "outputs.mod_script")))


def _safe_share_expr(numerator: str, denominator: str) -> pl.Expr:
    return pl.when(pl.col(denominator) > 0.0).then(pl.col(numerator) / pl.col(denominator)).otherwise(0.0)


def _require_columns(frame: pl.DataFrame, columns: set[str]) -> None:
    missing = sorted(columns - set(frame.columns))
    if missing:
        raise FoodStartupError(f"missing columns: {', '.join(missing)}")


