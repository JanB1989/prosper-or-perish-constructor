@dataclass(frozen=True)
class OutputRule:
    mode: str
    good: str | None
    production_methods: tuple[str, ...]
    multiplier: float
    estimated_production_efficiency: float = 0.0
    fixed_food_per_level: float | None = None
    good_amount_per_level: float | None = None


@dataclass(frozen=True)
class ProductionSourceRule:
    key: str
    enabled: bool
    mode: str
    output: OutputRule | None = None
    building: str | None = None
    population_column: str | None = None
    food_per_1000_population: float | None = None


@dataclass(frozen=True)
class ScoreRule:
    population: float
    development: float
    province_capital_bonus: float


@dataclass(frozen=True)
class BuildingRule:
    key: str
    enabled: bool
    order: int
    coverage_group: str
    target_food_ratio: float
    target_basis: str
    max_levels_per_province: int
    max_levels_per_location: int
    min_province_food_consumption: float
    placement: str
    allowed_ranks: tuple[str, ...]
    allowed_regions: tuple[str, ...]
    allowed_macro_regions: tuple[str, ...]
    allowed_super_regions: tuple[str, ...]
    allowed_country_tags: tuple[str, ...]
    required_raw_materials: tuple[str, ...]
    required_province_raw_materials: tuple[str, ...]
    excluded_raw_materials: tuple[str, ...]
    min_location_population: float
    min_location_development: float
    min_province_rural_population_share: float
    max_province_rural_population_share: float | None
    min_province_urban_population_share: float
    max_province_urban_population_share: float | None
    max_province_peasant_population_share: float | None
    min_province_development_per_1000_population: float
    target_scale_min: float
    peasant_share_scale_start: float | None
    peasant_share_scale_end: float | None
    development_per_1000_scale_start: float | None
    development_per_1000_scale_end: float | None
    output: OutputRule
    score: ScoreRule


