def compute_building_food_outputs(
    rules: Sequence[BuildingRule],
    goods: pl.DataFrame,
    production_methods: pl.DataFrame,
    buildings: pl.DataFrame,
) -> pl.DataFrame:
    _require_columns(goods, {"name", "food"})
    _require_columns(production_methods, {"name", "produced", "output", "input_goods", "input_amounts"})
    _require_columns(buildings, {"name", "pop_type", "employment_size"})
    goods_food = {
        str(row["name"]): float(row["food"] or 0.0)
        for row in goods.select("name", "food").to_dicts()
    }
    methods = {str(row["name"]): row for row in production_methods.to_dicts()}
    building_metadata = {str(row["name"]): row for row in buildings.to_dicts()}
    rows: list[dict[str, object]] = []
    for rule in rules:
        if not rule.enabled:
            continue
        metadata = building_metadata.get(rule.key)
        if metadata is None:
            raise FoodStartupError(f"missing parser building metadata for {rule.key!r}")
        worker_pop_type = str(metadata.get("pop_type") or "")
        if not worker_pop_type:
            raise FoodStartupError(f"parser building metadata for {rule.key!r} is missing pop_type")
        employment_size = float(metadata.get("employment_size") or 0.0)
        if employment_size <= 0.0:
            raise FoodStartupError(f"parser building metadata for {rule.key!r} has non-positive employment_size")
        food_per_level = _food_per_level(rule.output, goods_food, methods)
        rows.append(
            {
                "building": rule.key,
                "coverage_group": rule.coverage_group,
                "output_mode": rule.output.mode,
                "good": rule.output.good,
                "food_per_level": food_per_level,
                "production_methods": list(rule.output.production_methods),
                "multiplier": rule.output.multiplier,
                "estimated_production_efficiency": rule.output.estimated_production_efficiency,
                "worker_pop_type": worker_pop_type,
                "employment_size": employment_size,
                "employment_size_key": str(metadata.get("employment_size_key") or ""),
            }
        )
    return pl.DataFrame(
        rows,
        schema={
            "building": pl.String,
            "coverage_group": pl.String,
            "output_mode": pl.String,
            "good": pl.String,
            "food_per_level": pl.Float64,
            "production_methods": pl.List(pl.String),
            "multiplier": pl.Float64,
            "estimated_production_efficiency": pl.Float64,
            "worker_pop_type": pl.String,
            "employment_size": pl.Float64,
            "employment_size_key": pl.String,
        },
    )


def plan_building_placements(
    locations: pl.DataFrame,
    provinces: pl.DataFrame,
    rules: Sequence[BuildingRule],
    building_outputs: pl.DataFrame,
    *,
    existing_levels: Mapping[tuple[str, str], float] | None = None,
    remaining_peasants_by_location: dict[str, float] | None = None,
) -> pl.DataFrame:
    output_by_building = {
        str(row["building"]): float(row["food_per_level"] or 0.0)
        for row in building_outputs.to_dicts()
    }
    worker_metadata_by_building = {
        str(row["building"]): (
            str(row["worker_pop_type"] or ""),
            float(row["employment_size"] or 0.0),
        )
        for row in building_outputs.to_dicts()
    }
    locations_by_province: dict[str, list[dict[str, Any]]] = defaultdict(list)
    if remaining_peasants_by_location is None:
        remaining_peasants_by_location = _initial_remaining_peasants(locations)
    for row in locations.filter(pl.col("province").is_not_null()).to_dicts():
        locations_by_province[_province_key(row["province"])].append(row)
        remaining_peasants_by_location.setdefault(str(row["slug"]), _startup_peasant_reserve(row))

    existing_levels = existing_levels or {}
    coverage: dict[tuple[str, str], float] = defaultdict(float)
    enabled_keys = {rule.key for rule in rules if rule.enabled}
    mirror_victuals_import = (
        VICTUALS_MARKET_EXPORT in enabled_keys and VICTUALS_MARKET_IMPORT not in enabled_keys
    )
    rows: list[dict[str, object]] = []
    for rule in sorted((rule for rule in rules if rule.enabled), key=lambda item: (item.order, item.key)):
        food_per_level = output_by_building.get(rule.key, 0.0)
        if food_per_level <= 0.0:
            continue
        worker_pop_type, employment_size = worker_metadata_by_building.get(rule.key, ("", 0.0))
        if not worker_pop_type or employment_size <= 0.0:
            continue
        pair_with_import = mirror_victuals_import and rule.key == VICTUALS_MARKET_EXPORT
        allocation_employment = employment_size * (2.0 if pair_with_import else 1.0)
        for province in provinces.to_dicts():
            province_id = _province_key(province["province"])
            province_food = float(province["food_consumption"] or 0.0)
            if province_food < rule.min_province_food_consumption:
                continue
            if not _province_allowed(province, rule):
                continue
            target_base = _target_base(province, rule)
            target_scale = _province_target_scale(province, rule)
            target = target_base * rule.target_food_ratio * target_scale
            already_covered = coverage[(province_id, rule.coverage_group)]
            if rule.target_basis == "consumption":
                already_covered += float(province.get("food_production") or 0.0)
            needed_food = max(target - already_covered, 0.0)
            if needed_food <= 0.0:
                continue
            levels_needed = min(
                rule.max_levels_per_province,
                max(1, math.ceil(needed_food / food_per_level)),
            )
            for location, levels, available_peasants_before in _allocate_locations(
                locations_by_province.get(province_id, []),
                rule,
                levels_needed,
                remaining_peasants_by_location,
                allocation_employment,
                existing_levels,
            ):
                worker_peasant_requirement = levels * employment_size
                remaining_after_source = available_peasants_before - worker_peasant_requirement
                added_food = levels * food_per_level
