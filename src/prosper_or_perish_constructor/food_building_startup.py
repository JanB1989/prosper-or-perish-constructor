@dataclass(frozen=True)
class ProvinceFoodBalanceModel:
    pop_food_consumption: Mapping[str, float]
    unknown_pop_food_consumption: float
    food_consumption_multiplier: float
    production_sources: tuple[ProductionSourceRule, ...]
    goods_food: Mapping[str, float]
    production_methods: Mapping[str, Mapping[str, Any]]

    @classmethod
    def from_parser_tables(
        cls,
        pop_types: pl.DataFrame,
        goods: pl.DataFrame,
        production_methods: pl.DataFrame,
        production_sources: Sequence[ProductionSourceRule],
        *,
        unknown_pop_food_consumption: float,
        food_consumption_multiplier: float = 1.0,
    ) -> ProvinceFoodBalanceModel:
        _require_columns(pop_types, {"name", "pop_food_consumption"})
        _require_columns(goods, {"name", "food"})
        _require_columns(production_methods, {"name", "produced", "output", "input_goods", "input_amounts"})
        rates = {
            str(row["name"]): float(row["pop_food_consumption"] or 0.0)
            for row in pop_types.select("name", "pop_food_consumption").to_dicts()
        }
        goods_food = {
            str(row["name"]): float(row["food"] or 0.0)
            for row in goods.select("name", "food").to_dicts()
        }
        return cls(
            pop_food_consumption=rates,
            unknown_pop_food_consumption=unknown_pop_food_consumption,
            food_consumption_multiplier=food_consumption_multiplier,
            production_sources=tuple(source for source in production_sources if source.enabled),
            goods_food=goods_food,
            production_methods={str(row["name"]): row for row in production_methods.to_dicts()},
        )

    def compute_locations(
        self,
        locations: pl.DataFrame,
        *,
        existing_levels: Mapping[tuple[str, str], float] | None = None,
    ) -> pl.DataFrame:
        _require_columns(
            locations,
            {
                "location_id",
                "slug",
                "province",
                "region",
                "macro_region",
                "super_region",
                "development",
                "total_population",
                "rank",
            },
        )
        expr = pl.lit(0.0)
        for pop_type, rate in sorted(self.pop_food_consumption.items()):
            column = f"{POPULATION_PREFIX}{pop_type}"
            if column in locations.columns:
                expr = expr + pl.col(column).fill_null(0.0) * rate
        if "population_unknown" in locations.columns and self.unknown_pop_food_consumption:
            expr = expr + pl.col("population_unknown").fill_null(0.0) * self.unknown_pop_food_consumption
        expr = expr * self.food_consumption_multiplier

        frame = locations.with_columns(expr.alias("food_consumption"))
        frame = _with_province_capital(frame)
        frame = frame.with_columns(
            [
                pl.col("rank").fill_null("none").alias("location_rank"),
                pl.col("total_population").fill_null(0.0),
                pl.col("development").fill_null(0.0),
            ]
        )
        frame = self._with_location_production(frame, existing_levels=existing_levels or {})
        return frame.with_columns((pl.col("food_production") - pl.col("food_consumption")).alias("food_balance"))

    def compute_provinces(self, location_balance: pl.DataFrame) -> pl.DataFrame:
        _require_columns(
            location_balance,
            {
                "province",
                "slug",
                "province_capital",
                "region",
                "macro_region",
                "super_region",
                "food_consumption",
                "food_production",
                "food_balance",
                "total_population",
                "development",
                "location_rank",
                "raw_material",
            },
        )
        valid = location_balance.filter(pl.col("province").is_not_null())
        capital_slug = (
            valid.filter(pl.col("province_capital"))
            .select("province", pl.col("slug").alias("province_capital_slug"))
        )
        grouped = (
            valid.group_by("province")
            .agg(
                [
                    pl.col("food_consumption").sum().alias("food_consumption"),
                    pl.col("food_production").sum().alias("food_production"),
                    pl.col("food_balance").sum().alias("food_balance"),
                    pl.col("food_production_subsistence").sum().alias("food_production_subsistence"),
                    pl.col("food_production_buildings").sum().alias("food_production_buildings"),
                    pl.col("development").sum().alias("development"),
                    pl.col("total_population").sum().alias("total_population"),
                    pl.col("population_peasants").sum().alias("peasant_population"),
                    pl.when(pl.col("location_rank") == "rural_settlement")
                    .then(pl.col("total_population"))
                    .otherwise(0.0)
                    .sum()
                    .alias("rural_population"),
                    pl.when(pl.col("location_rank").is_in(["town", "city", "megalopolis"]))
                    .then(pl.col("total_population"))
                    .otherwise(0.0)
                    .sum()
                    .alias("urban_population"),
                    pl.col("raw_material").drop_nulls().unique().alias("raw_materials"),
                    pl.col("region").drop_nulls().first().alias("region"),
                    pl.col("macro_region").drop_nulls().first().alias("macro_region"),
                    pl.col("super_region").drop_nulls().first().alias("super_region"),
                    pl.len().alias("location_count"),
                ]
            )
            .join(capital_slug, on="province", how="left")
            .sort("food_consumption", descending=True)
        )
        return grouped.with_columns(
            [
                _safe_share_expr("rural_population", "total_population").alias("rural_population_share"),
                _safe_share_expr("urban_population", "total_population").alias("urban_population_share"),
                _safe_share_expr("peasant_population", "total_population").alias("peasant_population_share"),
                _safe_share_expr("development", "total_population").alias("development_per_1000_population"),
                pl.max_horizontal(pl.col("food_consumption") - pl.col("food_production"), pl.lit(0.0)).alias("food_shortfall"),
                _safe_share_expr("food_production", "food_consumption").alias("food_self_sufficiency"),
            ]
        ).sort("food_consumption", descending=True)

    def _with_location_production(
        self,
        locations: pl.DataFrame,
        *,
        existing_levels: Mapping[tuple[str, str], float],
    ) -> pl.DataFrame:
        expressions: list[pl.Expr] = []
        subsistence_expr = pl.lit(0.0)
        buildings_expr = pl.lit(0.0)
        other_expr = pl.lit(0.0)
        for source in self.production_sources:
            column = f"food_production_{source.key}"
            expr = self._location_production_expr(source, existing_levels)
            expressions.append(expr.alias(column))
            if source.mode == "population_per_1000":
                subsistence_expr = subsistence_expr + expr
            elif source.mode == "existing_building_levels":
                buildings_expr = buildings_expr + expr
            else:
                other_expr = other_expr + expr
        frame = locations.with_columns(expressions) if expressions else locations
        return frame.with_columns(
            [
                subsistence_expr.alias("food_production_subsistence"),
                buildings_expr.alias("food_production_buildings"),
                other_expr.alias("food_production_other"),
                (subsistence_expr + buildings_expr + other_expr).alias("food_production"),
            ]
        )

    def _location_production_expr(
        self,
        source: ProductionSourceRule,
        existing_levels: Mapping[tuple[str, str], float],
    ) -> pl.Expr:
        if source.mode == "population_per_1000":
            if source.population_column is None or source.food_per_1000_population is None:
                raise FoodStartupError(f"production source {source.key!r} requires population_column and food_per_1000_population")
            return pl.col(source.population_column).fill_null(0.0) * source.food_per_1000_population
        if source.mode == "existing_building_levels":
            if source.building is None or source.output is None:
                raise FoodStartupError(f"production source {source.key!r} requires building and output")
            food_per_level = _food_per_level(source.output, self.goods_food, self.production_methods)
            if not existing_levels:
                return pl.lit(0.0)
            values = {
                slug: level * food_per_level
                for (slug, building), level in existing_levels.items()
                if building == source.building
            }
            if not values:
                return pl.lit(0.0)
            return pl.col("slug").replace_strict(values, default=0.0, return_dtype=pl.Float64)
        raise FoodStartupError(f"unsupported production source mode {source.mode!r}")


class FoodStartupError(RuntimeError):
    """Raised when food startup planning cannot be completed."""


def load_food_startup_config(repo: Path, path: Path | None = None) -> FoodStartupConfig:
    config_path = _repo_path(repo, path or DEFAULT_CONFIG)
    raw = tomllib.loads(config_path.read_text(encoding="utf-8"))
    inputs = _mapping(raw.get("inputs"), "inputs")
    outputs = _optional_mapping(raw.get("outputs"), "outputs")
    demand = _optional_mapping(raw.get("demand"), "demand")
    planner = _mapping(raw.get("planner"), "planner")
    production_sources = raw.get("production_sources", [])
    buildings = raw.get("buildings")
    if not isinstance(production_sources, list):
        raise FoodStartupError(f"{config_path}: production_sources must be a list")
    if not isinstance(buildings, list) or not buildings:
        raise FoodStartupError(f"{config_path}: expected at least one [[buildings]] entry")

    return FoodStartupConfig(
        savegame_dir=_repo_path(repo, _path(inputs.get("savegame_dir"), "inputs.savegame_dir")),
        parser_artifact_dir=_repo_path(
            repo, _path(inputs.get("parser_artifact_dir"), "inputs.parser_artifact_dir")
        ),
        output_dir=_repo_path(repo, _path(inputs.get("output_dir"), "inputs.output_dir")),
        mod_script=_optional_repo_path(repo, outputs.get("mod_script")),
        load_order=_repo_path(repo, _path(inputs.get("load_order"), "inputs.load_order")),
        profile=_string(inputs.get("profile"), "inputs.profile"),
        unknown_pop_food_consumption=_float(
            demand.get("unknown_pop_food_consumption", planner.get("unknown_pop_food_consumption", 0.0)),
            "demand.unknown_pop_food_consumption",
        ),
        food_consumption_multiplier=_float(
            demand.get("food_consumption_multiplier", planner.get("food_consumption_multiplier", 1.0)),
            "demand.food_consumption_multiplier",
        ),
        include_existing_buildings=_bool(
            planner.get("include_existing_buildings", False),
            "planner.include_existing_buildings",
        ),
        generated_effect=_string(planner.get("generated_effect", "pp_food_building_startup"), "planner.generated_effect"),
        production_sources=tuple(_production_source_rule(item, index) for index, item in enumerate(production_sources)),
        buildings=tuple(_building_rule(item, index) for index, item in enumerate(buildings)),
    )


def build_food_startup_plan(config: FoodStartupConfig) -> FoodStartupResult:
    locations = _load_locations(config.savegame_dir)
    pop_types = _load_pop_types(config)
    goods = _load_goods(config)
    production_methods = _load_production_methods(config)
    existing = _load_existing_buildings(config.savegame_dir) if config.include_existing_buildings else {}

    balance_model = ProvinceFoodBalanceModel.from_parser_tables(
        pop_types,
        goods,
        production_methods,
        config.production_sources,
        unknown_pop_food_consumption=config.unknown_pop_food_consumption,
        food_consumption_multiplier=config.food_consumption_multiplier,
    )
    location_food = balance_model.compute_locations(locations, existing_levels=existing)
    province_food = balance_model.compute_provinces(location_food)
    building_outputs = compute_building_food_outputs(config.buildings, goods, production_methods)
    building_plan = plan_building_placements(
        location_food,
        province_food,
        config.buildings,
        building_outputs,
        existing_levels=existing,
    )
    summary = _summary(location_food, province_food, building_plan, building_outputs)
    return FoodStartupResult(
        location_food=location_food,
        province_food=province_food,
        building_plan=building_plan,
        building_outputs=building_outputs,
        pop_types=pop_types,
        summary=summary,
    )


def compute_location_food_consumption(
    locations: pl.DataFrame,
    pop_types: pl.DataFrame,
    *,
    unknown_pop_food_consumption: float,
) -> pl.DataFrame:
    empty_goods = pl.DataFrame({"name": [], "food": []}, schema={"name": pl.String, "food": pl.Float64})
    empty_methods = pl.DataFrame(
        {"name": [], "produced": [], "output": [], "input_goods": [], "input_amounts": []},
        schema={
            "name": pl.String,
            "produced": pl.String,
            "output": pl.Float64,
            "input_goods": pl.List(pl.String),
            "input_amounts": pl.List(pl.Float64),
        },
    )
    return ProvinceFoodBalanceModel.from_parser_tables(
        pop_types,
        empty_goods,
        empty_methods,
        (),
        unknown_pop_food_consumption=unknown_pop_food_consumption,
        food_consumption_multiplier=1.0,
    ).compute_locations(locations)


def compute_province_food_consumption(locations: pl.DataFrame) -> pl.DataFrame:
    return ProvinceFoodBalanceModel(
        pop_food_consumption={},
        unknown_pop_food_consumption=0.0,
        production_sources=(),
        goods_food={},
        production_methods={},
        food_consumption_multiplier=1.0,
    ).compute_provinces(locations)


def compute_building_food_outputs(
    rules: Sequence[BuildingRule],
    goods: pl.DataFrame,
    production_methods: pl.DataFrame,
) -> pl.DataFrame:
    _require_columns(goods, {"name", "food"})
    _require_columns(production_methods, {"name", "produced", "output", "input_goods", "input_amounts"})
    goods_food = {
        str(row["name"]): float(row["food"] or 0.0)
        for row in goods.select("name", "food").to_dicts()
    }
    methods = {str(row["name"]): row for row in production_methods.to_dicts()}
    rows: list[dict[str, object]] = []
    for rule in rules:
        if not rule.enabled:
            continue
        food_per_level = _food_per_level(rule.output, goods_food, methods)
        rows.append(
            {
                "building": rule.key,
                "coverage_group": rule.coverage_group,
                "output_mode": rule.output.mode,
                "good": rule.output.good,
                "food_per_level": food_per_level,
                "production_methods": list(rule.output.production_methods),
                "multiplier": rule.output.multiplier,
                "estimated_production_efficiency": rule.output.estimated_production_efficiency,
            }
        )
    return pl.DataFrame(
        rows,
        schema={
            "building": pl.String,
            "coverage_group": pl.String,
            "output_mode": pl.String,
            "good": pl.String,
            "food_per_level": pl.Float64,
            "production_methods": pl.List(pl.String),
            "multiplier": pl.Float64,
            "estimated_production_efficiency": pl.Float64,
        },
    )


def plan_building_placements(
    locations: pl.DataFrame,
    provinces: pl.DataFrame,
    rules: Sequence[BuildingRule],
    building_outputs: pl.DataFrame,
    *,
    existing_levels: Mapping[tuple[str, str], float] | None = None,
) -> pl.DataFrame:
    output_by_building = {
        str(row["building"]): float(row["food_per_level"] or 0.0)
        for row in building_outputs.to_dicts()
    }
    locations_by_province: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for row in locations.filter(pl.col("province").is_not_null()).to_dicts():
        locations_by_province[int(row["province"])].append(row)

    existing_levels = existing_levels or {}
    coverage: dict[tuple[int, str], float] = defaultdict(float)
    rows: list[dict[str, object]] = []
    for rule in sorted((rule for rule in rules if rule.enabled), key=lambda item: (item.order, item.key)):
        food_per_level = output_by_building.get(rule.key, 0.0)
        if food_per_level <= 0.0:
            continue
        for province in provinces.to_dicts():
            province_id = int(province["province"])
            province_food = float(province["food_consumption"] or 0.0)
            if province_food < rule.min_province_food_consumption:
                continue
            if not _province_allowed(province, rule):
                continue
            target_base = _target_base(province, rule)
            target_scale = _province_target_scale(province, rule)
            target = target_base * rule.target_food_ratio * target_scale
            already_covered = coverage[(province_id, rule.coverage_group)]
            if rule.target_basis == "consumption":
                already_covered += float(province.get("food_production") or 0.0)
            needed_food = max(target - already_covered, 0.0)
            if needed_food <= 0.0:
                continue
            levels_needed = min(
                rule.max_levels_per_province,
                max(1, math.ceil(needed_food / food_per_level)),
            )
            for location, levels in _allocate_locations(
                locations_by_province.get(province_id, []),
                rule,
                levels_needed,
            ):
                added_food = levels * food_per_level
                coverage[(province_id, rule.coverage_group)] += added_food
                rows.append(
                    {
                        "building": rule.key,
                        "coverage_group": rule.coverage_group,
                        "province": province_id,
                        "location_id": int(location["location_id"]),
                        "location_slug": str(location["slug"]),
                        "levels": int(levels),
                        "food_per_level": food_per_level,
                        "estimated_food_added": added_food,
                        "province_food_consumption": province_food,
                        "province_food_production": float(province.get("food_production") or 0.0),
                        "province_food_balance": float(province.get("food_balance") or 0.0),
                        "province_food_shortfall": float(province.get("food_shortfall") or 0.0),
                        "target_basis": rule.target_basis,
                        "target_base": target_base,
                        "target_scale": target_scale,
                        "target_food": target,
                        "needed_food_before": needed_food,
                        "placement": rule.placement,
                        "province_capital": bool(location.get("province_capital")),
                        "location_rank": str(location.get("location_rank") or location.get("rank") or ""),
                        "total_population": float(location.get("total_population") or 0.0),
                        "development": float(location.get("development") or 0.0),
                        "region": str(location.get("region") or ""),
                        "macro_region": str(location.get("macro_region") or ""),
                        "super_region": str(location.get("super_region") or ""),
                        "country_tag": str(location.get("country_tag") or ""),
                        "raw_material": str(location.get("raw_material") or ""),
                        "province_rural_population_share": float(province.get("rural_population_share") or 0.0),
                        "province_urban_population_share": float(province.get("urban_population_share") or 0.0),
                        "province_peasant_population_share": float(province.get("peasant_population_share") or 0.0),
                        "province_development_per_1000_population": float(province.get("development_per_1000_population") or 0.0),
                    }
                )
    schema = {
        "building": pl.String,
        "coverage_group": pl.String,
        "province": pl.Int64,
        "location_id": pl.Int64,
        "location_slug": pl.String,
        "levels": pl.Int64,
        "food_per_level": pl.Float64,
        "estimated_food_added": pl.Float64,
        "province_food_consumption": pl.Float64,
        "province_food_production": pl.Float64,
        "province_food_balance": pl.Float64,
        "province_food_shortfall": pl.Float64,
        "target_basis": pl.String,
        "target_base": pl.Float64,
        "target_scale": pl.Float64,
        "target_food": pl.Float64,
        "needed_food_before": pl.Float64,
        "placement": pl.String,
        "province_capital": pl.Boolean,
        "location_rank": pl.String,
        "total_population": pl.Float64,
        "development": pl.Float64,
        "region": pl.String,
        "macro_region": pl.String,
        "super_region": pl.String,
        "country_tag": pl.String,
        "raw_material": pl.String,
        "province_rural_population_share": pl.Float64,
        "province_urban_population_share": pl.Float64,
        "province_peasant_population_share": pl.Float64,
        "province_development_per_1000_population": pl.Float64,
    }
    return pl.DataFrame(rows, schema=schema).sort(["building", "province", "location_slug"])


def write_food_startup_artifacts(
    result: FoodStartupResult,
    output_dir: Path,
    *,
    compile_script: bool = False,
    effect_name: str = "pp_food_building_startup",
    mod_script: Path | None = None,
) -> dict[str, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "location_food": output_dir / "derived_food_balance_by_location.parquet",
        "province_food": output_dir / "derived_food_balance_by_province.parquet",
        "building_plan": output_dir / "food_building_plan.parquet",
        "building_outputs": output_dir / "food_building_outputs.parquet",
        "summary": output_dir / "summary.json",
    }
    result.location_food.write_parquet(paths["location_food"])
    result.province_food.write_parquet(paths["province_food"])
    result.building_plan.write_parquet(paths["building_plan"])
    result.building_outputs.write_parquet(paths["building_outputs"])
    paths["summary"].write_text(json.dumps(result.summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if compile_script:
        script_text = render_food_startup_effect(result.building_plan, effect_name=effect_name)
        script_path = output_dir / "pp_food_building_startup_generated.txt"
        script_path.write_text(script_text, encoding="utf-8")
        paths["script"] = script_path
        if mod_script is not None:
            mod_script.parent.mkdir(parents=True, exist_ok=True)
            mod_script.write_text(script_text, encoding="utf-8-sig")
            paths["mod_script"] = mod_script
    return paths


def render_food_startup_effect(plan: pl.DataFrame, *, effect_name: str) -> str:
    lines = [
        GENERATED_HEADER,
        "# Generated from tick-0 savegame pop counts and parser pop/goods data.",
        "",
        f"{effect_name} = {{",
        "\teffect = {",
    ]
    if plan.is_empty():
        lines.extend(["\t\t# No startup food building placements selected.", "\t}", "}", ""])
        return "\n".join(lines)

    for location_slug, location_rows in _plan_rows_by_location(plan).items():
        lines.append(f"\t\tlocation:{location_slug} = {{")
        for row in location_rows:
            building = str(row["building"])
            for target_level in range(1, int(row["levels"]) + 1):
                if target_level == 1:
                    level_guard = [
                        f"\t\t\t\t\tNOT = {{ has_building = building_type:{building} }}",
                    ]
                else:
                    level_guard = [
                        "\t\t\t\t\tlocation_building_level = {",
                        f"\t\t\t\t\t\tbuilding_type = building_type:{building}",
                        f"\t\t\t\t\t\tvalue < {target_level}",
                        "\t\t\t\t\t}",
                    ]
                lines.extend(
                    [
                        "\t\t\tif = {",
                        "\t\t\t\tlimit = {",
                        "\t\t\t\t\thas_owner = yes",
                        *level_guard,
                        "\t\t\t\t}",
                        "\t\t\t\tconstruct_building = {",
                        f"\t\t\t\t\tbuilding_type = building_type:{building}",
                        "\t\t\t\t\tinstant = yes",
                        "\t\t\t\t\tcost_multiplier = 0",
                        '\t\t\t\t\tcost_multiplier_reason = "game_start"',
                        "\t\t\t\t}",
                        "\t\t\t}",
                    ]
                )
        lines.append("\t\t}")
    lines.extend(["\t}", "}", ""])
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Plan province-level startup food buildings.")
    parser.add_argument("--repo", type=Path, default=None)
    parser.add_argument("--project", type=Path, default=DEFAULT_PROJECT)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output-dir", type=Path, default=None)
    parser.add_argument("--compile-script", action="store_true")
    args = parser.parse_args(argv)

    try:
        repo = resolve_repo(args.repo)
        config = load_food_startup_config(repo, args.config)
        if args.output_dir is not None:
            config = _replace_output_dir(config, _repo_path(repo, args.output_dir))
        result = build_food_startup_plan(config)
        paths = write_food_startup_artifacts(
            result,
            config.output_dir,
            compile_script=args.compile_script,
            effect_name=config.generated_effect,
            mod_script=config.mod_script,
        )
        _print_result(result, paths)
        return 0
    except FoodStartupError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


def resolve_repo(path: Path | None) -> Path:
    if path is not None:
        return path.resolve()
    current = Path.cwd().resolve()
    for candidate in (current, *current.parents):
        if (candidate / DEFAULT_PROJECT).is_file():
            return candidate
    raise FoodStartupError("could not find constructor.toml; pass --repo")


def _food_per_level(
    output: OutputRule,
    goods_food: Mapping[str, float],
    methods: Mapping[str, Mapping[str, Any]],
) -> float:
    if output.fixed_food_per_level is not None:
        return output.fixed_food_per_level * output.multiplier
    if output.good is None:
        raise FoodStartupError("output.good is required unless fixed_food_per_level is set")
    good_food = goods_food.get(output.good)
    if good_food is None:
        raise FoodStartupError(f"missing parser food value for good {output.good!r}")
    if output.mode == "configured_good_amount":
        if output.good_amount_per_level is None:
            raise FoodStartupError("configured_good_amount requires good_amount_per_level")
        return output.good_amount_per_level * good_food * output.multiplier
    if output.mode == "production_methods":
        good_amount = 0.0
        for name in output.production_methods:
            method = _require_method(methods, name)
            if method.get("produced") == output.good:
                good_amount += float(method.get("output") or 0.0)
        return (
            good_amount
            * good_food
            * output.multiplier
            * (1.0 + output.estimated_production_efficiency)
        )
    if output.mode == "input_goods_as_food":
        good_amount = 0.0
        for name in output.production_methods:
            method = _require_method(methods, name)
            good_amount += _input_amount(method, output.good)
        return good_amount * good_food * output.multiplier
    raise FoodStartupError(f"unsupported output mode {output.mode!r}")


def _require_method(methods: Mapping[str, Mapping[str, Any]], name: str) -> Mapping[str, Any]:
    try:
        return methods[name]
    except KeyError as exc:
        raise FoodStartupError(f"production method {name!r} is missing from parser artifacts") from exc


def _input_amount(method: Mapping[str, Any], good: str) -> float:
    goods = method.get("input_goods") or []
    amounts = method.get("input_amounts") or []
    total = 0.0
    for input_good, amount in zip(goods, amounts, strict=False):
        if input_good == good:
            total += float(amount or 0.0)
    return total


