"""Whole building levels behind the Cookshop cap (2026-10-24).

The Cookshop cap (``cookshop_max_level``, script_values/pp_building_caps.txt) counts the farm, orchard and other staple
food levels and the Victualling Yard levels of the province. Those buildings carry level counters in ``raw_modifier``
(``local_pp_farm_levels``, ``local_pp_staple_levels``, ``local_pp_victualling_yard_levels``), but the engine multiplies a
``raw_modifier`` by the building's input fulfilment: a farm short of an input counts a little under one level, the cap
floors one level lower than the start simulation's, and kitchens placed at the cap stood above it (31 at game start,
building_manager "is above max level", 2026-10-24).

``write`` renders location-scope script values that sum the standing levels of every building type that carries a
counter (counter value x ``location_building_level``), so the cap counts whole levels in the game as the start
simulation does. ``pp_food_building_values.txt`` sums them per province. The ``raw_modifier`` counters stay for their
other readers (the farms' crowding term in their AI weight).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from eu5gameparser.clausewitz.parser import parse_file
from eu5gameparser.clausewitz.syntax import CList

OUTPUT = Path("in_game/common/script_values/pp_food_building_level_counts.txt")
BUILDING_TYPES = Path("in_game/common/building_types")
# script value -> the raw_modifier counters whose buildings it counts
VALUES = {
    "pp_location_farm_building_levels": ("local_pp_farm_levels", "local_pp_staple_levels"),
    "pp_location_victualling_yard_building_levels": ("local_pp_victualling_yard_levels",),
}
_PREFIXES = ("REPLACE_OR_CREATE:", "INJECT_OR_CREATE:", "TRY_REPLACE:", "TRY_INJECT:", "REPLACE:", "INJECT:")
HEADER = (
    "﻿# Generated by ppc finalize (food_level_counts.py); do not edit by hand.\n"
    "# Location scope: the standing levels of the buildings that count toward the Cookshop cap, in whole levels. The\n"
    "# buildings' raw_modifier counters read less than a level while an input is short (the engine scales raw_modifier\n"
    "# by input fulfilment), which moved the cap below the kitchens standing at it.\n"
)


@dataclass
class Result:
    counted: dict[str, int]
    changed: bool


def _bare(key: str) -> str:
    for prefix in _PREFIXES:
        if key.startswith(prefix):
            return key[len(prefix):]
    return key


def counters(mod_root: Path) -> dict[str, dict[str, float]]:
    """building type -> {counter: value per level} from the raw_modifier blocks of the mod's building types."""
    names = {name for group in VALUES.values() for name in group}
    found: dict[str, dict[str, float]] = {}
    for path in sorted((mod_root / BUILDING_TYPES).glob("*.txt")):
        for entry in parse_file(path).entries:
            if not isinstance(entry.value, CList):
                continue
            values: dict[str, float] = {}
            for block in entry.value.values("raw_modifier"):
                if isinstance(block, CList):
                    for item in block.entries:
                        if str(item.key) in names and isinstance(item.value, (int, float)):
                            values[str(item.key)] = values.get(str(item.key), 0.0) + float(item.value)
            if values:
                found.setdefault(_bare(str(entry.key)), {}).update(values)
    return dict(sorted(found.items()))


def _num(value: float) -> str:
    return f"{value:.5f}".rstrip("0").rstrip(".")


def render(found: dict[str, dict[str, float]]) -> tuple[str, dict[str, int]]:
    blocks: list[str] = []
    counted: dict[str, int] = {}
    for value_name, names in VALUES.items():
        lines = [f"{value_name} = {{", "\tvalue = 0"]
        members = [(key, sum(per.get(name, 0.0) for name in names)) for key, per in found.items()]
        members = [(key, weight) for key, weight in members if weight]
        for key, weight in members:
            level = f'"location_building_level(building_type:{key})"'
            add = level if weight == 1 else f"{{ value = {level} multiply = {_num(weight)} }}"
            lines.append(f"\tif = {{ limit = {{ has_building = building_type:{key} }} add = {add} }}")
        lines.append("}")
        blocks.append("\n".join(lines))
        counted[value_name] = len(members)
    return HEADER + "\n" + "\n\n".join(blocks) + "\n", counted


def write(mod_root: Path) -> Result:
    text, counted = render(counters(mod_root))
    path = mod_root / OUTPUT
    changed = not path.is_file() or path.read_text(encoding="utf-8") != text
    if changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return Result(counted=counted, changed=changed)
