"""Whole building levels of the manufacturing lines, for the specialization town rights (2026-11-11).

Every building of a refined end-good line carries ``raw_modifier local_pp_<good>_line_levels = 1`` (manufacturing tiers
2026-10-06). The specialization charters and rights (``town_rights/pp_specialization_town_rights.txt``) asked for
``modifier:local_pp_<good>_line_levels >= N``, but the engine multiplies a ``raw_modifier`` by the building's input
fulfilment (the average over its method slots): a line short of an input counts less than its levels, and one that gets
no inputs (unstaffed, or no goods in the market) counts 0. In Jan's 1357 save 155 of 632 towns with 3 or more line
levels read under 3 (mean 0.07), so neither tier could be granted there, the player saw "0 of 8" in a town full of
workshops, and the rights tier looked unreachable.

``write`` renders one location-scope script value per line, ``pp_location_<good>_line_levels``: the standing levels of
every building type that carries that line's counter (counter value x ``location_building_level``), whole levels like
the build menu shows them. The town rights read these values. The ``raw_modifier`` counters stay as the markers this
pass reads (and the location's modifier list shows them).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from eu5gameparser.clausewitz.parser import parse_file
from eu5gameparser.clausewitz.syntax import CList

OUTPUT = Path("in_game/common/script_values/pp_line_level_counts.txt")
BUILDING_TYPES = Path("in_game/common/building_types")
COUNTER = re.compile(r"^local_pp_(\w+)_line_levels$")
_PREFIXES = ("REPLACE_OR_CREATE:", "INJECT_OR_CREATE:", "TRY_REPLACE:", "TRY_INJECT:", "REPLACE:", "INJECT:")
HEADER = (
    "﻿# Generated by ppc finalize (line_level_counts.py); do not edit by hand.\n"
    "# Location scope: the standing levels of each manufacturing line (every building type carrying the line's\n"
    "# local_pp_<good>_line_levels counter), in whole levels. The specialization town rights read these: the counters\n"
    "# themselves read less than the levels while an input is short (the engine scales raw_modifier by input\n"
    "# fulfilment) and 0 in a line that gets no inputs.\n"
)


@dataclass
class Result:
    lines: dict[str, int]
    changed: bool


def value_name(good: str) -> str:
    return f"pp_location_{good}_line_levels"


def _bare(key: str) -> str:
    for prefix in _PREFIXES:
        if key.startswith(prefix):
            return key[len(prefix):]
    return key


def counters(mod_root: Path) -> dict[str, dict[str, float]]:
    """line good -> {building type: counter value per level} from the raw_modifier blocks of the mod's building types."""
    found: dict[str, dict[str, float]] = {}
    for path in sorted((mod_root / BUILDING_TYPES).glob("*.txt")):
        for entry in parse_file(path).entries:
            if not isinstance(entry.value, CList):
                continue
            for block in entry.value.values("raw_modifier"):
                if not isinstance(block, CList):
                    continue
                for item in block.entries:
                    match = COUNTER.match(str(item.key))
                    if match and isinstance(item.value, (int, float)) and item.value:
                        per = found.setdefault(match.group(1), {})
                        key = _bare(str(entry.key))
                        per[key] = per.get(key, 0.0) + float(item.value)
    return {good: dict(sorted(per.items())) for good, per in sorted(found.items())}


def _num(value: float) -> str:
    return f"{value:.5f}".rstrip("0").rstrip(".")


def render(found: dict[str, dict[str, float]]) -> tuple[str, dict[str, int]]:
    blocks: list[str] = []
    counted: dict[str, int] = {}
    for good, members in found.items():
        lines = [f"{value_name(good)} = {{", "\tvalue = 0"]
        for key, weight in members.items():
            level = f'"location_building_level(building_type:{key})"'
            add = level if weight == 1 else f"{{ value = {level} multiply = {_num(weight)} }}"
            lines.append(f"\tif = {{ limit = {{ has_building = building_type:{key} }} add = {add} }}")
        lines.append("}")
        blocks.append("\n".join(lines))
        counted[good] = len(members)
    return HEADER + "\n" + "\n\n".join(blocks) + "\n", counted


def write(mod_root: Path) -> Result:
    text, counted = render(counters(mod_root))
    path = mod_root / OUTPUT
    changed = not path.is_file() or path.read_text(encoding="utf-8") != text
    if changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return Result(lines=counted, changed=changed)
