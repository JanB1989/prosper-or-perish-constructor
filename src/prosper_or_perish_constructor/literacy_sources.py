"""Country-wide literacy sources (2026-11-25/26, Jan): who the generic country-wide literacy sources reach.

A pop creeps up to its literacy cap, and nearly all of that cap came from country-wide bonuses for every class. Jan:
literacy is earned by local buildings, and research follows the country's average literacy, which tracks the learned
estates only if commoners read as little as in history. The rule of ``config/literacy_sources.toml``: a positive
all-class cap (``global_max_literacy = X``) becomes ``global_{nobles,clergy,burghers}_max_literacy = X`` (added to an
estate line the block already has; Written Alphabet keeps 2 for everyone, ``[split_exceptions]``); the lower-class
caps (``global_{peasants,laborers,soldiers}_max_literacy``) x 0.4 to clean numbers; literacy speed
(``global_/local_monthly_literacy``) to a fifth; explicit values for the base rate (Written Alphabet, Educated
Bureaucrats) and the estates' start (Guilds, Improved Religious Organization).

Scope: the folders of ``[folders.*]``; an object is judged by the file that first defines it (vanilla or a DLC
folder); an object PP defines itself keeps its numbers. Numbers change where they stand: in an advance's body, or in a
block whose key ends in ``modifier`` (a law's policies' ``country_modifier``, a religion's ``definition_modifier``, a
societal value's ``right_modifier``, ...), never in triggers.

Outputs (``apply``; ``check`` reports them current or off):
- ``<folder>/zz_pp_literacy_sources.txt``: every changed object whole, as the game merges it (vanilla, the DLC folders'
  injects and the mod's injects folded in, so nothing they add is lost), with only the literacy numbers changed;
  ``REPLACE:``, or ``TRY_REPLACE:`` for an object only a DLC folder defines. A DLC folder's inject into a vanilla
  object (Across the Pillars' Granada policy in education_elites_law) is carried; it gates itself with ``has_dlc``.
  An inject only changes a block by adding lines (copies of a modifier add up), so changing a number takes a replace.
- Objects another mod file already replaces are not replaced twice (the engine ignores later injects into a replaced
  block): the first-age advances are written by the starting technology ladder (``start_technology.py`` calls
  ``cut_advance``), legal_code_law by the RGO cost redirects (``rgo_cost_redirects.py`` calls ``cut_lines``), and a
  hand-written replace carries the numbers by hand (printing_press_advance). The pass checks their numbers and fails
  when one differs from the rule.
- ``artifacts/data/literacy_sources/changes.csv`` (folder, object, block, key, old, new, written by) and
  ``left_out.csv`` (every country-wide or local literacy line left as it is in the scanned folders, with the reason).
"""

