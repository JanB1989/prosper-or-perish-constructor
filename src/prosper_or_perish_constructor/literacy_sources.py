_HEADER = "GENERATED by `uv run ppc literacy apply` (src/prosper_or_perish_constructor/literacy_sources.py); do not edit."
_TAG_CHECK = re.compile(r"\b(?:has_or_had_tag|tag) = \w+")


class LiteracySourcesError(ValueError):
    pass


# ---------------------------------------------------------------------------------------------- config
@dataclass(frozen=True)
class FolderScope:
    name: str
    path: Path
    include: tuple[str, ...]
    exclude: tuple[str, ...] = ()
    top_level: bool = False
    skip_tag_gated: bool = False
    ladder_age: str | None = None

    def file_scope(self, file_name: str) -> bool | None:
        """True in scope, False excluded, None in neither list."""
        if any(fnmatch.fnmatchcase(file_name, g) for g in self.exclude):
            return False
        if any(fnmatch.fnmatchcase(file_name, g) for g in self.include):
            return True
        return None


@dataclass(frozen=True)
class Rule:
    split_key: str                               # all-class cap: a positive value goes to the estates
    split_into: tuple[str, ...]                  # the estate keys it goes to, at the same value
    split_exceptions: dict[tuple[str, str], tuple[Decimal, Decimal]]   # (folder, object) -> (kept for all, per estate)
    max_keys: frozenset[str]                     # lower-class caps: x factor
    max_factor: Decimal
    max_minimum: Decimal
    speed_keys: frozenset[str]
    speed_factor: Decimal
    speed_decimals: int
    speed_minimum: Decimal
    speed_keep: Decimal
    speed_small_factor: Decimal
    speed_active_folders: frozenset[str]         # sources a country chooses: a milder cut
    speed_active_factor: Decimal
    speed_active_decimals: int
    speed_active_minimum: Decimal
    values: dict[tuple[str, str, str], Decimal]  # explicit values ([base_rate], [estate_start])
    folders: dict[str, FolderScope]
    exclude_objects: dict[tuple[str, str], str]
    left_out_folders: dict[str, str] = field(default_factory=dict)

    @property
    def keys(self) -> frozenset[str]:
        """Every key the rule reads (the estate keys only where an explicit value names them)."""
        return frozenset({self.split_key, *self.max_keys, *self.speed_keys, *(k for _f, _o, k in self.values)})

    def new_value(self, folder: str, obj: str, key: str, value: str) -> str | None:
        """The new number for one line (not the split key), or None when it stays."""
        old = _decimal(folder, obj, key, value)
        fixed = self.values.get((folder, obj, key))
        if fixed is not None:
            new = fixed
        elif key in self.max_keys:
            if old <= 0:
                return None
            new = max(self.max_minimum, (old * self.max_factor).quantize(Decimal(1), rounding=ROUND_HALF_UP))
        elif key in self.speed_keys:
            if old <= 0:
                return None
            if folder in self.speed_active_folders:   # chosen sources: values above the threshold x the active factor
                if old <= self.speed_keep:
                    return None
                step = Decimal(1).scaleb(-self.speed_active_decimals)
                new = max(self.speed_active_minimum,
                          (old * self.speed_active_factor).quantize(step, rounding=ROUND_HALF_UP))
                return None if new == old else _number(new)
            step = Decimal(1).scaleb(-self.speed_decimals)
            if old <= self.speed_keep:   # the small sources: their own factor, no minimum
                new = (old * self.speed_small_factor).quantize(step, rounding=ROUND_HALF_UP)
            else:
                new = max(self.speed_minimum, (old * self.speed_factor).quantize(step, rounding=ROUND_HALF_UP))
        else:
            return None
        return None if new == old else _number(new)


def _number(value: Decimal) -> str:
    text = format(value.normalize(), "f")
    return text


def _decimal(folder: str, obj: str, key: str, value: str) -> Decimal:
    try:
        return Decimal(value)
    except InvalidOperation:
        raise LiteracySourcesError(f"{folder}/{obj}: {key} = {value} is not a number") from None


def load_rule(repo: Path) -> Rule:
    raw = tomllib.loads((Path(repo) / CONFIG).read_text(encoding="utf-8"))
    folders = {}
    for name, spec in raw["folders"].items():
        folders[name] = FolderScope(name, Path(spec["path"]), tuple(spec.get("include", ())), tuple(spec.get("exclude", ())),
                                    bool(spec.get("top_level", False)), bool(spec.get("skip_tag_gated", False)),
                                    spec.get("ladder_age"))
    values = {}
    for section in ("base_rate", "estate_start"):
        for dotted, value in raw.get(section, {}).items():
            folder, obj, key = dotted.split(".")
            values[(folder, obj, key)] = Decimal(str(value))
    excluded = {}
    for dotted, reason in raw.get("exclude_objects", {}).items():
        folder, obj = dotted.split(".")
        excluded[(folder, obj)] = str(reason)
    split = raw["split"]
    exceptions = {}
    for dotted, spec in raw.get("split_exceptions", {}).items():
        folder, obj = dotted.split(".")
        exceptions[(folder, obj)] = (Decimal(str(spec["keep"])), Decimal(str(spec["estates"])))
    m, s = raw["max_literacy"], raw["speed"]
    return Rule(
        split_key=str(split["key"]), split_into=tuple(split["into"]), split_exceptions=exceptions,
        max_keys=frozenset(m["keys"]), max_factor=Decimal(str(m["factor"])), max_minimum=Decimal(str(m["minimum"])),
        speed_keys=frozenset(s["keys"]), speed_factor=Decimal(str(s["factor"])), speed_decimals=int(s["decimals"]),
        speed_minimum=Decimal(str(s["minimum"])), speed_keep=Decimal(str(s["keep_at_or_below"])),
        speed_small_factor=Decimal(str(s.get("small_factor", 1))),
        speed_active_folders=frozenset(s.get("active_folders", ())),
        speed_active_factor=Decimal(str(s.get("active_factor", s["factor"]))),
        speed_active_decimals=int(s.get("active_decimals", s["decimals"])),
        speed_active_minimum=Decimal(str(s.get("active_minimum", s["minimum"]))),
        values=values, folders=folders, exclude_objects=excluded,
        left_out_folders={str(k): str(v) for k, v in raw.get("left_out_folders", {}).items()},
    )


def try_load_rule(repo: Path) -> Rule | None:
    return load_rule(repo) if (Path(repo) / CONFIG).is_file() else None


# ---------------------------------------------------------------------------------------------- objects
@dataclass
class Obj:
    key: str
    body: tuple[Stmt, ...]
    history: list[tuple[str, str, str]] = field(default_factory=list)   # (mode, layer, file name)
    replaced: bool = False

    @property
    def origin(self) -> tuple[str, str]:
        """(layer, file) of the first definition."""
        mode, layer, name = self.history[0]
        return layer, name

    @property
    def base_defined(self) -> bool:
        return any(mode in ("CREATE", "REPLACE_OR_CREATE", "INJECT_OR_CREATE") and layer != "dlc"
                   for mode, layer, _ in self.history)

    def replacer(self) -> str | None:
        """The last mod file that replaced the object (None: the mod only injects into it or leaves it alone)."""
        out = None
        for mode, layer, name in self.history[1:]:
            if layer == "mod" and mode in ("REPLACE", "TRY_REPLACE", "REPLACE_OR_CREATE", "CREATE"):
                out = name
        return out


def effective_objects(vanilla_root: Path, mod_root: Path | None, folder: Path, *,
                      skip: tuple[str, ...] = ()) -> dict[str, Obj]:
    """Every object of one folder as the game merges it (base game, DLC folders, the mod), the same merge as
    ``start_technology.effective_advances``: an inject into a replaced block is ignored."""
    db: dict[str, Obj] = {}
    for path in st.layered_files(vanilla_root, mod_root, folder, skip=skip):
        layer = st._layer_of(path, vanilla_root, mod_root)
        for stmt in st.parse_statements(path.read_text(encoding="utf-8-sig")):
            if stmt.key is None or not stmt.is_block:
                continue
            mode, key = st._mode(stmt.key)
            body: tuple[Stmt, ...] = stmt.value  # type: ignore[assignment]
            existing = db.get(key)
            record = (mode, layer, path.name)
            if mode in ("CREATE", "REPLACE", "REPLACE_OR_CREATE") or (mode == "TRY_REPLACE" and existing is not None):
                db[key] = Obj(key, body, [*(existing.history if existing else []), record],
                              replaced=mode != "CREATE" and existing is not None)
            elif mode in st._INJECT_MODES:
                if existing is None:
                    if mode == "INJECT_OR_CREATE":
                        db[key] = Obj(key, body, [record])
                    continue
                if existing.replaced:
                    continue
                existing.body = (*existing.body, *body)
                existing.history.append(record)
    return db


# ---------------------------------------------------------------------------------------------- the cut
@dataclass(frozen=True)
class Change:
    folder: str
    obj: str
    block: str
    key: str
    old: str
    new: str


def _counts(parent: str | None, top: bool, scope: FolderScope) -> bool:
    return (top and scope.top_level) or (parent is not None and parent.endswith("modifier"))


def cut_statements(rule: Rule, scope: FolderScope, obj: str, body: tuple[Stmt, ...]) -> tuple[tuple[Stmt, ...], list[Change]]:
    """The body with the rule applied where each line stands, and the changes.

    A positive all-class cap (``split_key``) leaves the block and its value goes to each estate key (``split_into``)
    in the same block: added to that key's line when the block has one, else a new line where the cap stood. A
    ``[split_exceptions]`` object keeps part of it for everyone. Zero and negative caps stay. Lower-class caps, speed
    and the explicit values go through ``Rule.new_value``."""
    changes: list[Change] = []
    exception = rule.split_exceptions.get((scope.name, obj))

    def walk(stmts: tuple[Stmt, ...], path: tuple[str, ...], top: bool) -> tuple[Stmt, ...]:
        out: list[Stmt] = []
        parent = path[-1] if path else None
        block = "/".join(path) or "(advance)"
        counts = _counts(parent, top, scope)
        adds: dict[str, Decimal] = {}
        insert_at: int | None = None
        for s in stmts:
            if s.is_block:
                out.append(dataclasses.replace(s, value=walk(s.value, (*path, s.key or "{}"), False)))  # type: ignore[arg-type]
                continue
            if counts and s.op == "=" and s.key == rule.split_key:
                old = _decimal(scope.name, obj, s.key, str(s.value))
                if old > 0:
                    keep, per_estate = exception if exception is not None else (Decimal(0), old)
                    if keep > 0:
                        out.append(Stmt(s.key, s.op, _number(keep)) if keep != old else s)
                    if insert_at is None:
                        insert_at = len(out)   # the estate lines follow what stays for everyone
                    if keep != old:
                        changes.append(Change(scope.name, obj, block, s.key, str(s.value), _number(keep) if keep > 0 else ""))
                    for estate in rule.split_into:
                        adds[estate] = adds.get(estate, Decimal(0)) + per_estate
                    continue
            elif counts and s.op == "=" and s.key in rule.keys:
                new = rule.new_value(scope.name, obj, s.key, str(s.value))
                if new is not None:
                    changes.append(Change(scope.name, obj, block, s.key, str(s.value), new))
                    out.append(Stmt(s.key, s.op, new))
                    continue
            out.append(s)
        new_lines: list[Stmt] = []
        for estate, amount in adds.items():
            index = next((i for i, x in enumerate(out) if x.key == estate and x.op == "=" and not x.is_block), None)
            if index is None:
                new_lines.append(Stmt(estate, "=", _number(amount)))
                changes.append(Change(scope.name, obj, block, estate, "", _number(amount)))
            else:
                old = _decimal(scope.name, obj, estate, str(out[index].value))
                out[index] = Stmt(estate, "=", _number(old + amount))
                changes.append(Change(scope.name, obj, block, estate, str(old), _number(old + amount)))
        if new_lines:
            out[insert_at:insert_at] = new_lines  # type: ignore[misc]
        return tuple(out)

    return walk(body, (), True), changes


def literacy_lines(body: tuple[Stmt, ...], path: tuple[str, ...] = ()) -> list[tuple[str, str, str]]:
    """(block path, key, value) of every literacy line of a body, triggers included."""
    out = []
    for s in body:
        if s.is_block:
            out += literacy_lines(s.value, (*path, s.key or "{}"))  # type: ignore[arg-type]
        elif s.key and LITERACY_KEY.match(s.key):
            out.append(("/".join(path) or "(advance)", s.key, str(s.value)))
    return out


def _in_scope(rule: Rule, scope: FolderScope, obj: Obj, vanilla: Obj | None) -> tuple[bool | None, str]:
    """(in scope, reason when not); None = a file neither list names."""
    if vanilla is None or obj.origin[0] == "mod":
        return False, "PP's own object (its numbers are deliberate)"
    layer, name = vanilla.origin
    reason = rule.exclude_objects.get((scope.name, obj.key))
    if reason:
        return False, reason
    in_file = scope.file_scope(name)
    if in_file is None:
        return None, f"file {name} is in neither include nor exclude of [folders.{scope.name}]"
    if not in_file:
        return False, f"specific file {name}"
    if scope.skip_tag_gated:
        for pot in (s.value for s in vanilla.body if s.key == "potential" and s.is_block):
            if _TAG_CHECK.search(st.flat_text(pot)):  # type: ignore[arg-type]
                return False, "country-specific (its potential names a country tag)"
    return True, ""


def cut_advance(rule: Rule | None, adv: "st.Advance") -> tuple[tuple[Stmt, ...], list[Change]]:
    """For the starting technology ladder: an advance's body with the cut (unchanged when out of scope)."""
    if rule is None or "advances" not in rule.folders or not adv.history:
        return adv.body, []
    scope = rule.folders["advances"]
    mode, layer, name = adv.history[0]
    if layer == "mod" or rule.exclude_objects.get(("advances", adv.key)) or scope.file_scope(name) is not True:
        return adv.body, []
    return cut_statements(rule, scope, adv.key, adv.body)


_LINE = re.compile(r"^(\s*)(\w+)(\s*=\s*)(-?[0-9.]+)(.*)$")
_OPENER = re.compile(r"([\w:.]+)\s*=\s*\{\s*(?:#.*)?$")


def cut_lines(rule: Rule | None, folder: str, obj: str, origin_file: str, lines: list[str]) -> list[str]:
    """For a pass that copies vanilla text (rgo_cost_redirects): the block's lines with the cut, formatting kept.
    A line counts when its innermost block's key ends in ``modifier``."""
    if rule is None or folder not in rule.folders:
        return lines
    scope = rule.folders[folder]
    if rule.exclude_objects.get((folder, obj)) or scope.file_scope(origin_file) is not True:
        return lines
    stack: list[str] = []
    out = []
    for line in lines:
        code = line.split("#", 1)[0]
        match = _LINE.match(line)
        if match and match.group(2) in rule.keys and stack and stack[-1].endswith("modifier") and "{" not in code:
            if match.group(2) == rule.split_key:
                if Decimal(match.group(4)) > 0:
                    # moving a cap to the estates needs the whole block (an estate line may already stand in it)
                    raise LiteracySourcesError(f"{folder}/{obj}: cut_lines cannot move {rule.split_key} to the estates; "
                                               "extend it or let literacy_sources.py replace the object")
                new = None
            else:
                new = rule.new_value(folder, obj, match.group(2), match.group(4))
            if new is not None:
                line = f"{match.group(1)}{match.group(2)}{match.group(3)}{new}{match.group(5)}"
        out.append(line)
        for token in re.finditer(r"([\w:.]+)\s*=\s*(?:\w+\s*)?\{|\{|\}", code):
            text = token.group(0)
            if text == "}":
                if stack:
                    stack.pop()
            elif text == "{":
                stack.append("{}")
            else:
                stack.append(token.group(1).split(":")[-1])
    return out


# ---------------------------------------------------------------------------------------------- the pass
@dataclass
class Result:
    changes: list[tuple[Change, str]]            # (change, written by)
    written: dict[str, dict[str, tuple[str, tuple[Stmt, ...]]]]   # folder -> object -> (mode, body)
    left_out: list[dict[str, str]]
    problems: list[str]
    changed: list[Path]

    @property
    def objects(self) -> int:
        return len({(c.folder, c.obj) for c, _ in self.changes})


def plan(rule: Rule, vanilla_root: Path, mod_root: Path) -> Result:
    changes: list[tuple[Change, str]] = []
    written: dict[str, dict[str, tuple[str, tuple[Stmt, ...]]]] = {}
    left_out: list[dict[str, str]] = []
    problems: list[str] = []
    for name, scope in rule.folders.items():
        vanilla_db = effective_objects(vanilla_root, None, scope.path)
        mod_db = effective_objects(vanilla_root, mod_root, scope.path, skip=(OUTPUT_NAME,))
        for key in sorted(mod_db):
            obj, vanilla = mod_db[key], vanilla_db.get(key)
            lines = literacy_lines(obj.body)
            if not lines:
                continue
            ok, reason = _in_scope(rule, scope, obj, vanilla)
            if ok is None:
                problems.append(f"{name}/{key}: {reason}")
                continue
            if not ok:
                left_out += [{"folder": name, "object": key, "file": obj.origin[1], "block": b, "key": k, "value": v,
                              "reason": reason} for b, k, v in lines
                             if k == rule.split_key or k in rule.max_keys or k in rule.speed_keys]
                continue
            expected, wanted = cut_statements(rule, scope, key, vanilla.body)  # type: ignore[union-attr]
            if not wanted:
                continue
            ladder = scope.ladder_age is not None and st._last_scalar(vanilla.body, "age") == scope.ladder_age  # type: ignore[union-attr]
            owner = "start_technology.py (ladder)" if ladder else obj.replacer()
            if owner:
                # another file writes the object: its numbers must be the rule's
                have = Counter(literacy_lines(obj.body))
                want = Counter(literacy_lines(expected))
                if have != want:
                    problems.append(f"{name}/{key} is written by {owner}: literacy lines {sorted(have - want)} should be "
                                    f"{sorted(want - have)}" + (" (run uv run ppc start-tech apply)" if ladder else ""))
                changes += [(c, owner) for c in wanted]
                continue
            if "expand_rgo_" in st.flat_text(obj.body):
                # rgo_cost_redirects.py injects into it (or would refuse a mod replace of it on the next build)
                problems.append(f"{name}/{key} carries an expand_rgo_*_cost_modifier: let rgo_cost_redirects.py "
                                "replace it and carry the literacy cut there (cut_lines)")
                continue
            body, done = cut_statements(rule, scope, key, obj.body)
            mode = "REPLACE" if obj.base_defined else "TRY_REPLACE"
            written.setdefault(name, {})[key] = (mode, body)
            changes += [(c, OWN_WRITER) for c in done]
    # what the folders left out on purpose hold
    for rel, reason in rule.left_out_folders.items():
        db = effective_objects(vanilla_root, mod_root, Path(rel))
        for key in sorted(db):
            for b, k, v in literacy_lines(db[key].body):
                left_out.append({"folder": Path(rel).name, "object": key, "file": db[key].origin[1], "block": b,
                                 "key": k, "value": v, "reason": reason})
    return Result(changes, written, left_out, problems, [])


def render(scope: FolderScope, blocks: dict[str, tuple[str, tuple[Stmt, ...]]]) -> str:
    lines = [
        f"# {_HEADER}",
        "# Country-wide literacy sources (config/literacy_sources.toml): the generic objects with a country-wide maximum",
        "# literacy or literacy speed, each whole as the game merges it (vanilla, DLC folders, the mod) with only those",
        "# lines changed (an all-class cap moved to the three estates, lower-class caps and speed cut).",
    ]
    for key in sorted(blocks):
        mode, body = blocks[key]
        lines += ["", f"{mode}:{key} = {{", *st.render_statements(body, 1), "}"]
    # the statement renderer puts a colour's `rgb { ... }` on two lines (same tokens); keep it on one as vanilla does
    return re.sub(r"= (rgb|hsv|hsv360)\n\t*\{", r"= \1 {", "\n".join(lines) + "\n")


def _csv_text(header: tuple[str, ...], rows: list[dict[str, object]]) -> str:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=list(header), lineterminator="\n", extrasaction="ignore")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue()


def apply(repo: Path, project: Path, mod_root: Path | None = None, vanilla_root: Path | None = None, *,
          write: bool = True) -> Result:
    """Write (or with ``write=False`` only compare) the replace files; with ``write`` also the reports. Raises on a
    problem (a file in neither list, another owner's numbers off the rule)."""
    from prosper_or_perish_constructor.worldbuilder.stage import vanilla_root as configured_vanilla_root

    repo = Path(repo)
    mod_root = Path(mod_root) if mod_root is not None else repo / "mod" / MOD_FOLDER
    vanilla_root = Path(vanilla_root) if vanilla_root is not None else configured_vanilla_root(repo, project)
    rule = load_rule(repo)
    result = plan(rule, vanilla_root, mod_root)
    if result.problems:
        raise LiteracySourcesError("literacy sources: " + "; ".join(result.problems))
    for name, scope in rule.folders.items():
        path = mod_root / scope.path / OUTPUT_NAME
        blocks = result.written.get(name, {})
        if blocks:
            if st._write(path, render(scope, blocks), write=write, bom=True):
                result.changed.append(scope.path / OUTPUT_NAME)
        elif path.is_file():
            result.changed.append(scope.path / OUTPUT_NAME)
            if write:
                path.unlink()
    if write:
        rows = [{"folder": c.folder, "object": c.obj, "block": c.block, "key": c.key, "old": c.old, "new": c.new,
                 "written_by": by} for c, by in result.changes]
        (repo / REPORT_DIR).mkdir(parents=True, exist_ok=True)
        st._write(repo / CHANGES_CSV, _csv_text(CHANGES_HEADER, rows), write=True, bom=False)
        st._write(repo / LEFT_OUT_CSV, _csv_text(LEFT_OUT_HEADER, result.left_out), write=True, bom=False)
    return result


def summary(result: Result, *, check: bool = False) -> str:
    per_folder = Counter(c.folder for c, _ in result.changes)
    objects = Counter(f for f, _ in {(c.folder, c.obj) for c, _ in result.changes})
    own = sum(len(v) for v in result.written.values())
    if check:
        state = "current" if not result.changed else "OFF (run uv run ppc literacy apply): " + ", ".join(map(str, result.changed))
    else:
        state = f"{len(result.changed)} files rewritten" if result.changed else "unchanged"
    parts = ", ".join(f"{f} {objects[f]}/{per_folder[f]}" for f in sorted(per_folder))
    return (f"Literacy sources: {result.objects} objects, {len(result.changes)} values cut (objects/values: {parts}); "
            f"{own} replaced here, {result.objects - own} by their own pass; {len(result.left_out)} literacy lines "
            f"left out; {state}.")
