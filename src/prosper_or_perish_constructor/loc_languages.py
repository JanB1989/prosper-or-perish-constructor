"""The mod's English text for players of every other game language.

EU5 loads a localization file only for the language its header and name say (``l_english:``, ``*_l_english.yml``). The
mod ships English only, so a player running the game in French saw raw keys (``pp_tavern_price``) wherever the mod
adds text, and vanilla's own French wherever the mod changes a vanilla text (Steam request, 2026-10-24). ``apply``
writes the English text for each other language the game has, per localization folder (``localization/<language>/``,
``localization/replace/<language>/``): every English file's entries in one file ``pp_mod_text_l_<language>.yml`` (one
file per folder keeps the paths inside the repo's Windows path budget), the header switched, the text unchanged.
Files that ``separate`` names keep their own copy (``<name>_l_<language>.yml``): the Seasonal Harvests standalone ships
those files too, and a same-name file replaces the other mod's copy instead of defining its keys twice. It runs in
``ppc finalize`` after every pass that writes English text; files in those folders it does not write are removed (the
mod has no translations of its own).
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

# EU5 1.4's languages (game/main_menu/localization) other than English
LANGUAGES = ("braz_por", "french", "german", "japanese", "korean", "polish", "russian", "simp_chinese", "spanish", "turkish")
FOLDERS = (Path("main_menu/localization"), Path("main_menu/localization/replace"), Path("in_game/localization"))
MERGED = "pp_mod_text_l_{language}.yml"
BOM = "﻿"
_HEADER = re.compile(r"^l_english:[ \t]*\n?", re.MULTILINE)


@dataclass
class Result:
    written: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)
    files: int = 0


def translated(text: str, language: str) -> str:
    """An English file's text with its header switched to ``language`` (BOM kept; comments above the header stay)."""
    body, count = re.subn(r"^l_english:", f"l_{language}:", text.removeprefix(BOM), count=1, flags=re.MULTILINE)
    if not count:
        raise ValueError("an English localization file needs an l_english: header")
    return BOM + body


def entries(text: str) -> str:
    """An English file's lines without its BOM and header."""
    body, count = _HEADER.subn("", text.removeprefix(BOM), count=1)
    if not count:
        raise ValueError("an English localization file needs an l_english: header")
    return body if body.endswith("\n") or not body else body + "\n"


def plan(mod_root: Path, language: str, separate: Iterable[str] = ()) -> dict[Path, str]:
    """Every file ``apply`` writes for ``language``: path -> text. ``separate``: English file paths relative to the mod
    root that keep their own copy."""
    keep = {Path(p) for p in separate}
    out: dict[Path, str] = {}
    for folder in FOLDERS:
        english = Path(mod_root) / folder / "english"
        if not english.is_dir():
            continue
        merged: list[str] = []
        for source in sorted(english.rglob("*_l_english.yml")):
            text = source.read_text(encoding="utf-8-sig")
            rel = source.relative_to(english)
            if source.relative_to(mod_root) in keep:
                out[Path(mod_root) / folder / language / rel.parent / rel.name.replace("_l_english.yml", f"_l_{language}.yml")] = translated(text, language)
            else:
                merged.append(f" # {rel.as_posix()}\n" + entries(text))
        if merged:
            out[Path(mod_root) / folder / language / MERGED.format(language=language)] = (
                BOM + f"l_{language}:\n # Generated by ppc finalize (loc_languages.py): the mod's English text, file by file.\n" + "".join(merged))
    return out


def apply(mod_root: Path, languages: tuple[str, ...] = LANGUAGES, separate: Iterable[str] = ()) -> Result:
    result = Result()
    separate = tuple(separate)
    result.files = sum(len(list((Path(mod_root) / f / "english").rglob("*_l_english.yml"))) for f in FOLDERS if (Path(mod_root) / f / "english").is_dir())
    for language in languages:
        wanted = plan(mod_root, language, separate)
        for path, text in wanted.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
                result.written.append(path)
        for folder in FOLDERS:
            root = Path(mod_root) / folder / language
            for stale in root.rglob("*.yml") if root.is_dir() else ():
                if stale not in wanted:
                    stale.unlink()
                    result.removed.append(stale)
    return result


def summary(results: dict[str, Result]) -> str:
    parts = [f"{name}: {r.files} English files x {len(LANGUAGES)} languages ({len(r.written)} files written, {len(r.removed)} removed)"
             for name, r in results.items()]
    return "Other languages show the English text: " + "; ".join(parts) + "."
