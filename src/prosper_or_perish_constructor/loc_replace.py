"""Vanilla localization keys the mod overrides: move them from ``localization/english`` into ``localization/replace``.

A key that the mod's ``main_menu/localization/english`` defines while vanilla's English localization defines it too is
loaded twice: the engine logs ``Key '...' defined in multiple files`` (pdx_localize.cpp) and which text wins is not
defined. Only ``localization/replace/english`` overrides a vanilla key cleanly. Many such keys come from blueprint
localization blocks rendered by eu5-building-pipeline (``# >>> eu5-building-pipeline:<key>:localization``), so a one-off
move would be undone by the next render: ``apply`` runs in ``ppc finalize`` after every render.

``apply`` takes every such line out of the English files (the blueprint block keeps its markers) and writes it into
``GENERATED_RELATIVE_PATH``; a key moved again replaces the text there (the blueprint is the source), keys whose text is
vanilla's word for word are dropped (nothing to override), and the other replace files stay untouched. Hand-written keys
moved once live on in the generated file, so edit their text there (or in the blueprint for rendered keys).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

ENGLISH_RELATIVE_PATH = Path("main_menu/localization/english")
REPLACE_RELATIVE_PATH = Path("main_menu/localization/replace/english")
GENERATED_RELATIVE_PATH = REPLACE_RELATIVE_PATH / "pp_vanilla_overrides_l_english.yml"
HEADER = (
    "l_english:\n"
    " # Generated by ppc finalize (loc_replace.py): vanilla keys the mod overrides, moved out of localization/english\n"
    " # (a key defined there and in vanilla loads twice). Rendered blueprint keys are moved again every build: edit\n"
    " # their text in the blueprint. Hand-written keys stay here once moved: edit them here.\n"
)

_LINE = re.compile(r'^[ \t]*([A-Za-z0-9_.\-\']+):(\d*)[ \t]*"(.*)"[ \t]*(?:#.*)?$')


def parse_line(line: str) -> tuple[str, str] | None:
    """(key, text) of a localization entry line, else None (header, comment, blank)."""
    match = _LINE.match(line.rstrip("\r\n"))
    if match is None or match[1].startswith("l_"):
        return None
    return match[1], match[3]


def read_entries(path: Path) -> dict[str, str]:
    entries: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8-sig", errors="replace").splitlines():
        parsed = parse_line(line)
        if parsed is not None:
            entries.setdefault(parsed[0], parsed[1])
    return entries


def vanilla_english(vanilla_game: Path) -> dict[str, str]:
    """Every key of vanilla's English localization (first definition), replace folders excluded."""
    keys: dict[str, str] = {}
    for path in sorted(vanilla_game.rglob("*_l_english.yml")):
        parts = path.relative_to(vanilla_game).parts
        if "localization" not in parts or "replace" in parts:
            continue
        for key, text in read_entries(path).items():
            keys.setdefault(key, text)
    return keys


def english_files(mod_root: Path) -> list[Path]:
    root = mod_root / ENGLISH_RELATIVE_PATH
    return sorted(root.rglob("*.yml")) if root.is_dir() else []


@dataclass
class Result:
    moved: dict[str, list[str]] = field(default_factory=dict)   # source file name -> keys moved this run
    dropped_equal: list[str] = field(default_factory=list)      # keys whose text is vanilla's
    kept: int = 0                                                # keys in the generated file
    files_changed: int = 0

    @property
    def moved_count(self) -> int:
        return sum(len(keys) for keys in self.moved.values())


def _generated_lines(path: Path) -> dict[str, str]:
    """key -> full entry line of the generated file."""
    lines: dict[str, str] = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            parsed = parse_line(line)
            if parsed is not None:
                lines[parsed[0]] = " " + line.strip()
    return lines


def apply(mod_root: Path, vanilla_game: Path) -> Result:
    vanilla = vanilla_english(vanilla_game)
    result = Result()
    target = mod_root / GENERATED_RELATIVE_PATH
    generated = _generated_lines(target)
    # keys other replace files already override stay where they are (a second replace definition would clash)
    other_replace: set[str] = set()
    replace_root = mod_root / REPLACE_RELATIVE_PATH
    if replace_root.is_dir():
        for path in sorted(replace_root.rglob("*.yml")):
            if path != target:
                other_replace.update(read_entries(path))
    for path in english_files(mod_root):
        raw = path.read_bytes().decode("utf-8-sig")   # bytes: a CRLF file keeps its line ends
        kept_lines: list[str] = []
        moved: list[str] = []
        for line in raw.splitlines(keepends=True):
            parsed = parse_line(line)
            if parsed is None or parsed[0] not in vanilla:
                kept_lines.append(line)
                continue
            key = parsed[0]
            moved.append(key)
            if key not in other_replace:
                generated[key] = " " + line.strip()
        if moved:
            result.moved[path.name] = moved
            path.write_text("".join(kept_lines), encoding="utf-8-sig", newline="")
            result.files_changed += 1
    for key in sorted(generated):
        if key in other_replace:   # another replace file owns it now (a second definition would clash)
            del generated[key]
            continue
        parsed = parse_line(generated[key])
        if parsed is not None and vanilla.get(key) == parsed[1]:
            result.dropped_equal.append(key)
            del generated[key]
    result.kept = len(generated)
    text = HEADER + "".join(f"{generated[key]}\n" for key in sorted(generated, key=str.lower))
    if not generated:
        if target.is_file():
            target.unlink()
            result.files_changed += 1
        return result
    if not target.is_file() or target.read_text(encoding="utf-8-sig") != text:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8-sig", newline="\n")
        result.files_changed += 1
    return result


def clashes(mod_root: Path, vanilla_game: Path) -> dict[str, list[str]]:
    """English files of the mod -> keys vanilla's English localization defines too (should be empty)."""
    vanilla = vanilla_english(vanilla_game)
    found: dict[str, list[str]] = {}
    for path in english_files(mod_root):
        keys = [key for key in read_entries(path) if key in vanilla]
        if keys:
            found[str(path.relative_to(mod_root))] = keys
    return found
