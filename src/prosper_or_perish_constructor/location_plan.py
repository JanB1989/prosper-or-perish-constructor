# one icon's size, scaled with the zoom like vanilla's marker (which caps at 85)
_ICON_SIZE = "[Min_CVector2f(Multiply_CVector2f(GetInverseZoom2, '(CVector2f)9333, 9333'), '(CVector2f)60, 60')]"
