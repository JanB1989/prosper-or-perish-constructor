def add_location_button(text: str) -> str:
    """The location window's header gets a button (player-owned locations) that opens the Location Plan window."""
    if BUTTON_MARK in text:
        return text
    anchor = 'blockoverride "lateralview_topbuttons_extra" {'
    if text.count(anchor) != 1:
        raise ValueError("location window: lateralview_topbuttons_extra block not found once")
    depth, index = 1, text.index(anchor) + len(anchor)
    while depth:
        depth += {"{": 1, "}": -1}.get(text[index], 0)
        index += 1
    line_start = text.rindex("\n", 0, index - 1) + 1
    return text[:line_start] + BUTTON.lstrip("\n") + text[line_start:]


