@dataclass(frozen=True)
class Candidate:
    """A building a target can build, with what the plan's cost formula needs of it."""

    name: str
    demand: str
    category: str
    ipl: float
    pop_type: str = "peasants"  # the workers a level needs (pp_cplan_staff); none = 0 peasants
    workers: float = 0.0

    @property
    def params(self) -> str:
        return (f"type = {self.name} demand = {self.demand} cat = {self.category} ipl = {cp._num(self.ipl)} "
                f"pt = {self.pop_type} sz = {cp._num(self.workers)}")


@dataclass
class Result:
    targets: dict[str, list[Candidate]] = field(default_factory=dict)  # target key -> buildings, expand order
    categories: dict[str, list[str]] = field(default_factory=dict)
    files_changed: int = 0


def target_goods(repo: Path, project: Path) -> list[str]:
    """The goods a target can be made for, in the Location Plan picker's order (without the hidden goods)."""
    return [good for good, _ in lp.picker_goods(repo, lp.load_config(project))]


