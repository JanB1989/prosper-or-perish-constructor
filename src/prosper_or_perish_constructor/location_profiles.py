def target_upgrades(candidates: list[Candidate], pairs: list[tuple[str, str]]) -> list[tuple[str, Candidate]]:
    """The tier steps of a target (town plans, 2026-11-19: a plan follows the tiers as they unlock): (older tier,
    successor) for every upgrade pair whose two buildings are both the target's, the highest successor first."""
    by_name = {c.name: c for c in candidates}
    order = [c.name for c in candidates]
    steps = [(older, by_name[successor]) for older, successor in pairs if older in by_name and successor in by_name]
    return sorted(steps, key=lambda step: (order.index(step[1].name), order.index(step[0])))


def render_targets(found: dict[str, list[Candidate]], pairs: list[tuple[str, str]] = ()) -> str:
    parts = [
        "\n# ---- Targets (location scope, in a plan's turn; scope:pp_lprof_pb = the payback limit + 100, far away for a plan) ----\n"
        "# A level under construction of any of the target's buildings here: the plan waits (pp_lprof_st 103). Else a\n"
        "# standing older tier whose successor (one of the target's buildings) the country has researched is upgraded\n"
        "# first, one level a turn (pp_lprof_upgrade: the game's Upgrade button; the tiers follow as they unlock); then a\n"
        "# standing one grows, highest tier first; where none stands, the cheapest that can be built here starts. Each\n"
        "# candidate that fails ranks its reason in pp_lprof_fail (pp_lprof_finish turns it into the plan's state).\n"
    ]
    for key, candidates in found.items():
        if not candidates:
            continue
        types = " ".join(f"building_type = building_type:{c.name}" for c in candidates)
        lines = [
            f"\npp_lprof_t_{key} = {{",
            "\tif = {",
            f"\t\tlimit = {{ any_buildings_in_location = {{ building_levels_under_construction > 0 OR = {{ {types} }} }} }}",
            "\t\tset_variable = { name = pp_lprof_st value = 103 }",
            "\t}",
            "\telse_if = {",
            f"\t\tlimit = {{ any_buildings_in_location = {{ building_level > 0 OR = {{ {types} }} }} }}",
        ]
        lines += [f"\t\tpp_lprof_upgrade = {{ old = {older} {c.params} }}" for older, c in target_upgrades(candidates, pairs)]
        lines += [f"\t\tpp_lprof_expand = {{ {c.params} }}" for c in candidates]
        lines += ["\t}", "\telse = {"]
        lines += [f"\t\tpp_lprof_start = {{ {c.params} }}" for c in candidates]
        lines += ["\t\tpp_lprof_start_pick = yes", "\t}", "}"]
        parts.append("\n".join(lines) + "\n")
    return "".join(parts)


def render_marks(plans: list[town_plans.Plan]) -> str:
    """The plans a location holds (town_plans.py, 2026-11-19: a plan is a town right): each held plan runs its target
    (or, where its producers need a higher rank, the plan's turn that raises it first), in the plans' order; n = 100 +
    its place there (the plan that measured the best payback is known by it), lo / hi the bounds around n."""
    lines = [
        "\n# ---- The location's plans (town rights pp_plan_<plan>, forced) ----\n"
        "# Location scope (in pp_lplan_location_turn, pp_location_profiles.txt): each held plan in the plans' order\n"
        "# (pp_lplan_mark, has_town_rights: its target pp_lprof_t_<target>, or pp_tplan_do_<plan> where it raises the rank\n"
        "# first; no payback limit, no market limit). Run twice a turn: once to measure (scope:pp_lplan_mode 1: the plan\n"
        "# whose next level pays back soonest is built first), once to build and to write the states. The first\n"
        "# construction of the turn in the location makes the rest wait. The window's ledger shows a plan's construction as\n"
        f"# the Locations group's, step {WHY_MARK_STEP}.\n"
        "pp_lplan_location_marks = {\n"
    ]
    for number, plan in enumerate(plans, 101):
        lines.append(f"\tpp_lplan_mark = {{ v = {plan.suffix} g = {plan.key} do = {plan.do} "
                     f"n = {number} lo = {number - 0.5:g} hi = {number + 0.5:g} }}\n")
    lines.append("}\n")
    return "".join(lines)


def render_effects(found: dict[str, list[Candidate]], plans: list[town_plans.Plan] | None = None,
                   pairs: list[tuple[str, str]] = ()) -> str:
    return HEADER + render_targets(found, pairs) + render_marks(plans or [])


