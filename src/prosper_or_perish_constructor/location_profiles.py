"""The plan engine of the Locations rule group (script side). Location Profiles and the building marks are gone
(2026-11-19, Jan: the town-right plan is the only per-location decision, ``town_plans.py``); the module and the script
names keep their old prefixes (``pp_lprof_*``, ``pp_lplan_*``) for what survived.

A location holds plans (town rights ``pp_plan_<plan>``). In the Construction Plan's monthly pass the Locations group
(internal key "profiles", construction code 105, its own purse) gives every location of the country that holds a plan
its turn, the locations taking turns (hand-written ``pp_lprof_look``, script value ``pp_lprof_turn``). In a location's
turn each held plan runs its target, forced: no payback limit and no market limit; inside one location the plans whose
next level has a profit to measure go first, the best payback first, then the rest in the plans' order (hand-written
``pp_lplan_location_turn``). Plans add: they switch nothing off in the global rule groups.

The engine is hand-written in the mod (``scripted_effects/pp_location_profiles.txt``); this module writes the parts
that follow the buildings and the plan list:

* ``scripted_effects/pp_location_profiles_generated.txt``: per target (a good, the food plan's ``food``, the trade
  plan's ``trade_category``) the buildings it builds (``pp_lprof_t_<target>``), and the location's plans in order
  (``pp_lplan_location_marks``);
* ``script_values/pp_location_profiles_generated.txt``: the group's weight switch and the pass's helper values;
* ``scripted_triggers/pp_location_profiles_generated.txt``: "the country has a location with a plan".

Targets: a good builds its producers (the buildings whose main good it is, as the Construction Plan's goods rules), a
building category the player-buildable building types of that category (no foreign, special, estate, organisation or
event-only buildings), food the producers of the staple foods and the Province Food buildings. A standing older tier
whose successor the country has researched is upgraded first; a standing building grows highest tier first; where none
of the target's buildings stands, the cheapest one that can be built here starts (its first level has no profit to
measure). Variables carry + 100 (a variable at 0 counts as unset; ``var:x = n`` compares scopes).
"""

