def _block_end(text: str, start: int) -> int:
    """End of the brace block opened at or after start (comments and strings skipped)."""
    depth, index, opened = 0, start, False
    while True:
        char = text[index]
        if char == "#":
            index = text.index("\n", index)
            continue
        if char == '"':
            index = text.index('"', index + 1) + 1
            continue
        if char == "{":
            depth += 1
            opened = True
        elif char == "}":
            depth -= 1
            if opened and depth == 0:
                return index + 1
        index += 1


