def patch_context_menu(vanilla: str, config: Config) -> str:
    """Vanilla's context_menu.gui with the Location Profile section added to LocationContextMenu, before the player's
    own country section (the only change)."""
    if vanilla.count(_MENU_TYPE) != 1:
        raise ValueError("context_menu.gui: LocationContextMenu not found once")
    start = vanilla.index(_MENU_TYPE)
    end = _block_end(vanilla, start)
    block = vanilla[start:end]
    if block.count(_MENU_ANCHOR) != 1:
        raise ValueError("context_menu.gui: the player location's country section not found once in LocationContextMenu")
    anchor = start + block.index(_MENU_ANCHOR)
    return vanilla[:anchor] + menu_section(config) + "\n" + vanilla[anchor:]


