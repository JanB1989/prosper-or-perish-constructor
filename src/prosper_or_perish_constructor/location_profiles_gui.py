def _icon_button(icon: str, tab: str, **props: str) -> str:
    lines = [f"{tab}pp_lprof_icon_button = {{\n", f"{tab}\tblockoverride \"pp_lprof_icon\" {{ texture = \"{FLAT.format(icon)}\" }}\n"]
    for name, value in props.items():
        for single in value.split("\n"):
            lines.append(f"{tab}\t{name.rstrip('_')} = \"{single}\"\n")
    lines.append(f"{tab}}}\n")
    return "".join(lines)


