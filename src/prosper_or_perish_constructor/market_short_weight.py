"""Short market weight (branch stockpile-prices, 2026-11-02, Jan): the AI reacts a little when its market runs short of a good.

The finalize step of ``ppc build`` / ``ppc sync`` gives every producer's ``ai_construct_weight``, as its last line (after
any income divide), ``add = pp_market_short_<good>`` for the building's main good. One script value per good:

    amount x clamp(1 - market stock / monthly market demand) x clamp(owner tax base / tax_base_full)

only where the market's monthly demand is above demand_floor. Full at an empty market, 0 from one month of stock, so the
term only touches markets in shortage and leaves a market in its band alone. The tax base part keeps small countries with
idle gold from building on it. A building without a weight gets a new block with only this term.

A weight is added to the score after the engine's multipliers: it can tip a site that was narrowly negative, a site the
engine scores exactly 0 (profit gate, rural producer next to a town) stays 0, so no gate and no rule opens. Nothing here
changes output, recipes, prices or costs. Tests and numbers: docs/ai_building_rulebook.md "Short market weight".
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
import re
import tomllib

from prosper_or_perish_constructor.building_footprint import vanilla_files

OUTPUT = Path("in_game/common/script_values/pp_market_short_weight.txt")
BUILDING_TYPES = Path("in_game/common/building_types")
PRODUCTION_METHODS = Path("in_game/common/production_methods")
GOODS = Path("in_game/common/goods")
VALUE_PREFIX = "pp_market_short_"
LEG_SUFFIX = "_market_sales"
HEADER = (
    "﻿# Generated by ppc finalize (market_short_weight.py) from [market_short_weight]; do not edit by hand.\n"
    "# Location scope: added last to the ai_construct_weight of every producer of the good.\n\n"
)
_PREFIX = re.compile(r"^(REPLACE|INJECT|TRY_INJECT|TRY_REPLACE|REPLACE_OR_CREATE|INJECT_OR_CREATE):(.+)$")
_INJECT_MODES = {"INJECT", "TRY_INJECT", "INJECT_OR_CREATE"}
_OLD_LINE = re.compile(rf"^[ \t]*add = {VALUE_PREFIX}\w+[ \t]*\r?\n", re.MULTILINE)
_OLD_INLINE = re.compile(rf" add = {VALUE_PREFIX}\w+ ")
_OPS = ("?=", "<=", ">=", "!=", "==", "=", "<", ">")


@dataclass(frozen=True)
class Config:
    amount: float
    demand_floor: float
    tax_base_full: float
    not_goods: frozenset[str]


@dataclass
class Result:
    producers: int = 0
    goods: int = 0
    files_changed: int = 0
    new_blocks: int = 0
    main_good: dict[str, str] = field(default_factory=dict)
    not_in_mod: list[str] = field(default_factory=list)


def load_config(project: Path) -> Config:
    section = tomllib.loads(Path(project).read_text(encoding="utf-8-sig"))["market_short_weight"]
    return Config(float(section["amount"]), float(section["demand_floor"]), float(section["tax_base_full"]), frozenset(section["not_goods"]))


# ---------------------------------------------------------------- script text with offsets


@dataclass
class _Node:
    key: str
    value: str | None
    children: list["_Node"] | None
    body_end: int = -1  # offset of the block's "}"

    def get(self, key: str) -> "_Node | None":
        return next((child for child in self.children or [] if child.key == key), None)


def _tokens(text: str) -> list[tuple[str, str, int]]:
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c in " \t\r\n﻿":
            i += 1
        elif c == "#":
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif c == '"':
            j = text.find('"', i + 1)
            j = n - 1 if j < 0 else j
            out.append(("word", text[i: j + 1], i))
            i = j + 1
        elif c in "{}":
            out.append((c, c, i))
            i += 1
        elif text.startswith(_OPS, i):
            op = next(op for op in _OPS if text.startswith(op, i))
            out.append(("op", op, i))
            i += len(op)
        else:
            j = i
            while j < n and text[j] not in " \t\r\n{}=<>!?#\"":
                j += 1
            j = max(j, i + 1)  # a lone ! or ?
            out.append(("word", text[i:j], i))
            i = j
    return out


def parse(text: str) -> list[_Node]:
    tokens = _tokens(text)
    pos = 0

    def block(nested: bool) -> list[_Node]:
        nonlocal pos
        nodes: list[_Node] = []
        while pos < len(tokens):
            kind, value, _ = tokens[pos]
            if kind == "}":
                if nested:
                    return nodes
                pos += 1
                continue
            pos += 1
            if kind == "{":
                children = block(True)
                end = tokens[pos][2] if pos < len(tokens) else len(text)
                pos += 1
                nodes.append(_Node("", None, children, end))
            elif pos < len(tokens) and tokens[pos][0] == "op":
                pos += 1
                if pos < len(tokens) and tokens[pos][0] == "{":
                    pos += 1
                    children = block(True)
                    end = tokens[pos][2] if pos < len(tokens) else len(text)
                    pos += 1
                    nodes.append(_Node(value, None, children, end))
                elif pos < len(tokens):
                    nodes.append(_Node(value, tokens[pos][1], None))
                    pos += 1
            else:
                nodes.append(_Node(value, None, None))
        return nodes

    return block(False)


def _read(path: Path) -> str:
    with open(path, encoding="utf-8", newline="") as handle:
        return handle.read()


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)


def _load_order(relative: Path, mod_root: Path, vanilla_root: Path) -> list[tuple[Path, bool]]:
    """(path, from the mod) in the game's order: one list by file name, a mod file shadowing vanilla's of the same name."""
    files = {path.name: (path, False) for path in vanilla_files(vanilla_root, relative) if path.name != "readme.txt"}
    files |= {path.name: (path, True) for path in (mod_root / relative).glob("*.txt")}
    return [files[name] for name in sorted(files)]


def _split_key(key: str) -> tuple[str, str]:
    match = _PREFIX.match(key)
    return (match.group(1), match.group(2)) if match else ("", key)


# ---------------------------------------------------------------- who makes what


@dataclass(frozen=True)
class Method:
    name: str
    produced: str | None
    output: float


def _method(name: str, node: _Node) -> Method:
    produced = node.get("produced")
    output = node.get("output")
    try:
        amount = float(output.value) if output is not None and output.value is not None else 0.0
    except ValueError:
        amount = 0.0
    return Method(name, produced.value if produced is not None else None, amount)


def main_good(slots: list[list[Method]], prices: dict[str, float], not_goods: frozenset[str]) -> str | None:
    """The good the building is there for: its market leg's (the gate follows that price), else its largest output by value."""
    outputs: dict[str, float] = {}
    leg = None
    for slot in slots:
        for method in slot:
            if method.produced and method.output > 0:
                outputs[method.produced] = max(outputs.get(method.produced, 0.0), method.output)
                if method.name.endswith(LEG_SUFFIX):
                    leg = method.produced
    real = {good: amount for good, amount in outputs.items() if good not in not_goods and good in prices}
    if not real:
        return None
    return leg if leg in real else max(real, key=lambda good: real[good] * prices[good])


def _goods_prices(mod_root: Path, vanilla_root: Path) -> dict[str, float]:
    prices: dict[str, float] = {}
    for path, _ in _load_order(GOODS, mod_root, vanilla_root):
        for node in parse(_read(path)):
            if node.children is None:
                continue
            mode, name = _split_key(node.key)
            if not mode or mode.endswith("REPLACE"):
                prices[name] = 1.0
            elif name not in prices:
                continue
            price = node.get("default_market_price")
            if price is not None and price.value is not None:
                prices[name] = float(price.value)
    return prices


@dataclass
class _Type:
    name: str
    path: Path
    node: _Node
    from_mod: bool
    slots: list[list[Method]] = field(default_factory=list)
    weight_path: Path | None = None
    weight: _Node | None = None


def _types(mod_root: Path, vanilla_root: Path, texts: dict[Path, str]) -> dict[str, _Type]:
    """The effective building types. `texts` holds the building files of the mod being edited: offsets must fit those."""
    shared: dict[str, Method] = {}
    for path, _ in _load_order(PRODUCTION_METHODS, mod_root, vanilla_root):
        for node in parse(_read(path)):
            if node.children is not None:
                name = _split_key(node.key)[1]
                shared[name] = _method(name, node)
    types: dict[str, _Type] = {}
    for path, from_mod in _load_order(BUILDING_TYPES, mod_root, vanilla_root):
        for node in parse(texts[path] if path in texts else _read(path)):
            if node.children is None or not node.key:
                continue
            mode, name = _split_key(node.key)
            inject = mode in _INJECT_MODES
            if inject and name not in types and mode != "INJECT_OR_CREATE":
                continue
            building = types.get(name)
            if not inject or building is None:
                building = types[name] = _Type(name, path, node, from_mod)
            for child in node.children:
                if child.key == "unique_production_methods":
                    building.slots.append([_method(m.key, m) for m in child.children or [] if m.children is not None])
                elif child.key == "possible_production_methods":
                    building.slots.append([shared[m.key] for m in child.children or [] if m.key in shared])
                elif child.key == "ai_construct_weight":
                    building.weight_path, building.weight = path, child
    return types


# ---------------------------------------------------------------- writing


def _strip_terms(text: str) -> str:
    return _OLD_INLINE.sub("", _OLD_LINE.sub("", text))


def _line_start(text: str, offset: int) -> int:
    return text.rfind("\n", 0, offset) + 1


def _insertion(text: str, close: int, line: str) -> tuple[int, str]:
    """Where and what to insert so `line` (ends in a newline) is the last in the block closing at `close`."""
    newline = "\r\n" if "\r\n" in text else "\n"
    start = _line_start(text, close)
    if not text[start:close].strip():
        return start, line.replace("\n", newline)
    if line.count("\n") == 1:
        return close, f" {line.strip()} "
    return close, newline + line.replace("\n", newline)


def render_value(good: str, config: Config) -> str:
    demand = f"goods_demand_in_market(goods:{good})"
    return (
        f"{VALUE_PREFIX}{good} = {{\n"
        "    value = 0\n"
        "    if = {\n"
        f'        limit = {{ market ?= {{ "{demand}" > {config.demand_floor:g} }} }}\n'
        "        add = {\n"
        "            value = 1\n"
        f'            subtract = {{ value = "market.stockpile_in_market(goods:{good})" divide = "market.{demand}" }}\n'
        "            min = 0\n"
        "            max = 1\n"
        f"            multiply = {config.amount:g}\n"
        f"            multiply = {{ value = owner.country_tax_base divide = {config.tax_base_full:g} max = 1 }}\n"
        "        }\n"
        "    }\n"
        "}\n"
    )


def apply(project: Path, mod_root: Path, vanilla_root: Path, write: bool = True) -> Result:
    """Bring the mod's weights in step. Starts from the weights without this term, so it can run on a finalized mod."""
    config = load_config(project)
    prices = _goods_prices(mod_root, vanilla_root)
    before = {path: _read(path) for path in sorted((mod_root / BUILDING_TYPES).glob("*.txt"))}
    bare = {path: _strip_terms(text) for path, text in before.items()}
    types = _types(mod_root, vanilla_root, bare)
    result = Result()
    inserts: dict[Path, list[tuple[int, str]]] = {}
    for name, building in sorted(types.items()):
        good = main_good(building.slots, prices, config.not_goods)
        if good is None:
            continue
        if not building.from_mod or (building.weight_path is not None and building.weight_path not in bare):
            result.not_in_mod.append(name)
            continue
        value = f"{VALUE_PREFIX}{good}"
        if building.weight is not None:
            text = bare[building.weight_path]
            inserts.setdefault(building.weight_path, []).append(_insertion(text, building.weight.body_end, f"    add = {value}\n"))
        else:
            text = bare[building.path]
            block = f"ai_construct_weight = {{\n    value = 0\n    add = {value}\n}}\n"
            inserts.setdefault(building.path, []).append(_insertion(text, building.node.body_end, block))
            result.new_blocks += 1
        result.main_good[name] = good
    result.producers = len(result.main_good)
    goods = sorted(set(result.main_good.values()))
    result.goods = len(goods)
    rendered = HEADER + "\n".join(render_value(good, config) for good in goods)
    for path in bare:
        text = bare[path]
        out, last = [], 0
        for offset, line in sorted(inserts.get(path, []), key=lambda item: item[0]):
            out += [text[last:offset], line]
            last = offset
        out.append(text[last:])
        joined = "".join(out)
        if joined != before[path]:
            result.files_changed += 1
            if write:
                _write(path, joined)
    output = mod_root / OUTPUT
    if not output.is_file() or _read(output) != rendered:
        result.files_changed += 1
        if write:
            _write(output, rendered)
    return result
