"""Plans free their workers (branch town-plans, 2026-11-20, Jan).

Jan: "You conquer or get a city with a bunch of businesses the AI built, and you want to specialize it ... at some point
there is a worker shortage. Then, step by step, the other businesses that are not part of the location's plans should
be turned off in that location, so they release the workers and we can use them. It should happen automatically,
probably by profitability ..."

Script cannot close a building. A building scope can sit in a country variable list, and an always-present hidden
scripted widget (``gui/pp_plan_closer.gui``) closes each listed building through the game's own GUI function and takes
it off the list with a scripted GUI (``pp_pclose_ack``); a second list reopens (in game 2026-11-20, prototype). The
rule (hand-written ``scripted_effects/pp_plan_closer.txt`` and ``scripted_triggers/pp_plan_closer.txt``, called by the
plan engine ``pp_location_profiles.txt``): where a plan's next level waits for workers and nothing else, the location's
turn puts ONE other business of the player's there on the close list, the one that earns least per worker
(``pp_pclose_rank``), then waits two looks. ``docs/location_plan.md`` "Plans free their workers".

This module writes what the rule needs from the building and plan lists,
``in_game/common/scripted_triggers/pp_plan_closer_generated.txt`` (building scope):

* ``pp_pclose_planned``: the building is a candidate of a plan its location holds (``scope:pp_pclose_l``);
* ``pp_pclose_never_type``: a building the rule never closes: logistics, improvements (capacity), the public buildings
  of the Towns and Buildings group (every tier of their lines);
* ``pp_pclose_food_type``: a Province Food maker or staple food producer (the Food plan's buildings and the food
  rule's kitchens, taverns, granaries, granges and yards): closed only while the province's store is not short;
* ``pp_pclose_pt_match``: the building's workers are the pop type the asking plan's building needs
  (``scope:pp_pclose_pt``; peasants are checked beside it in ``pp_pclose_candidate``).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from prosper_or_perish_constructor import town_plans

TRIGGERS = Path("in_game/common/scripted_triggers/pp_plan_closer_generated.txt")
HAND_EFFECTS = Path("in_game/common/scripted_effects/pp_plan_closer.txt")
HAND_TRIGGERS = Path("in_game/common/scripted_triggers/pp_plan_closer.txt")
HAND_VALUES = Path("in_game/common/script_values/pp_plan_closer.txt")
SCRIPTED_GUIS = Path("in_game/common/scripted_guis/pp_plan_closer.txt")
GUI = Path("in_game/gui/pp_plan_closer.gui")
WIDGET = Path("in_game/gui/scripted_widgets/pp_plan_closer.txt")
HEADER = "﻿# Generated by ppc finalize (plan_closer.py) from the plan and building lists; do not edit by hand.\n"

# Names (the contract the hand-written script, the GUI and the tests share)
CLOSE_LIST = "pp_pclose_now"  # country: the buildings the widget closes (emptied at every monthly pass's start)
OPEN_LIST = "pp_popen_now"  # country: the buildings the widget reopens
ACK_GUI = "pp_pclose_ack"  # scripted GUI: the widget took the building (scope:pp_b) off both lists
LOCATIONS_LIST = "pp_pclose_locs"  # country: the locations where the rule closed something
TYPES_LIST = "pp_pclose_types"  # location: the building types the rule closed there
KEEP_LIST = "pp_pclose_keep"  # location: types the player opened again by hand (never closed again there)
FOR_LIST = "pp_pclose_for"  # location: the plans (town rights) the closings there are for
WAIT_VAR = "pp_pclose_wait"  # location: + 100, the looks the location still waits after a closing
WAIT_LOOKS = 2  # a closing, then no closing in the next look; the second look after it may close again
FAIL_CLOSE = 104.25  # pp_lprof_fail: the plan's level waits for workers and nothing else (state 14 while closing)
STATE = 14  # the plan state "closing another business here to free workers"
OFF_VAR = town_plans.FREE_OFF_VAR  # country: set = the setting is off


@dataclass
class Result:
    plans: int = 0
    never: list[str] = field(default_factory=list)
    food: list[str] = field(default_factory=list)
    pop_types: list[str] = field(default_factory=list)
    files_changed: int = 0


def never_types(repo: Path, project: Path, mod_root: Path, vanilla_root: Path, known: set[str]) -> list[str]:
    """Logistics buildings, improvements (World Builder caps that add capacity) and every tier of the Towns and
    Buildings group's public buildings."""
    from prosper_or_perish_constructor import arable_land_bar
    from prosper_or_perish_constructor import construction_plan as cp
    from prosper_or_perish_constructor import construction_plan_country as cc

    names = set(cp.load_config(project).logistics_order)
    names |= {b.key for b in arable_land_bar.model(mod_root, vanilla_root / "game").improvements}
    lines, _, _ = cc.building_lines(cc.database(mod_root, vanilla_root, cc.BUILDING_TYPES),
                                    cc.load_config(project).public_buildings)
    names |= {tier for tiers in lines.values() for tier in tiers}
    return sorted(names & known)


def food_types(project: Path, plans: list[town_plans.Plan], known: set[str]) -> list[str]:
    """The Food plan's buildings (staple food producers and Province Food buildings) and the food rule's own."""
    from prosper_or_perish_constructor import construction_plan as cp

    config = cp.load_config(project)
    names = {name for plan in plans if plan.key == "food" for name in plan.candidates}
    names |= set(config.kitchens) | set(config.taverns) | set(config.granaries) | set(config.granges) | set(config.yards)
    return sorted(names & known)


def _types(names: list[str], tab: str) -> str:
    return "".join(f"{tab}building_type = building_type:{name}\n" for name in names)


def render_triggers(plans: list[town_plans.Plan], never: list[str], food: list[str], pop_types: list[str]) -> str:
    parts = [
        HEADER,
        "\n# Building scope, scope:pp_pclose_l = its location (pp_pclose_pick): a building the location's plans want, a\n"
        "# candidate of a plan the location holds (the plan's target, older tiers of its lines included).\n"
        "pp_pclose_planned = {\n\tOR = {\n",
    ]
    for plan in plans:
        parts.append(
            f"\t\tAND = {{\n\t\t\tscope:pp_pclose_l = {{ has_town_rights = town_rights_type:{plan.right} }}\n"
            "\t\t\tOR = {\n" + _types(sorted(plan.candidates), "\t\t\t\t") + "\t\t\t}\n\t\t}\n"
        )
    parts.append("\t}\n}\n")
    parts.append(
        "\n# Building scope: a building the rule never closes: logistics, improvements (capacity) and the public\n"
        "# buildings of the Towns and Buildings group, every tier.\n"
        "pp_pclose_never_type = {\n\tOR = {\n" + _types(never, "\t\t") + "\t}\n}\n"
    )
    parts.append(
        "\n# Building scope: a Province Food maker or staple food producer (closed only while the province's store is not\n"
        "# short, pp_pclose_candidate).\n"
        "pp_pclose_food_type = {\n\tOR = {\n" + _types(food, "\t\t") + "\t}\n}\n"
    )
    parts.append(
        "\n# Building scope, scope:pp_pclose_pt = the pop type the asking plan's building needs: the building's workers are\n"
        "# of that type (peasants are checked beside it).\n"
        "pp_pclose_pt_match = {\n\tOR = {\n"
        + "".join(f"\t\tAND = {{\n\t\t\tbuilding_pop_type = {pt}\n\t\t\tscope:pp_pclose_pt = pop_type:{pt}\n\t\t}}\n"
                  for pt in pop_types)
        + "\t}\n}\n"
    )
    return "".join(parts)


def inputs(repo: Path, project: Path, mod_root: Path, vanilla_root: Path):
    from prosper_or_perish_constructor import construction_plan as cp
    from prosper_or_perish_constructor import construction_plan_country as cc

    # the building types after the load order, without those only a DLC folder defines (AGENTS.md "DLC Content": their
    # keys must not appear in the mod's script)
    known = {name for name, entry in cc.database(mod_root, vanilla_root, cc.BUILDING_TYPES).items() if not entry.dlc_only}
    plans = town_plans.plans(repo, project, mod_root, vanilla_root)
    never = never_types(repo, project, mod_root, vanilla_root, known)
    food = food_types(project, plans, known)
    pop_types = sorted(set(cp._database(mod_root, vanilla_root, cp.POP_TYPES)) - {"peasants"})
    return plans, never, food, pop_types


def apply(repo: Path, project: Path, mod_root: Path, vanilla_root: Path, write: bool = True) -> Result:
    plans, never, food, pop_types = inputs(repo, project, mod_root, vanilla_root)
    result = Result(plans=len(plans), never=never, food=food, pop_types=pop_types)
    text = render_triggers(plans, never, food, pop_types)
    path = mod_root / TRIGGERS
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    if old != text:
        result.files_changed = 1
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    return result


def summary(result: Result) -> str:
    return (f"Plans free their workers: {result.plans} plans, {len(result.never)} building types never closed, "
            f"{len(result.food)} food buildings, {len(result.pop_types) + 1} pop types, {result.files_changed} files changed.")
