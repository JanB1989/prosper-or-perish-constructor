"""Plans free their workers (branch town-plans, 2026-11-20, Jan).

Jan: "You conquer or get a city with a bunch of businesses the AI built, and you want to specialize it ... at some point
there is a worker shortage. Then, step by step, the other businesses that are not part of the location's plans should
be turned off in that location, so they release the workers and we can use them. It should happen automatically,
probably by profitability ..."

Script cannot close a building. A building scope can sit in a country variable list, and an always-present hidden
scripted widget (``gui/pp_plan_closer.gui``) closes each listed building through the game's own GUI function and takes
it off the list with a scripted GUI (``pp_pclose_ack``); a second list reopens (in game 2026-11-20, prototype). The
rule (hand-written ``scripted_effects/pp_plan_closer.txt`` and ``scripted_triggers/pp_plan_closer.txt``, called by the
plan engine ``pp_location_profiles.txt``): where a plan's next level waits for workers and nothing else, the location's
turn puts ONE other business of the player's there on the close list, the one that earns least per worker
(``pp_pclose_rank``), then waits two looks. ``docs/location_plan.md`` "Plans free their workers".

This module writes what the rule needs from the building and plan lists. Per plan the location variable
``pp_pclose_for_<plan>`` says the closings there are for that plan (set by ``pp_pclose_plan``); over them
``in_game/common/scripted_effects/pp_plan_closer_generated.txt`` holds ``pp_pclose_for_clear`` (location scope: none
of them left) and the triggers file ``pp_pclose_for_held`` (location scope: the location still holds a plan the
closings are for). ``in_game/common/scripted_triggers/pp_plan_closer_generated.txt`` (building scope):

* ``pp_pclose_planned``: the building is a candidate of a plan its location holds (``scope:pp_pclose_l``);
* ``pp_pclose_never_type``: a building the rule never closes: logistics, improvements (capacity), the public buildings
  of the Towns and Buildings group (every tier of their lines);
* ``pp_pclose_food_type``: a Province Food maker or staple food producer (the Food plan's buildings and the food
  rule's kitchens, taverns, granaries, granges and yards): closed only while the province's store is not short;
* ``pp_pclose_pt_match``: the building's workers are the pop type the asking plan's building needs
  (``scope:pp_pclose_pt``; peasants are checked beside it in ``pp_pclose_candidate``).
"""

