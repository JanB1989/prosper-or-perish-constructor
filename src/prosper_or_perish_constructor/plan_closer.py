def _block_end(text: str, open_brace: int) -> int:
    depth = 0
    quoted = comment = False
    for i in range(open_brace, len(text)):
        c = text[i]
        if comment:
            comment = c != "\n"
        elif quoted:
            quoted = c != '"'
        elif c == "#":
            comment = True
        elif c == '"':
            quoted = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("location window: unbalanced block")


def add_row_locks(text: str) -> str:
    """The padlock in the top right corner of each pop type row's header card (location window, buildings list):
    placed after the header's own button, so it lies on top of it and takes its clicks."""
    if ROW_MARK in text:
        return text
    if text.count(_ROW_ANCHOR) != 1:
        raise ValueError("location window: the pop type row's header button not found once")
    start = text.rindex(_ROW_HEADER, 0, text.index(_ROW_ANCHOR))
    line_start = text.rindex("\n", 0, start) + 1
    tab = text[line_start:start]
    if tab.strip():
        raise ValueError("location window: the pop type row's header button no longer starts its line")
    end = text.index("\n", _block_end(text, text.index("{", start))) + 1
    button = "".join(tab + line + "\n" for line in _ROW_BUTTON.splitlines())
    return text[:end] + button + text[end:]


@dataclass
class Result:
    plans: int = 0
    never: list[str] = field(default_factory=list)
    food: list[str] = field(default_factory=list)
    pop_types: list[str] = field(default_factory=list)
    files_changed: int = 0


def never_types(repo: Path, project: Path, mod_root: Path, vanilla_root: Path, known: set[str]) -> list[str]:
    """Logistics buildings, improvements (World Builder caps that add capacity), every tier of the Towns and
    Buildings group's public buildings, and every building with a goods output: nobody can close a production building
    since 2026-11-27 (building_shutdown.py writes can_close = no; the game's close function refuses it), so the rule
    must not list one."""
    from prosper_or_perish_constructor import arable_land_bar
    from prosper_or_perish_constructor import building_shutdown
    from prosper_or_perish_constructor import construction_plan as cp
    from prosper_or_perish_constructor import construction_plan_country as cc

    names = set(cp.load_config(project).logistics_order)
    names |= set(building_shutdown.producers(repo, mod_root, vanilla_root))
    names |= {b.key for b in arable_land_bar.model(mod_root, vanilla_root / "game").improvements}
    lines, _, _ = cc.building_lines(cc.database(mod_root, vanilla_root, cc.BUILDING_TYPES),
                                    cc.load_config(project).public_buildings)
    names |= {tier for tiers in lines.values() for tier in tiers}
    return sorted(names & known)


def food_types(project: Path, plans: list[town_plans.Plan], known: set[str]) -> list[str]:
    """The Food plan's buildings (staple food producers and Province Food buildings) and the food rule's own."""
    from prosper_or_perish_constructor import construction_plan as cp

    config = cp.load_config(project)
    names = {name for plan in plans if plan.key == "food" for name in plan.candidates}
    names |= set(config.kitchens) | set(config.taverns) | set(config.granaries) | set(config.granges) | set(config.yards)
    return sorted(names & known)


def _types(names: list[str], tab: str) -> str:
    return "".join(f"{tab}building_type = building_type:{name}\n" for name in names)


def render_triggers(plans: list[town_plans.Plan], never: list[str], food: list[str], pop_types: list[str]) -> str:
    parts = [
        HEADER,
        "\n# Building scope, scope:pp_pclose_l = its location (pp_pclose_pick): a building the location's plans want, a\n"
        "# candidate of a plan the location holds (the plan's target, older tiers of its lines included).\n"
        "pp_pclose_planned = {\n\tOR = {\n",
    ]
    for plan in plans:
        parts.append(
            f"\t\tAND = {{\n\t\t\tscope:pp_pclose_l = {{ has_variable = {plan.var} }}\n"
            "\t\t\tOR = {\n" + _types(sorted(plan.candidates), "\t\t\t\t") + "\t\t\t}\n\t\t}\n"
        )
    parts.append("\t}\n}\n")
    parts.append(
        "\n# Location scope: the location still holds a plan the closings here are for (pp_pclose_needed): a plan with\n"
        f"# {FOR_PREFIX}<plan> (pp_pclose_plan) whose marker the location carries.\n"
        f"{FOR_HELD} = {{\n\tOR = {{\n"
        + "".join(f"\t\tAND = {{\n\t\t\thas_variable = {FOR_PREFIX}{plan.key}\n\t\t\thas_variable = {plan.var}\n\t\t}}\n"
                  for plan in plans)
        + "\t}\n}\n"
    )
    parts.append(
        "\n# Building scope: a building the rule never closes: logistics, improvements (capacity) and the public\n"
        "# buildings of the Towns and Buildings group, every tier.\n"
        "pp_pclose_never_type = {\n\tOR = {\n" + _types(never, "\t\t") + "\t}\n}\n"
    )
    parts.append(
        "\n# Building scope: a Province Food maker or staple food producer (closed only while the province's store is not\n"
        "# short, pp_pclose_candidate).\n"
        "pp_pclose_food_type = {\n\tOR = {\n" + _types(food, "\t\t") + "\t}\n}\n"
    )
    parts.append(
        "\n# Building scope, scope:pp_pclose_pt = the pop type the asking plan's building needs: the building's workers are\n"
        "# of that type (peasants are checked beside it).\n"
        "pp_pclose_pt_match = {\n\tOR = {\n"
        + "".join(f"\t\tAND = {{\n\t\t\tbuilding_pop_type = {pt}\n\t\t\tscope:pp_pclose_pt = pop_type:{pt}\n\t\t}}\n"
                  for pt in pop_types)
        + "\t}\n}\n"
    )
    return "".join(parts)


def render_effects(plans: list[town_plans.Plan], pop_types: list[str]) -> str:
    return (
        HEADER
        + "\n# Location scope: the closings here are for no plan any more (pp_pclose_undo, pp_pclose_forget).\n"
        f"{FOR_CLEAR} = {{\n"
        + "".join(f"\tremove_variable = {FOR_PREFIX}{plan.key}\n" for plan in plans)
        + "}\n"
        + f"\n# Location scope, scope:pp_key = flag:<pop type> (scripted GUI {ROW_GUI}): the row lock of that pop type.\n"
        f"{ROW_PICK} = {{\n"
        + "".join(f"\tif = {{\n\t\tlimit = {{ scope:pp_key = flag:{pt} }}\n\t\tpp_row_toggle_do = {{ pt = {pt} }}\n\t}}\n"
                  for pt in sorted({*pop_types, "peasants"}))
        + "}\n"
    )


def inputs(repo: Path, project: Path, mod_root: Path, vanilla_root: Path):
    from prosper_or_perish_constructor import construction_plan as cp
    from prosper_or_perish_constructor import construction_plan_country as cc

    # the building types after the load order, without those only a DLC folder defines (AGENTS.md "DLC Content": their
    # keys must not appear in the mod's script)
    known = {name for name, entry in cc.database(mod_root, vanilla_root, cc.BUILDING_TYPES).items() if not entry.dlc_only}
    plans = town_plans.plans(repo, project, mod_root, vanilla_root)
    never = never_types(repo, project, mod_root, vanilla_root, known)
    food = food_types(project, plans, known)
    pop_types = sorted(set(cp._database(mod_root, vanilla_root, cp.POP_TYPES)) - {"peasants"})
    return plans, never, food, pop_types


def apply(repo: Path, project: Path, mod_root: Path, vanilla_root: Path, write: bool = True) -> Result:
    plans, never, food, pop_types = inputs(repo, project, mod_root, vanilla_root)
    result = Result(plans=len(plans), never=never, food=food, pop_types=pop_types)
    texts = {mod_root / TRIGGERS: render_triggers(plans, never, food, pop_types),
             mod_root / EFFECTS: render_effects(plans, pop_types)}
    for path, text in texts.items():
        old = path.read_text(encoding="utf-8") if path.is_file() else None
        if old != text:
            result.files_changed += 1
            if write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    return result


def summary(result: Result) -> str:
    return (f"Plans free their workers: {result.plans} plans, {len(result.never)} building types never closed, "
            f"{len(result.food)} food buildings, {len(result.pop_types) + 1} pop types, {result.files_changed} files changed.")
