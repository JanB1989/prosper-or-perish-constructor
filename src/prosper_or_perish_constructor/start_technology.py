def building_gates(ladder: Ladder, advances: dict[str, Advance]) -> list[tuple[str, str, int]]:
    """(building, unlocking advance, its ladder level) for every building whose first-age unlockers are all ladder
    advances (later-age unlockers count as not held at the start). A building with another first-age unlocker is not
    gated (that advance's conditions cannot be read offline)."""
    unlockers: dict[str, set[str]] = defaultdict(set)
    for key, adv in advances.items():
        if adv.age != AGE1:
            continue
        for value in _values(adv.body, "unlock_building"):
            if isinstance(value, str):
                unlockers[value].add(key)
    rows = []
    for building, keys in sorted(unlockers.items()):
        if keys <= set(ladder.levels):
            rows += [(building, key, ladder.levels[key]) for key in sorted(keys)]
    return rows


def render_building_table(rows: list[tuple[str, str, int]]) -> str:
    return _csv_text(BUILDINGS_HEADER, [dict(zip(BUILDINGS_HEADER, row)) for row in rows])


def load_building_table(repo: Path) -> dict[str, tuple[str, int]]:
    """building -> (the unlocking ladder advance with the lowest level, that level)."""
    path = Path(repo) / BUILDINGS_CSV
    if not path.is_file():
        return {}
    out: dict[str, tuple[str, int]] = {}
    with path.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            level = int(row["level"])
            if row["building"] not in out or level < out[row["building"]][1]:
                out[row["building"]] = (row["advance"], level)
    return out


