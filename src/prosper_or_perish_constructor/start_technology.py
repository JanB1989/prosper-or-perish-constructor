# ---------------------------------------------------------------------------------------------- statement parser
_TOKEN = re.compile(
    r'(?P<space>\s+)|(?P<comment>\#[^\n]*)|(?P<string>"(?:[^"\\]|\\.)*")|(?P<math>@\[[^\]\n]*\])'
    r"|(?P<brace>[{}])|(?P<op>\?=|<=|>=|!=|==|=|<|>)|(?P<atom>[^\s{}#<>=!?\"]+|[?!])"
)


@dataclass(frozen=True)
class Stmt:
    """One statement of a block: ``key op value`` or a bare item (``key`` None). ``value`` is a token (quotes kept)
    or a tuple of statements."""

    key: str | None
    op: str | None
    value: str | tuple["Stmt", ...]

    @property
    def is_block(self) -> bool:
        return isinstance(self.value, tuple)


def _tokens(text: str) -> list[str]:
    out: list[str] = []
    for match in _TOKEN.finditer(text):
        kind = match.lastgroup
        if kind in ("space", "comment"):
            continue
        out.append(match.group())
    return out


def parse_statements(text: str) -> tuple[Stmt, ...]:
    """The top-level statements of a script text, comments dropped, tokens verbatim."""
    tokens = _tokens(text.lstrip("﻿"))
    statements, index = _parse_block(tokens, 0, top=True)
    return statements


def _parse_block(tokens: list[str], index: int, *, top: bool = False) -> tuple[tuple[Stmt, ...], int]:
    out: list[Stmt] = []
    n = len(tokens)
    while index < n:
        token = tokens[index]
        if token == "}":
            if top:   # a stray closing brace: the game skips it too
                index += 1
                continue
            return tuple(out), index + 1
        if token == "{":
            inner, index = _parse_block(tokens, index + 1)
            out.append(Stmt(None, None, inner))
            continue
        if index + 1 < n and _is_op(tokens[index + 1]):
            op = tokens[index + 1]
            if index + 2 < n and tokens[index + 2] == "{":
                inner, index = _parse_block(tokens, index + 3)
                out.append(Stmt(token, op, inner))
            else:
                out.append(Stmt(token, op, tokens[index + 2] if index + 2 < n else ""))
                index += 3
            continue
        out.append(Stmt(None, None, token))
        index += 1
    return tuple(out), index


def _is_op(token: str) -> bool:
    return token in ("=", "?=", "<=", ">=", "!=", "==", "<", ">")


def render_statements(statements: tuple[Stmt, ...] | list[Stmt], indent: int = 0) -> list[str]:
    lines: list[str] = []
    pad = "\t" * indent
    for stmt in statements:
        head = f"{stmt.key} {stmt.op} " if stmt.key is not None else ""
        if stmt.is_block:
            inner = stmt.value  # type: ignore[assignment]
            if not inner:
                lines.append(f"{pad}{head}{{ }}")
            elif all(not s.is_block for s in inner) and len(inner) <= 6 and sum(len(_flat(s)) for s in inner) < 80:
                lines.append(f"{pad}{head}{{ {' '.join(_flat(s) for s in inner)} }}")
            else:
                lines.append(f"{pad}{head}{{")
                lines.extend(render_statements(inner, indent + 1))
                lines.append(f"{pad}}}")
        else:
            lines.append(f"{pad}{head}{stmt.value}")
    return lines


def _flat(stmt: Stmt) -> str:
    head = f"{stmt.key} {stmt.op} " if stmt.key is not None else ""
    if stmt.is_block:
        return head + "{ " + " ".join(_flat(s) for s in stmt.value) + " }"  # type: ignore[union-attr]
    return head + str(stmt.value)


def flat_text(statements: tuple[Stmt, ...]) -> str:
    return " ".join(_flat(s) for s in statements)


def _values(statements: tuple[Stmt, ...], key: str) -> list[str | tuple[Stmt, ...]]:
    return [s.value for s in statements if s.key == key]


def _last_scalar(statements: tuple[Stmt, ...], key: str) -> str | None:
    values = [v for v in _values(statements, key) if isinstance(v, str)]
    return values[-1] if values else None


def _int(value: str | None) -> int | None:
    if value is None:
        return None
    try:
        return int(float(value))
    except ValueError:
        return None


