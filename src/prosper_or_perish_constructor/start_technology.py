def setup_building_rows(vanilla_root: Path, mod_root: Path) -> list[tuple[str, str, str, int]]:
    """(tag, building, location, levels) of every ``building_manager`` row of the effective setup folder (a mod file
    replaces the same name) plus every ``town_setup`` preset a location still names (owner = the location's owner)."""
    from eu5gameparser.clausewitz.syntax import CList

    from prosper_or_perish_constructor.worldbuilder.start_placement import load_owners

    owners = load_owners(Path(vanilla_root), Path(mod_root))
    towns: dict[str, CList] = {}
    for path in layered_files(vanilla_root, mod_root, Path("in_game/common/town_setups")):
        for entry in _setup_parse(path).entries:
            if isinstance(entry.value, CList):
                towns[entry.key.split(":", 1)[-1]] = entry.value
    rows: list[tuple[str, str, str, int]] = []
    for path in layered_files(vanilla_root, mod_root, SETUP_DIR):
        text = path.read_text(encoding="utf-8-sig")
        if "building_manager" not in text and "town_setup" not in text:
            continue
        doc = _setup_parse(path)
        for manager in doc.values("building_manager"):
            if not isinstance(manager, CList):
                continue
            for entry in manager.entries:
                if isinstance(entry.value, CList):
                    rows.append((str(entry.value.first("tag") or ""), entry.key, str(entry.value.first("location") or ""),
                                 int(entry.value.first("level") or 0)))
        if "town_setup" in text:
            from prosper_or_perish_constructor.worldbuilder.start_simulation import town_levels

            for block in doc.values("locations"):
                if not isinstance(block, CList):
                    continue
                for entry in block.entries:
                    town = entry.value.first("town_setup") if isinstance(entry.value, CList) else None
                    if town:
                        for key, n in town_levels(towns, str(town)).items():
                            rows.append((owners.get(entry.key, ""), key, entry.key, int(n)))
    return rows


