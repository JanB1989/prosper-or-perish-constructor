@dataclass(frozen=True)
class Ladder:
    groups: dict[int, str]
    nobody: int
    floors: dict[str, int]
    caps: dict[str, int]
    levels: dict[str, int]
    specific_remap: dict[int, int]
    requires: dict[str, list[str]]
    research_cost: dict[str, float]
    ai_weight: dict[str, float]
    remove_start_buildings: bool
    research_base: float | None = None                                  # flat research a month without any advance
    research_speed: dict[str, float] = field(default_factory=dict)      # advance -> flat research a month it adds

    @property
    def replaced(self) -> set[str]:
        return set(self.requires) | set(self.research_cost) | set(self.ai_weight) | set(self.research_speed)


def load_ladder(repo: Path) -> Ladder:
    raw = tomllib.loads((Path(repo) / CONFIG).read_text(encoding="utf-8"))
    return Ladder(
        groups={int(k): str(v) for k, v in raw["groups"].items()},
        nobody=int(raw["nobody"]),
        floors={str(k): int(v) for k, v in raw.get("floors", {}).items()},
        caps={str(k): int(v) for k, v in raw.get("caps", {}).items()},
        levels={str(k): int(v) for k, v in raw["levels"].items()},
        specific_remap={int(k): int(v) for k, v in raw.get("specific_remap", {}).items()},
        requires={str(k): [str(x) for x in v] for k, v in raw.get("requires", {}).items()},
        research_cost={str(k): float(v) for k, v in raw.get("research_cost", {}).items()},
        ai_weight={str(k): float(v) for k, v in raw.get("ai_weight", {}).items()},
        remove_start_buildings=bool(raw.get("start_buildings", {}).get("remove_when_advance_above_group", True)),
        research_base=(float(raw["research_speed"]["base"]) if "research_speed" in raw else None),
        research_speed={str(k): float(v) for k, v in raw.get("research_speed", {}).get("advances", {}).items()},
    )


# ---------------------------------------------------------------------------------------------- layered files
def _game_roots(vanilla_root: Path) -> list[Path]:
    from prosper_or_perish_constructor.building_footprint import vanilla_game_roots

    return list(vanilla_game_roots(Path(vanilla_root)))


def layered_files(vanilla_root: Path, mod_root: Path | None, relative: Path, *, skip: tuple[str, ...] = ()) -> list[Path]:
    """The ``*.txt`` files of one folder as the game loads them: the union by file name of ``game/``, every DLC folder
    and the mod (a later layer's file replaces the same name), in name order."""
    by_name: dict[str, Path] = {}
    roots = [*_game_roots(vanilla_root), *([Path(mod_root)] if mod_root is not None else [])]
    for root in roots:
        folder = root / relative
        if folder.is_dir():
            for path in folder.glob("*.txt"):
                by_name[path.name] = path
    return [by_name[name] for name in sorted(by_name) if name not in skip]


def _layer_of(path: Path, vanilla_root: Path, mod_root: Path | None) -> str:
    if mod_root is not None and Path(path).is_relative_to(Path(mod_root)):
        return "mod"
    if Path(path).is_relative_to(Path(vanilla_root) / "game" / "dlc"):
        return "dlc"
    return "game"


# ---------------------------------------------------------------------------------------------- advances
@dataclass
class Advance:
    key: str
    body: tuple[Stmt, ...]
    history: list[tuple[str, str, str]] = field(default_factory=list)   # (mode, layer, file name)
    replaced: bool = False            # a REPLACE / TRY_REPLACE rewrote the block (the engine ignores later injects)
    mod_keys: set[str] = field(default_factory=set)   # keys a mod file wrote (inject or replace)

    @property
    def age(self) -> str:
        return _last_scalar(self.body, "age") or ""

    @property
    def requires(self) -> list[str]:
        return [v for v in _values(self.body, "requires") if isinstance(v, str)]

    @property
    def in_tree_of(self) -> list[str]:
        return [v for v in _values(self.body, "in_tree_of") if isinstance(v, str)]

    @property
    def level(self) -> int | None:
        return _int(_last_scalar(self.body, LEVEL_KEY))

    @property
    def base_defined(self) -> bool:
        """Defined in the base game or the mod, not only in a DLC folder (DLC-only objects take TRY_ modes)."""
        return any(mode in ("CREATE", "REPLACE_OR_CREATE", "INJECT_OR_CREATE") and layer != "dlc"
                   for mode, layer, _ in self.history)

    @property
    def mod_touched(self) -> bool:
        return any(layer == "mod" for _, layer, _ in self.history)


def _mode(raw_key: str) -> tuple[str, str]:
    if ":" not in raw_key:
        return "CREATE", raw_key
    prefix, key = raw_key.split(":", 1)
    return prefix.strip().upper(), key


def effective_advances(vanilla_root: Path, mod_root: Path) -> dict[str, Advance]:
    """Every advance as the game merges the advance folder (vanilla, DLC folders, the mod), without this pass's file."""
    db: dict[str, Advance] = {}
    for path in layered_files(vanilla_root, mod_root, ADVANCES_DIR, skip=(ADVANCES_OUTPUT.name,)):
        layer = _layer_of(path, vanilla_root, mod_root)
        for stmt in parse_statements(path.read_text(encoding="utf-8-sig")):
            if stmt.key is None or not stmt.is_block:
                continue
            mode, key = _mode(stmt.key)
            body: tuple[Stmt, ...] = stmt.value  # type: ignore[assignment]
            existing = db.get(key)
            record = (mode, layer, path.name)
            mod_keys = {s.key for s in body if s.key} if layer == "mod" else set()
            if mode in ("CREATE", "REPLACE", "REPLACE_OR_CREATE") or (mode == "TRY_REPLACE" and existing is not None):
                history = [*(existing.history if existing else []), record]
                db[key] = Advance(key, body, history, replaced=mode != "CREATE" and existing is not None,
                                  mod_keys=(existing.mod_keys if existing else set()) | mod_keys)
            elif mode in _INJECT_MODES:
                if existing is None:
                    if mode == "INJECT_OR_CREATE":
                        db[key] = Advance(key, body, [record], mod_keys=mod_keys)
                    continue
                if existing.replaced:
                    continue   # the engine ignores an inject into a replaced block
                existing.body = (*existing.body, *body)
                existing.history.append(record)
                existing.mod_keys |= mod_keys
    return db


def _classify_allow(block: tuple[Stmt, ...]) -> tuple[set[str], bool, set[str]]:
    """(institutions, other condition, institutions inside an OR with other conditions) of one ``allow``."""
    text = flat_text(block)
    insts = set(re.findall(r"has_embraced_institution = institution:(\w+)", text))
    other = re.sub(r"has_embraced_institution = institution:\w+", "", text)
    other = re.sub(r"\b(?:OR|AND) = \{|\}", "", other).strip()
    if insts and other and "OR = {" in text:
        return set(), False, insts
    return insts, bool(other), set()


def gate_classes(advances: dict[str, Advance]) -> dict[str, str]:
    """Gate class of every advance over itself and its ancestors (requires and in_tree_of): free, institution,
    institution_or_geo (an institution OR geography/market conditions), other (potential, government, country
    type or another allow condition), other+institution, non_location_country."""
    own: dict[str, tuple[set[str], set[str], bool]] = {}
    for key, adv in advances.items():
        insts: set[str] = set()
        mixed: set[str] = set()
        other = False
        for allow in _values(adv.body, "allow"):
            if isinstance(allow, tuple):
                i, o, m = _classify_allow(allow)
                insts |= i
                mixed |= m
                other = other or o
        country_type = _last_scalar(adv.body, "country_type")
        other = other or any(isinstance(v, tuple) for v in _values(adv.body, "potential"))
        other = other or bool(_values(adv.body, "government"))
        other = other or (country_type not in (None, "location"))
        own[key] = (insts, mixed, other)
    memo: dict[str, tuple[set[str], set[str], bool]] = {}

    def inherited(key: str, stack: tuple[str, ...] = ()) -> tuple[set[str], set[str], bool]:
        if key in memo:
            return memo[key]
        adv = advances.get(key)
        if adv is None or key in stack:
            return set(), set(), False
        insts, mixed, other = (set(own[key][0]), set(own[key][1]), own[key][2])
        for parent in (*adv.requires, *adv.in_tree_of):
            pi, pm, po = inherited(parent, (*stack, key))
            insts |= pi
            mixed |= pm
            other = other or po
        memo[key] = (insts, mixed, other)
        return memo[key]

    out: dict[str, str] = {}
    for key, adv in advances.items():
        insts, mixed, other = inherited(key)
        country_type = _last_scalar(adv.body, "country_type")
        if country_type not in (None, "location"):
            out[key] = "non_location_country"
        elif other and insts:
            out[key] = "other+institution"
        elif other:
            out[key] = "other"
        elif insts:
            out[key] = "institution"
        elif mixed:
            out[key] = "institution_or_geo"
        else:
            out[key] = "free"
    return out


def first_age(advances: dict[str, Advance]) -> dict[str, Advance]:
    return {k: a for k, a in advances.items() if a.age == AGE1}


def general_first_age(advances: dict[str, Advance]) -> set[str]:
    classes = gate_classes(advances)
    return {k for k in first_age(advances) if classes[k] in GENERAL_GATES}


def specific_first_age(advances: dict[str, Advance]) -> set[str]:
    classes = gate_classes(advances)
    return {k for k in first_age(advances) if classes[k] not in GENERAL_GATES}


def parents_after(ladder: Ladder, advances: dict[str, Advance]) -> dict[str, list[str]]:
    """Every advance's ``requires`` after ``[requires]``."""
    return {k: list(ladder.requires.get(k, a.requires)) for k, a in advances.items()}


def granted(keys: set[str] | dict, parents: dict[str, list[str]], level: dict[str, int], group: int) -> set[str]:
    """The advances of ``keys`` a country of ``group`` starts with, conditions aside: its level <= group and one
    parent granted (a root needs none)."""
    memo: dict[str, bool] = {}

    def held(key: str, stack: tuple[str, ...] = ()) -> bool:
        if key in memo:
            return memo[key]
        if key not in keys or key in stack or level.get(key, 0) > group:
            memo[key] = False
            return False
        ps = parents.get(key, [])
        result = not ps or any(held(p, (*stack, key)) for p in ps)
        memo[key] = result
        return result

    return {k for k in keys if held(k)}


@dataclass
class AdvancePlan:
    general: set[str]
    specific: set[str]
    injects: dict[str, int]                    # advance -> level (plain INJECT)
    replaces: dict[str, tuple[Stmt, ...]]      # advance -> full new block
    try_mode: set[str]                         # DLC-only advances: TRY_INJECT / TRY_REPLACE
    final_levels: dict[str, int]               # every first-age advance with a level after this pass
    remapped: dict[str, tuple[int, int]]       # specific advance -> (old level, new level)
    parents: dict[str, list[str]]


def _replace_body(adv: Advance, *, level: int | None, requires: list[str] | None, research_cost: float | None,
                  ai_weight: float | None, research_speed: float | None = None) -> tuple[Stmt, ...]:
    """The effective block, key for key, with the level (None: the block keeps none), the requires, the research cost,
    the AI weight and the flat research the advance adds set."""
    out: list[Stmt] = []
    lead = {"age", "icon", "depth"}
    placed = {"level": level is None, "requires": requires is None, "research_cost": research_cost is None,
              "ai_weight": ai_weight is None}
    present = {s.key for s in adv.body if s.key}
    new_requires = [Stmt("requires", "=", r) for r in (requires or [])]
    if requires is not None and not requires and "depth" not in present and adv.requires:
        new_requires = [Stmt("depth", "=", "0")]   # a new root carries depth = 0 like vanilla's roots
    # a key the block lacks goes after its leading age / icon / depth lines; a key it has keeps its place
    if "requires" not in present and requires is not None:
        placed["requires"] = False
    if "research_cost" not in present and research_cost is not None:
        placed["research_cost"] = False

    def lead_done(index: int) -> bool:
        return index + 1 >= len(adv.body) or adv.body[index + 1].key not in lead

    for index, stmt in enumerate(adv.body):
        if stmt.key == LEVEL_KEY:
            if level is None:
                raise StartTechnologyError(f"{adv.key}: a REPLACE without a level of an advance that carries one")
            if not placed["level"]:
                out.append(Stmt(LEVEL_KEY, "=", str(level)))
                placed["level"] = True
            continue
        if stmt.key == "requires" and requires is not None:
            if not placed["requires"]:
                out.extend(new_requires)
                placed["requires"] = True
            continue
        if stmt.key == "research_cost" and research_cost is not None:
            if not placed["research_cost"]:
                out.append(Stmt("research_cost", "=", _number(research_cost)))
                placed["research_cost"] = True
            continue
        if stmt.key == "ai_weight" and ai_weight is not None:
            if not placed["ai_weight"]:
                out.append(_ai_weight_stmt(stmt, ai_weight))
                placed["ai_weight"] = True
            continue
        if stmt.key == RESEARCH_KEY and research_speed is not None:
            continue   # written once, below
        out.append(stmt)
        if stmt.key in lead and lead_done(index):
            if not placed["requires"] and "requires" not in present:
                out.extend(new_requires)
                placed["requires"] = True
            if not placed["research_cost"] and "research_cost" not in present:
                out.append(Stmt("research_cost", "=", _number(research_cost)))  # type: ignore[arg-type]
                placed["research_cost"] = True
    if not placed["requires"]:
        out.extend(new_requires)
    if not placed["research_cost"]:
        out.append(Stmt("research_cost", "=", _number(research_cost)))  # type: ignore[arg-type]
    if research_speed is not None:
        out.append(Stmt(RESEARCH_KEY, "=", _number(research_speed)))
    if not placed["ai_weight"]:
        out.append(Stmt("ai_weight", "=", (Stmt("add", "=", _number(ai_weight)),)))  # type: ignore[arg-type]
    if not placed["level"]:
        out.append(Stmt(LEVEL_KEY, "=", str(level)))
    return tuple(out)


def _ai_weight_stmt(stmt: Stmt, weight: float) -> Stmt:
    if not stmt.is_block:
        return Stmt("ai_weight", "=", (Stmt("add", "=", _number(weight)),))
    inner = [s for s in stmt.value if s.key != "add"]  # type: ignore[union-attr]
    return Stmt("ai_weight", stmt.op, (Stmt("add", "=", _number(weight)), *inner))


def _number(value: float) -> str:
    if float(value).is_integer() and abs(value) >= 10:
        return str(int(value))
    text = f"{float(value):.4f}".rstrip("0")
    return text + "0" if text.endswith(".") else text


def plan_advances(ladder: Ladder, advances: dict[str, Advance]) -> AdvancePlan:
    """What the advance file writes; raises ``StartTechnologyError`` on a config that does not fit the game."""
    general = general_first_age(advances)
    specific = specific_first_age(advances)
    problems: list[str] = []
    missing = sorted(general - set(ladder.levels))
    unknown = sorted(set(ladder.levels) - set(advances))
    not_general = sorted((set(ladder.levels) & set(advances)) - general)
    if missing:
        problems.append(f"general first-age advances without a level in [levels]: {', '.join(missing)}")
    if unknown:
        problems.append(f"[levels] names advances the game does not have: {', '.join(unknown)}")
    if not_general:
        problems.append(f"[levels] names advances that are not general first-age advances: {', '.join(not_general)}")
    for section, keys in (("research_cost", ladder.research_cost), ("ai_weight", ladder.ai_weight),
                          ("research_speed.advances", ladder.research_speed)):
        bad = sorted(set(keys) - set(ladder.levels))
        if bad:
            problems.append(f"[{section}] names advances outside [levels]: {', '.join(bad)}")
    if ladder.research_base is not None:
        total = ladder.research_base + sum(ladder.research_speed.values())
        if abs(total - VANILLA_RESEARCH_BASE) > 1e-9 or ladder.research_base <= 0 or min(ladder.research_speed.values(), default=1) <= 0:
            problems.append(f"[research_speed] base and advances must be positive and add up to {VANILLA_RESEARCH_BASE:g} "
                            f"(vanilla's flat research, so a country that holds them all gains nothing); they add up to {total:g}")
    # [requires] may also move a country, culture, religion or government advance of the first age
    bad = sorted(set(ladder.requires) - set(ladder.levels) - specific)
    if bad:
        problems.append(f"[requires] names advances that are neither in [levels] nor specific first-age advances: "
                        f"{', '.join(bad)}")
    for key, parents in ladder.requires.items():
        bad = [p for p in parents if p not in advances or advances[p].age != AGE1]
        if bad:
            problems.append(f"[requires] {key}: unknown or not first-age parents {', '.join(bad)}")
    for key in sorted(ladder.replaced & set(advances)):
        configured = {"requires"} if key in ladder.requires else set()
        configured |= {"research_cost"} if key in ladder.research_cost else set()
        configured |= {"ai_weight"} if key in ladder.ai_weight else set()
        configured |= {RESEARCH_KEY} if key in ladder.research_speed else set()
        clash = advances[key].mod_keys & (configured | {LEVEL_KEY})
        if clash:
            files = ", ".join(f"{m}:{f}" for m, layer, f in advances[key].history if layer == "mod")
            problems.append(f"{key}: another mod file ({files}) also writes {', '.join(sorted(clash))}; "
                            "merge it into the ladder config or that file")
    final: dict[str, int] = {}
    injects: dict[str, int] = {}
    replaces: dict[str, tuple[Stmt, ...]] = {}
    remapped: dict[str, tuple[int, int]] = {}
    for key in sorted(specific):
        old = advances[key].level
        if old is None:
            continue
        if old not in ladder.specific_remap:
            problems.append(f"specific first-age advance {key} carries level {old}, which [specific_remap] does not map")
            continue
        remapped[key] = (old, ladder.specific_remap[old])
    if problems:
        raise StartTechnologyError("starting technology ladder: " + "; ".join(problems))
    targets = {k: v for k, v in ladder.levels.items()}
    targets.update({k: new for k, (old, new) in remapped.items()})
    for key, level in sorted(targets.items()):
        adv = advances[key]
        final[key] = level
        if key in ladder.replaced or adv.replaced:
            replaces[key] = _replace_body(
                adv,
                level=level,
                requires=ladder.requires.get(key),
                research_cost=ladder.research_cost.get(key),
                ai_weight=ladder.ai_weight.get(key),
                research_speed=ladder.research_speed.get(key),
            )
        else:
            injects[key] = level
    for key in sorted(set(ladder.requires) - set(targets)):   # a specific advance without a level: new parents only
        replaces[key] = _replace_body(advances[key], level=None, requires=ladder.requires[key], research_cost=None,
                                      ai_weight=None)
    for key, adv in first_age(advances).items():
        if key not in final and adv.level is not None:
            final[key] = adv.level
    try_mode = {k for k in (*targets, *replaces) if not advances[k].base_defined}
    return AdvancePlan(general, specific, injects, replaces, try_mode, final, remapped, parents_after(ladder, advances))


def render_advances(ladder: Ladder, plan: AdvancePlan) -> str:
    lines = [
        f"# {_HEADER}",
        "# Starting technology ladder (config/starting_technology.toml): a country starts with the first-age advances",
        "# whose level is at most its group. REPLACE blocks are the effective block with the ladder's requires,",
        "# research cost and AI weight (or a block another mod file already replaced: the engine ignores injects there).",
        "",
    ]
    general = sorted((k for k in plan.injects if k in plan.general), key=lambda k: (plan.injects[k], k))
    specific = sorted((k for k in plan.injects if k not in plan.general), key=lambda k: (plan.injects[k], k))
    lines.append("# general first-age advances")
    for key in general:
        prefix = "TRY_INJECT" if key in plan.try_mode else "INJECT"
        lines.append(f"{prefix}:{key} = {{ {LEVEL_KEY} = {plan.injects[key]} }}")
    lines += ["", "# country, culture, religion and government advances: vanilla level remapped ([specific_remap])"]
    for key in specific:
        prefix = "TRY_INJECT" if key in plan.try_mode else "INJECT"
        old, new = plan.remapped[key]
        lines.append(f"{prefix}:{key} = {{ {LEVEL_KEY} = {new} }}  # was {old}")
    for key in sorted(plan.replaces, key=lambda k: (plan.final_levels.get(k, 0), k)):
        prefix = "TRY_REPLACE" if key in plan.try_mode else "REPLACE"
        lines.append("")
        lines.append(f"{prefix}:{key} = {{")
        lines.extend(render_statements(plan.replaces[key], 1))
        lines.append("}")
    return "\n".join(lines) + "\n"


def research_base_blocks(ladder: Ladder, vanilla_root: Path, mod_root: Path | None) -> dict[str, tuple[Stmt, ...]]:
    """Vanilla's auto modifiers that give a country its flat research (``research_speed`` = vanilla's base), each with
    the ladder's base instead. Empty without ``[research_speed]``."""
    if ladder.research_base is None:
        return {}
    out: dict[str, tuple[Stmt, ...]] = {}
    for path in layered_files(vanilla_root, None, AUTO_MODIFIERS_DIR):
        for stmt in parse_statements(path.read_text(encoding="utf-8-sig")):
            if stmt.key is None or not stmt.is_block:
                continue
            value = _last_scalar(stmt.value, RESEARCH_KEY)  # type: ignore[arg-type]
            try:
                is_base = value is not None and abs(float(value) - VANILLA_RESEARCH_BASE) < 1e-9
            except ValueError:
                is_base = False
            if not is_base:
                continue
            mode, key = _mode(stmt.key)
            if mode != "CREATE":
                raise StartTechnologyError(f"vanilla auto modifier {stmt.key} in {path.name}: unexpected prefix")
            out[key] = tuple(Stmt(RESEARCH_KEY, s.op, _number(ladder.research_base)) if s.key == RESEARCH_KEY else s
                             for s in stmt.value)  # type: ignore[union-attr]
    if not out:
        raise StartTechnologyError(f"no vanilla auto modifier gives research_speed = {VANILLA_RESEARCH_BASE:g} any more; "
                                   "[research_speed] has nothing to replace")
    if mod_root is not None:
        folder = Path(mod_root) / AUTO_MODIFIERS_DIR
        for path in sorted(folder.glob("*.txt")) if folder.is_dir() else []:
            if path.name == RESEARCH_OUTPUT.name:
                continue
            for stmt in parse_statements(path.read_text(encoding="utf-8-sig")):
                if stmt.key and stmt.is_block and _mode(stmt.key)[1] in out:
                    raise StartTechnologyError(f"{path.name} also writes the auto modifier {_mode(stmt.key)[1]}; "
                                               "the research base replaces that block whole")
    return out


def render_research_base(ladder: Ladder, blocks: dict[str, tuple[Stmt, ...]]) -> str:
    lines = [
        f"# {_HEADER}",
        "# Flat research a month without any advance (config/starting_technology.toml [research_speed]): vanilla gives",
        f"# {VANILLA_RESEARCH_BASE:g}; here the base is {ladder.research_base:g} and the advances of the writing branch add the rest,",
        "# so a country that holds them all researches as before. The blocks are vanilla's, with that one number changed.",
    ]
    for key in sorted(blocks):
        lines += ["", f"REPLACE:{key} = {{", *render_statements(blocks[key], 1), "}"]
    return "\n".join(lines) + "\n"


def output_blocks(mod_root: Path) -> dict[str, tuple[str, tuple[Stmt, ...]]]:
    """The generated advance file as parsed: advance -> (mode, block)."""
    path = Path(mod_root) / ADVANCES_OUTPUT
    if not path.is_file():
        return {}
    out = {}
    for stmt in parse_statements(path.read_text(encoding="utf-8-sig")):
        if stmt.key and stmt.is_block:
            mode, key = _mode(stmt.key)
            out[key] = (mode, stmt.value)
    return out  # type: ignore[return-value]


