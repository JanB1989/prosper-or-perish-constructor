class StartBuildingGate:
    """What the World Builder start stage keeps: a building whose unlocking ladder advance is above the owner's group
    is dropped from the setup and never placed."""

    def __init__(self, groups: dict[str, int], needs: dict[str, tuple[str, int]], enabled: bool = True):
        self.groups = groups
        self.needs = needs if enabled else {}

    @classmethod
    def load(cls, repo: Path, vanilla_root: Path, mod_root: Path | None) -> "StartBuildingGate":
        ladder = load_ladder(repo)
        groups = {g.tag: g.level for g in country_groups(repo, vanilla_root, mod_root, ladder)}
        return cls(groups, load_building_table(repo), ladder.remove_start_buildings)

    def locked(self, owner: str | None, building: str) -> tuple[str, int, int] | None:
        """(advance, its level, the owner's group) when ``owner`` may not have ``building`` at the start, else None."""
        need = self.needs.get(building)
        if need is None or owner is None:
            return None
        group = self.groups.get(owner, 0)
        return (need[0], need[1], group) if need[1] > group else None


