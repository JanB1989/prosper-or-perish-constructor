def _definitions(vanilla_root: Path, mod_root: Path, folder: Path) -> dict[str, tuple[Stmt, ...]]:
    db: dict[str, tuple[Stmt, ...]] = {}
    for path in layered_files(vanilla_root, mod_root, folder):
        for stmt in parse_statements(path.read_text(encoding="utf-8-sig")):
            if stmt.key is None or not stmt.is_block:
                continue
            mode, key = _mode(stmt.key)
            if mode in _INJECT_MODES and key in db:
                db[key] = (*db[key], *stmt.value)  # type: ignore[misc]
            elif mode in _INJECT_MODES:
                continue
            elif mode == "TRY_REPLACE" and key not in db:
                continue
            else:
                db[key] = stmt.value  # type: ignore[assignment]
    return db


def _has_advance_refs(body: tuple[Stmt, ...], ladder_keys: set[str]) -> dict[str, bool]:
    """advance -> negated, for every ``has_advance = <ladder advance>`` in the block (negated: inside a NOT)."""
    text = flat_text(body)
    out: dict[str, bool] = {}
    for match in re.finditer(r"has_advance = (?:advance_type:)?(\w+)", text):
        key = match.group(1)
        if key in ladder_keys:
            before = text[: match.start()]
            negated = bool(re.search(r"NOT = \{ (?:[^{}]*)$", before))
            out[key] = out.get(key, True) and negated
    return out


def setup_requirements(ladder: Ladder, advances: dict[str, Advance], countries: list[Country],
                       groups: list[CountryGroup], vanilla_root: Path, mod_root: Path) -> list[dict[str, object]]:
    """Subject types, laws, policies, government reforms, estate privileges and parliament types the start countries
    set that need a ladder advance (unlocked by it, switched on by it, or naming it in a ``has_advance``), with the
    countries whose group is below that advance (or, for a ``NOT = { has_advance }``, at or above it)."""
    level_of = {g.tag: g.level for g in groups}
    uses: dict[tuple[str, str], set[str]] = defaultdict(set)
    for country in countries:
        for reform in country.reforms:
            uses[("government_reform", reform)].add(country.tag)
        for privilege in country.privileges:
            uses[("estate_privilege", privilege)].add(country.tag)
        for law, policy in country.laws:
            uses[("law", law)].add(country.tag)
            uses[("policy", policy)].add(country.tag)
        if country.parliament_type:
            uses[("parliament_type", country.parliament_type)].add(country.tag)
    for overlord, _subject, kind in dependencies(vanilla_root, mod_root):
        if kind:
            uses[("subject_type", kind)].add(overlord)
        uses[("subject_type", "*any*")].add(overlord)
    needs: list[tuple[str, str, str, str, bool]] = []   # kind, thing, advance, how, negated
    for key in sorted(ladder.levels):
        adv = advances.get(key)
        if adv is None:
            continue
        for stmt in adv.body:
            if stmt.key in _UNLOCK_KINDS and isinstance(stmt.value, str):
                needs.append((_UNLOCK_KINDS[stmt.key], stmt.value, key, stmt.key, False))
            elif stmt.key and stmt.value == "yes" and re.fullmatch(r"allow_(\w+)_parliament", stmt.key):
                kind = re.fullmatch(r"allow_(\w+)_parliament", stmt.key).group(1)  # type: ignore[union-attr]
                needs.append(("parliament_type", kind, key, stmt.key, False))
            elif stmt.key == "allow_subjects" and stmt.value == "yes":
                needs.append(("subject_type", "*any*", key, stmt.key, False))
    ladder_keys = set(ladder.levels)
    for kind, folder in _REQUIREMENT_FOLDERS.items():
        for thing, body in _definitions(vanilla_root, mod_root, folder).items():
            if kind == "law":
                policies = [s for s in body if s.is_block and s.key and _is_policy(s)]
                law_body = tuple(s for s in body if s not in policies)
                for adv_key, negated in _has_advance_refs(law_body, ladder_keys).items():
                    needs.append(("law", thing, adv_key, "has_advance in definition", negated))
                for policy in policies:
                    for adv_key, negated in _has_advance_refs(policy.value, ladder_keys).items():  # type: ignore[arg-type]
                        needs.append(("policy", str(policy.key), adv_key, "has_advance in definition", negated))
            else:
                for adv_key, negated in _has_advance_refs(body, ladder_keys).items():
                    needs.append((kind, thing, adv_key, "has_advance in definition", negated))
    # held = granted along the tree (conditions aside), with the ladder and, for comparison, with vanilla's levels
    general = general_first_age(advances)
    new_parents = parents_after(ladder, advances)
    new_held = {g: granted(general, new_parents, ladder.levels, g) for g in sorted(ladder.groups)}
    old_parents = {k: a.requires for k, a in advances.items()}
    old_levels = {k: a.level or 0 for k, a in advances.items()}
    vanilla_level = {c.tag: c.vanilla_level for c in countries}
    old_held = {v: granted(general, old_parents, old_levels, v) for v in sorted(set(vanilla_level.values()))}

    def lacks(adv_key: str, held: set[str], negated: bool) -> bool:
        return (adv_key in held) if negated else (adv_key not in held)

    rows = []
    for kind, thing, adv_key, how, negated in sorted(set(needs)):
        users = uses.get((kind, thing), set())
        if not users:
            continue
        level = ladder.levels[adv_key]
        affected = sorted(t for t in users if lacks(adv_key, new_held.get(level_of.get(t, 0), set()), negated))
        before = sorted(t for t in users if lacks(adv_key, old_held.get(vanilla_level.get(t, 0), set()), negated))
        per_group = Counter(level_of.get(t, 0) for t in affected)
        rows.append({
            "kind": kind, "thing": thing, "advance": adv_key, "advance_level": level, "how": how,
            "negated": "yes" if negated else "", "countries_using": len(users), "countries_affected": len(affected),
            "affected_with_vanilla_levels": len(before), "newly_affected": len(set(affected) - set(before)),
            **{f"g{g}": per_group.get(g, 0) for g in sorted(ladder.groups)},
            "affected_tags": " ".join(affected[:25]) + (" ..." if len(affected) > 25 else ""),
        })
    return rows


_LAW_KEYS = frozenset({"potential", "allow", "requires", "locked", "law_category", "type", "unique", "ai_will_do",
                       "law_country_group", "law_gov_group", "law_religion_group", "custom_tags", "ai_weight"})


def _is_policy(stmt: Stmt) -> bool:
    return stmt.key not in _LAW_KEYS


