WITHHELD_REPORT = REPORT_DIR / "withheld_specific_advances.csv"
WITHHELD_HEADER = ("tag", "advance", "blocking_advance", "blocking_level", "group", "vanilla_level", "unlocks")
_TAG_CHECK = re.compile(r"\b(?:has_or_had_tag|tag) = (\w+)")


def withheld_specific(ladder: Ladder, advances: dict[str, Advance], plan: AdvancePlan, countries: list[Country],
                      groups: list[CountryGroup]) -> tuple[list[dict[str, object]], int]:
    """Country-specific first-age advances a country on the map would start with under vanilla's levels and tree but
    not under the ladder, because an ancestor sits above its group. Only advances whose own or an ancestor's
    ``potential`` names tags (``has_or_had_tag`` / ``tag``) are judged, by the tag alone; culture, religion, government
    and every other condition are not evaluated. Returns the rows and the number of specific first-age advances not
    judged (no tag in their chain)."""
    ages = first_age(advances)
    specific = specific_first_age(advances)
    tags_of: dict[str, set[str] | None] = {}

    def chain_tags(key: str, stack: tuple[str, ...] = ()) -> list[set[str]]:
        adv = ages.get(key)
        if adv is None or key in stack:
            return []
        out = [set(_TAG_CHECK.findall(flat_text(p))) for p in _values(adv.body, "potential") if isinstance(p, tuple)]
        out = [t for t in out if t]
        for parent in adv.requires:   # vanilla tree: a tag gate on any ancestor gates the subtree
            out += chain_tags(parent, (*stack, key))
        return out

    for key in specific:
        gates = chain_tags(key)
        tags_of[key] = set.intersection(*gates) if gates else None
    judged = {k for k, t in tags_of.items() if t is not None}
    old_parents = {k: a.requires for k, a in ages.items()}
    new_parents = {k: v for k, v in plan.parents.items() if k in ages}
    old_levels = {k: a.level or 0 for k, a in ages.items()}
    new_levels = {k: plan.final_levels.get(k, 0) for k in ages}
    group_of = {g.tag: g.level for g in groups}

    def holds(tag: str, level: int, parents: dict[str, list[str]], levels: dict[str, int]):
        memo: dict[str, bool] = {}

        def held(key: str, stack: tuple[str, ...] = ()) -> bool:
            if key in memo:
                return memo[key]
            tags = tags_of.get(key)
            ok = key in ages and key not in stack and levels.get(key, 0) <= level and (tags is None or tag in tags)
            ok = ok and (not parents.get(key) or any(held(p, (*stack, key)) for p in parents[key]))
            memo[key] = ok
            return ok

        return held

    def blocker(key: str, level: int, held, stack: tuple[str, ...] = ()) -> tuple[str, int] | None:
        """The nearest ancestor (or the advance itself) above the group on the ladder's tree."""
        if new_levels.get(key, 0) > level:
            return key, new_levels[key]
        for parent in new_parents.get(key, []):
            if parent not in stack and not held(parent):
                found = blocker(parent, level, held, (*stack, key))
                if found:
                    return found
        return None

    rows = []
    for country in countries:
        if not country.owns_land or country.tag not in group_of:
            continue
        candidates = [k for k in sorted(judged) if country.tag in tags_of[k]]   # type: ignore[operator]
        if not candidates:
            continue
        old = holds(country.tag, country.vanilla_level, old_parents, old_levels)
        new = holds(country.tag, group_of[country.tag], new_parents, new_levels)
        for key in candidates:
            if old(key) and not new(key):
                found = blocker(key, group_of[country.tag], new) or ("", "")
                unlocks = [f"{s.key.removeprefix('unlock_')}:{s.value}" for s in ages[key].body
                           if s.key and s.key.startswith("unlock_") and isinstance(s.value, str)]
                rows.append({"tag": country.tag, "advance": key, "blocking_advance": found[0],
                             "blocking_level": found[1], "group": group_of[country.tag],
                             "vanilla_level": country.vanilla_level, "unlocks": " ".join(unlocks)})
    return rows, len(specific) - len(judged)


# ---------------------------------------------------------------------------------------------- the pass
@dataclass
class Result:
    ladder: Ladder
    plan: AdvancePlan
    groups: list[CountryGroup]
    changed: list[Path]
    table_changed: bool
    removed: list[dict[str, str]]
    requirements: list[dict[str, object]]

    @property
    def per_level(self) -> Counter:
        return Counter(g.level for g in self.groups)

    @property
    def floors(self) -> list[CountryGroup]:
        return [g for g in self.groups if g.floor]


def _csv_text(header: tuple[str, ...], rows: list[dict[str, object]]) -> str:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=list(header), lineterminator="\n", extrasaction="ignore")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue()


def _write(path: Path, text: str, *, write: bool, bom: bool) -> bool:
    current = path.read_text(encoding="utf-8-sig") if path.is_file() else None
    raw_bom = path.read_bytes().startswith(b"\xef\xbb\xbf") if path.is_file() else bom
    if current == text and raw_bom == bom:
        return False
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(("﻿" if bom else "") + text, encoding="utf-8")
    return True


def apply(repo: Path, project: Path, mod_root: Path | None = None, vanilla_root: Path | None = None, *,
          write: bool = True) -> Result:
    """Write (or with ``write=False`` only compare) the advance file, the setup file and the building table; with
    ``write`` also the reports. ``Result.changed`` lists the outputs that were (would be) rewritten."""
    from prosper_or_perish_constructor.worldbuilder.stage import vanilla_root as configured_vanilla_root

    repo = Path(repo)
    mod_root = Path(mod_root) if mod_root is not None else repo / "mod" / MOD_FOLDER
    vanilla_root = Path(vanilla_root) if vanilla_root is not None else configured_vanilla_root(repo, project)
    ladder = load_ladder(repo)
    advances = effective_advances(vanilla_root, mod_root)
    plan = plan_advances(ladder, advances)
    countries = country_blocks(vanilla_root, mod_root)
    groups = country_groups(repo, vanilla_root, mod_root, ladder, countries)
    changed = []
    if _write(mod_root / ADVANCES_OUTPUT, render_advances(ladder, plan), write=write, bom=True):
        changed.append(ADVANCES_OUTPUT)
    if _write(mod_root / SETUP_OUTPUT, render_setup(groups), write=write, bom=False):
        changed.append(SETUP_OUTPUT)
    research = research_base_blocks(ladder, vanilla_root, mod_root)
    if research:
        if _write(mod_root / RESEARCH_OUTPUT, render_research_base(ladder, research), write=write, bom=True):
            changed.append(RESEARCH_OUTPUT)
    elif (mod_root / RESEARCH_OUTPUT).is_file():
        changed.append(RESEARCH_OUTPUT)
        if write:
            (mod_root / RESEARCH_OUTPUT).unlink()
    table_changed = _write(repo / BUILDINGS_CSV, render_building_table(building_gates(ladder, advances)),
                           write=write, bom=False)
    if table_changed:
        changed.append(BUILDINGS_CSV)
    requirements = setup_requirements(ladder, advances, countries, groups, vanilla_root, mod_root)
    if write:
        rows = [{"tag": g.tag, "vanilla_level": g.vanilla_level, "csv_group": g.csv_group, "confidence": g.confidence,
                 "basis": g.basis, "floor": g.floor, "level": g.level} for g in groups]
        _write(repo / COUNTRIES_REPORT, _csv_text(("tag", "vanilla_level", "csv_group", "confidence", "basis", "floor",
                                                   "level"), rows), write=True, bom=False)
        header = ("kind", "thing", "advance", "advance_level", "how", "negated", "countries_using", "countries_affected",
                  "affected_with_vanilla_levels", "newly_affected", *(f"g{g}" for g in sorted(ladder.groups)),
                  "affected_tags")
        _write(repo / REQUIREMENTS_REPORT, _csv_text(header, requirements), write=True, bom=False)
        withheld, _unjudged = withheld_specific(ladder, advances, plan, countries, groups)
        _write(repo / WITHHELD_REPORT, _csv_text(WITHHELD_HEADER, withheld), write=True, bom=False)
    return Result(ladder, plan, groups, changed, table_changed, read_removed(repo), requirements)


def summary(result: Result, *, check: bool = False) -> str:
    levels = " ".join(f"{level}:{n}" for level, n in sorted(result.per_level.items()))
    removed = sum(int(r["levels"] or 0) for r in result.removed if r.get("source") == "setup")
    if check:
        state = "current" if not result.changed else "OFF (run uv run ppc start-tech apply): " + ", ".join(map(str, result.changed))
    else:
        state = f"{len(result.changed)} files rewritten" if result.changed else "unchanged"
    line = (f"Starting technology: {len(result.plan.injects)} level injects, {len(result.plan.replaces)} replaced advances, "
            f"{len(result.plan.remapped)} specific remapped; {len(result.groups)} countries by level {levels}, "
            f"{len(result.floors)} changed by floors or caps; start building levels removed {removed}; "
            + (f"research base {result.ladder.research_base:g} + {len(result.ladder.research_speed)} advances; "
               if result.ladder.research_base is not None else "") + f"{state}.")
    if result.table_changed and not check:
        line += " The start building table changed: the next build reruns the start setup."
    return line
