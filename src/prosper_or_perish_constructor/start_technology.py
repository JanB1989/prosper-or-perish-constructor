"""Starting technology ladder (2026-11-25, Jan): every country starts with the first-age advances of its group 1..9.

At game start the engine grants an Age of Traditions advance when its ``starting_technology_level`` <= the country's
``starting_technology_level`` (an advance without the key counts as 0), its ``allow`` / ``potential`` pass and at
least one parent (``requires``) is granted; a withheld advance withholds its whole subtree. Levels are a plain integer
compare (5..9 tested in game). This pass gives every general first-age advance (no country, culture, religion,
government or country-type condition on it or an ancestor) the level of ``config/starting_technology.toml``
``[levels]`` and every country of the 1337 setup its group from ``config/starting_technology_countries.csv`` (after
the floors) as its level.

Outputs (``apply``; ``check`` reports them current or off):
- ``in_game/common/advances/zz_pp_start_technology.txt``: ``INJECT:<advance> = { starting_technology_level = N }``,
  or a ``REPLACE:`` with the effective block (vanilla plus what other mod files do) where ``[requires]``,
  ``[research_cost]`` or ``[ai_weight]`` change the advance, or where another mod file already replaced it (the
  engine ignores an inject into a replaced block). Country-specific first-age advances that carry a level get it
  remapped through ``[specific_remap]``. Later ages are not touched. The name sorts after every advance file.
- ``main_menu/setup/1337/28_pp_start_technology.txt`` (no BOM): one partial country block per country of the
  effective ``10_countries.txt``; a later setup file's partial block merges into the country and its level wins
  (tested in game). The name sorts after every setup file that sets a level.
- ``in_game/common/auto_modifiers/pp_research_base.txt`` (``[research_speed]``): a ``REPLACE:`` of every vanilla
  auto modifier that gives a country the flat ``research_speed = 1`` (countries with land, building, army and navy
  countries; the societies of pops keep their 0.1), with the ladder's base instead. The advances of
  ``[research_speed.advances]`` carry the rest as ``research_speed`` lines, so a country that holds them all researches
  as in vanilla.
- ``config/starting_technology_buildings.csv``: building -> the ladder advance that unlocks it and its level. The
  World Builder start stage reads it (``StartBuildingGate``), drops every start building whose advance is above the
  owner's group and never places one (start_simulation ``drop_locked`` / ``add``), so raising a group and rebuilding
  brings the buildings back. The stage reads this table, not the advance files, so an advance edit does not rerun
  the start setup; ``ppc build`` / ``ppc sync`` refresh it before the stage (``refresh_building_table``).
- ``artifacts/data/start_technology/``: ``countries.csv``, ``removed_start_buildings.csv`` (written by the stage),
  ``setup_requirements.csv`` (subject types, laws, policies, reforms, privileges and parliament types of the start
  countries that need a ladder advance, with the countries below it).

Advance files are read with a small statement parser of its own (``parse_statements``): the game parser package
drops the ``?=`` operator and the quotes of strings, and a REPLACE must copy the block token for token.
"""

