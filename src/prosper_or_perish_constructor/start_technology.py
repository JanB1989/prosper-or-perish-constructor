@dataclass(frozen=True)
class Country:
    tag: str
    vanilla_level: int
    level_source: str
    reforms: tuple[str, ...] = ()
    privileges: tuple[str, ...] = ()
    laws: tuple[tuple[str, str], ...] = ()
    parliament_type: str | None = None
    owns_land: bool = False
    country_type: str | None = None   # the block's `type` (pop, building, army; none = a country with land)


def _setup_parse(path: Path):
    from eu5gameparser.clausewitz.parser import parse_file

    return parse_file(path)


def country_blocks(vanilla_root: Path, mod_root: Path | None) -> list[Country]:
    """Every country block of the effective ``10_countries.txt`` in reading order, with its effective level (the last
    ``starting_technology_level`` in reading order, ``include`` templates expanded where they stand; none = 0) and
    the government its block and templates set."""
    from eu5gameparser.clausewitz.syntax import CList

    files = {p.name: p for p in layered_files(vanilla_root, mod_root, SETUP_DIR)}
    if COUNTRIES_FILE not in files:
        raise StartTechnologyError(f"no {COUNTRIES_FILE} in the setup folder {SETUP_DIR}")
    templates = {p.stem: p for p in layered_files(vanilla_root, mod_root, TEMPLATES_DIR)}
    cache: dict[str, list] = {}

    def template(name: str) -> list:
        if name not in cache:
            path = templates.get(name)
            cache[name] = list(_setup_parse(path).entries) if path is not None else []
        return cache[name]

    def expand(entries, source: str, stack: tuple[str, ...] = ()):
        for entry in entries:
            if entry.key == "include" and isinstance(entry.value, str):
                name = entry.value.strip('"')
                if name not in stack:
                    yield from expand(template(name), f"template:{name}", (*stack, name))
            else:
                yield entry, source

    out: list[Country] = []
    document = _setup_parse(files[COUNTRIES_FILE])
    for outer in document.values("countries"):
        if not isinstance(outer, CList):
            continue
        for inner in outer.values("countries"):
            if not isinstance(inner, CList):
                continue
            for block in inner.entries:
                if not isinstance(block.value, CList):
                    continue
                level, source = 0, "default"
                reforms: list[str] = []
                privileges: list[str] = []
                laws: dict[str, str] = {}
                parliament = None
                owns = False
                kind = None
                for entry, src in expand(block.value.entries, "own"):
                    if entry.key == LEVEL_KEY:
                        level, source = int(entry.value), src  # type: ignore[arg-type]
                    elif entry.key == "type" and isinstance(entry.value, str):
                        kind = entry.value
                    elif entry.key.startswith("own_") and isinstance(entry.value, CList) and entry.value.items:
                        owns = True
                    elif entry.key == "government" and isinstance(entry.value, CList):
                        for g in entry.value.entries:
                            if g.key == "reforms" and isinstance(g.value, CList):
                                reforms += [str(x) for x in g.value.items]
                            elif g.key == "privilege" and isinstance(g.value, CList):
                                privileges += [str(x) for x in g.value.items]
                            elif g.key == "laws" and isinstance(g.value, CList):
                                laws.update({law.key: str(law.value) for law in g.value.entries})
                            elif g.key == "parliament" and isinstance(g.value, CList):
                                parliament = str(g.value.first("parliament_type") or parliament or "") or None
                out.append(Country(block.key, level, source, tuple(dict.fromkeys(reforms)),
                                   tuple(dict.fromkeys(privileges)), tuple(sorted(laws.items())), parliament, owns, kind))
    return out


def dependencies(vanilla_root: Path, mod_root: Path | None) -> list[tuple[str, str, str]]:
    """(overlord, subject, subject type) of every ``dependency`` in the effective setup's diplomacy blocks."""
    from eu5gameparser.clausewitz.syntax import CList

    out: list[tuple[str, str, str]] = []
    for path in layered_files(vanilla_root, mod_root, SETUP_DIR, skip=(SETUP_OUTPUT.name,)):
        if "diplomacy_manager" not in path.read_text(encoding="utf-8-sig"):
            continue
        for manager in _setup_parse(path).values("diplomacy_manager"):
            if not isinstance(manager, CList):
                continue
            for dep in manager.values("dependency"):
                if isinstance(dep, CList) and dep.first("first") and dep.first("second"):
                    out.append((str(dep.first("first")), str(dep.first("second")), str(dep.first("subject_type") or "")))
    return out


@dataclass(frozen=True)
class CountryGroup:
    tag: str
    csv_group: int
    level: int
    floor: str            # why a floor raised or a cap lowered it ("" when neither did)
    vanilla_level: int
    confidence: str = ""
    basis: str = ""


def read_country_rows(repo: Path) -> list[dict[str, str]]:
    path = Path(repo) / COUNTRIES_CSV
    if not path.is_file():
        raise StartTechnologyError(f"{COUNTRIES_CSV} is missing (tools/start_technology_placeholder.py writes a placeholder)")
    with path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        if tuple(reader.fieldnames or ()) != COUNTRIES_HEADER:
            raise StartTechnologyError(f"{COUNTRIES_CSV}: header must be {','.join(COUNTRIES_HEADER)}, is {reader.fieldnames}")
        return list(reader)


def country_groups(repo: Path, vanilla_root: Path, mod_root: Path | None, ladder: Ladder | None = None,
                   countries: list[Country] | None = None) -> list[CountryGroup]:
    """One entry per country block, in setup order: the CSV group raised by the floors. Fails on a setup tag without a
    row, a row for a tag the setup does not have, a duplicate row or a group outside the ladder's groups."""
    ladder = ladder or load_ladder(repo)
    countries = countries if countries is not None else country_blocks(vanilla_root, mod_root)
    rows = read_country_rows(repo)
    tags = [c.tag for c in countries]
    by_tag: dict[str, dict[str, str]] = {}
    duplicates = sorted(tag for tag, n in Counter(r["tag"] for r in rows).items() if n > 1)
    for row in rows:
        by_tag[row["tag"]] = row
    missing = [t for t in tags if t not in by_tag]
    extra = sorted(set(by_tag) - set(tags))
    low, high = min(ladder.groups), max(ladder.groups)
    bad = []
    for row in rows:
        try:
            group = int(row["group"])
        except (TypeError, ValueError):
            group = None
        if group is None or not low <= group <= high:
            bad.append(f"{row['tag']}={row['group']!r}")
    problems = []
    if missing:
        problems.append(f"setup countries without a row: {', '.join(missing)}")
    if extra:
        problems.append(f"rows for tags the setup does not have: {', '.join(extra)}")
    if duplicates:
        problems.append(f"duplicate rows: {', '.join(duplicates)}")
    if bad:
        problems.append(f"groups outside {low}..{high}: {', '.join(bad)}")
    if problems:
        raise StartTechnologyError(f"{COUNTRIES_CSV}: " + "; ".join(problems))
    subjects: dict[str, list[str]] = defaultdict(list)
    for overlord, subject, kind in dependencies(vanilla_root, mod_root):
        subjects[overlord].append(f"{subject} ({kind})" if kind else subject)
    overlord_floor = ladder.floors.get("overlord")
    pop_cap = ladder.caps.get("society_of_pops")
    out = []
    for country in countries:
        row = by_tag[country.tag]
        group = int(row["group"])
        level, floor = group, ""
        if overlord_floor is not None and subjects.get(country.tag) and group < overlord_floor:
            level = overlord_floor
            floor = f"overlord of {len(subjects[country.tag])}: {' '.join(subjects[country.tag][:6])}"
        if pop_cap is not None and country.country_type == "pop" and level > pop_cap:
            level = pop_cap
            floor = "society of pops: holds nothing until it settles"
        out.append(CountryGroup(country.tag, group, level, floor, country.vanilla_level, row.get("confidence", ""),
                                row.get("basis", "")))
    return out


def render_setup(groups: list[CountryGroup]) -> str:
    lines = [
        f"# {_HEADER}",
        "# Each country's starting technology level = its group of the starting technology ladder",
        "# (config/starting_technology_countries.csv after the floors). Read after 10_countries.txt: the partial",
        "# blocks merge into the countries and the level set here wins.",
        "countries = {",
        "\tcountries = {",
    ]
    lines += [f"\t\t{g.tag} = {{ {LEVEL_KEY} = {g.level} }}" for g in groups]
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"


