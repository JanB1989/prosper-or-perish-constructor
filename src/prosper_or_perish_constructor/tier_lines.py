"""Upgrade lines bound to a raw material: tier prices, level bonus, depth caps, skip-tier upgrades ([tier_lines]).

Once a building's successor is researched, the old tier cannot be built any more, so the upgrade's price is the price
of growing the site at all. Without an own price a building costs what its unlock's age costs, so these lines paid
4-24x the base tier for 1.0-1.5x its profit (run 6ee05b7e, 1837: lead 75/600/1800, coal 75/1200/1800, iron 75/300/600;
2,715 of 3,163 eligible sites never entered the AI's queue, and iron sat at under half a month of stock). Finalize pass
over the compiled buildings, the blueprints stay as they are:

- Price: a tier's worth is its profit per level at base goods prices x `payback_months`. The lowest tier pays that
  inside `base_min` and `base_max`, a higher tier inside `step_min` and `step_max` x the tier below, in steps of
  `round_to`. The keys hold final gold; zz_pp_building_price_stockpile.txt (x1.5) does not touch them.
- Level bonus: a positive `local_<good>_output_modifier` on the line's own good x `level_bonus_factor`.
- Depth: a tier above the lowest on `rural_building_cap` gets that cap x (1 + `depth_per_tier` x tier), one labelled row.
- Skip-tier upgrades: each tier also names every older tier as `obsolete`. Only the next tier was named, so a site two
  tiers behind could neither be built on nor upgraded (iron: 97 sites, 1 entry in the queue).

`[tier_lines.price_overrides]` sets the price of single buildings outside these lines, nothing else about them.
"""

from __future__ import annotations

import re
import tomllib
from collections import defaultdict
from dataclasses import dataclass, field
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

from prosper_or_perish_constructor import building_footprint as bf
from prosper_or_perish_constructor import production_gate as pg
from prosper_or_perish_constructor import yaml_io

PRICES_OUTPUT = Path("in_game/common/prices/pp_tier_line_prices.txt")
CAPS_OUTPUT = Path("in_game/common/script_values/pp_tier_line_caps.txt")
CAPS_SOURCE = Path("in_game/common/script_values/pp_building_cap_adjustments.txt")
LOC_OUTPUT = Path("main_menu/localization/english/pp_tier_lines_l_english.yml")
BLUEPRINTS = Path("blueprints/accepted/buildings")
BASE_CAP = "rural_building_cap"
DEPTH_ROW = "PP_BUILDING_LEVEL_UPGRADED_TIER"
DEPTH_ROW_TEXT = "Upgraded Building"
HEADER = "# Generated by ppc build (tier_lines.py) from [tier_lines] in constructor.toml. Do not edit by hand.\n"

_OBSOLETE_RE = re.compile(r"(?m)^\s*obsolete\s*=\s*(\w+)")
_POTENTIAL_RE = re.compile(r"location_potential\s*=\s*\{(.*?)\n\s*\}", re.DOTALL)
_NEGATED_RE = re.compile(r"(NOT|NOR)\s*=\s*\{[^{}]*\}", re.DOTALL)
_RAW_MATERIAL_RE = re.compile(r"raw_material\s*=\s*goods:(\w+)")
_MODIFIER_RE = re.compile(r"(?m)^\s*modifier\s*=\s*\{(.*?)^\s*\}", re.DOTALL)
_OUTPUT_MODIFIER_RE = re.compile(r"local_(\w+)_output_modifier\s*=\s*(-?[\d.]+)")
_CAP_RE = re.compile(r"(?m)^\s*max_levels\s*=\s*(\S+)")


@dataclass(frozen=True)
class Config:
    payback_months: float
    base_min: float
    base_max: float
    step_min: float
    step_max: float
    round_to: int
    extra_lines: frozenset[str]
    exclude_lines: frozenset[str]
    level_bonus_factor: Decimal
    depth_per_tier: Decimal
    price_overrides: dict[str, int]


@dataclass(frozen=True)
class Tier:
    tag: str
    line: str
    tier: int  # 0 = lowest
    price: int
    value: float = 0.0
    previous: str | None = None
    older: tuple[str, ...] = ()  # tiers below the previous one, nearest first
    deepens: bool = False  # on BASE_CAP above the lowest tier
    bonus: tuple[tuple[str, Decimal], ...] = ()  # own good -> blueprint value


@dataclass
class Result:
    buildings: int = 0
    lines: int = 0
    files_changed: int = 0
    not_in_mod: list[str] = field(default_factory=list)


def load_config(project: Path) -> Config:
    section = tomllib.loads(Path(project).read_text(encoding="utf-8-sig"))["tier_lines"]
    return Config(
        payback_months=float(section["payback_months"]),
        base_min=float(section["base_min"]),
        base_max=float(section["base_max"]),
        step_min=float(section["step_min"]),
        step_max=float(section["step_max"]),
        round_to=int(section["round_to"]),
        extra_lines=frozenset(section["extra_lines"]),
        exclude_lines=frozenset(section["exclude_lines"]),
        level_bonus_factor=Decimal(str(section["level_bonus_factor"])),
        depth_per_tier=Decimal(str(section["depth_per_tier"])),
        price_overrides={str(tag): int(gold) for tag, gold in section.get("price_overrides", {}).items()},
    )


def tier_price(value: float, below: int | None, config: Config) -> int:
    """Final gold of a tier with this profit per level at base prices, given the price of the tier below."""
    worth = max(value, 0.0) * config.payback_months
    if below is None:
        price = min(max(worth, config.base_min), config.base_max)
    else:
        price = min(max(worth, below * config.step_min), below * config.step_max)
    steps = Decimal(str(price / config.round_to)).quantize(Decimal(1), rounding=ROUND_HALF_UP)
    return int(steps) * config.round_to


def _profit_per_level(body: str, prices: dict[str, float]) -> float:
    """Sum over the slots of the slot's most profitable method."""
    slots, _ = pg.body_slots(body)
    return sum(max((m.value(prices) - m.cost(prices) for m in slot.methods), default=0.0) for slot in slots)


def _bound_to_raw_material(body: str) -> bool:
    potential = _POTENTIAL_RE.search(body)
    return bool(potential and _RAW_MATERIAL_RE.search(_NEGATED_RE.sub("", potential.group(1))))


def _own_good_bonus(body: str) -> tuple[tuple[str, Decimal], ...]:
    modifier = _MODIFIER_RE.search(body)
    if not modifier:
        return ()
    slots, _ = pg.body_slots(body)
    goods = {method.produced for slot in slots for method in slot.methods if method.produced}
    return tuple(
        (good, Decimal(value))
        for good, value in _OUTPUT_MODIFIER_RE.findall(modifier.group(1))
        if good in goods and Decimal(value) > 0
    )


def _producing_bodies(repo: Path) -> dict[str, str]:
    bodies: dict[str, str] = {}
    for path in sorted((Path(repo) / BLUEPRINTS).glob("*.yml")):
        building = yaml_io.safe_load(path.read_text(encoding="utf-8-sig")).get("building") or {}
        key, body = building.get("key"), building.get("body") or ""
        if key and any(method.produced for slot in pg.body_slots(body)[0] for method in slot.methods):
            bodies[key] = body
    return bodies


def plan(repo: Path, project: Path) -> list[Tier]:
    """Every tier of the lines in scope, lowest first per line, then the price overrides."""
    config = load_config(project)
    prices = pg.load_prices(repo, project)
    bodies = _producing_bodies(repo)
    previous = {tag: found.group(1) for tag, body in bodies.items() if (found := _OBSOLETE_RE.search(body))}

    def chain(tag: str) -> list[str]:  # oldest first, ending in tag
        tiers = [tag]
        while (older := previous.get(tiers[0])) in bodies and older not in tiers:
            tiers.insert(0, older)
        return tiers

    lines: dict[str, list[str]] = defaultdict(list)
    for tag in bodies:
        lines[chain(tag)[0]].append(tag)

    tiers: list[Tier] = []
    for line, members in sorted(lines.items()):
        if len(members) < 2 or line in config.exclude_lines:
            continue
        if not (_bound_to_raw_material(bodies[line]) or line in config.extra_lines):
            continue
        price: dict[str, int] = {}
        for tag in sorted(members, key=lambda member: len(chain(member))):
            below = chain(tag)[:-1]
            value = _profit_per_level(bodies[tag], prices)
            price[tag] = tier_price(value, price[below[-1]] if below else None, config)
            cap = _CAP_RE.search(bodies[tag])
            tiers.append(Tier(
                tag=tag,
                line=line,
                tier=len(below),
                price=price[tag],
                value=value,
                previous=below[-1] if below else None,
                older=tuple(reversed(below[:-1])),
                deepens=bool(below) and bool(cap) and cap.group(1) == BASE_CAP,
                bonus=_own_good_bonus(bodies[tag]),
            ))
    tiers += [Tier(tag=tag, line=tag, tier=0, price=gold) for tag, gold in sorted(config.price_overrides.items())]
    return tiers


def cap_name(tier: int) -> str:
    return f"pp_{BASE_CAP}_tier_{tier}"


def _fmt(value: Decimal) -> str:
    return format(value.quantize(Decimal("0.00001"), rounding=ROUND_HALF_UP).normalize(), "f")


def _set_price(body: str, key: str) -> str:
    tops = bf._depth_zero_text(body)
    line = re.search(r"(?m)^(?P<indent>[ \t]*)price[ \t]*=[ \t]*\S+", tops)
    if line:
        return f"{body[:line.start()]}{line['indent']}price = {key}{body[line.end():]}"
    anchor = re.search(r"(?m)^(?P<indent>[ \t]*)increase_per_level_cost[ \t]*=[^\n]*\n", tops)
    if not anchor:
        raise ValueError(f"no increase_per_level_cost line to put {key} after")
    return f"{body[:anchor.end()]}{anchor['indent']}price = {key}\n{body[anchor.end():]}"


def _set_cap(body: str, cap: str) -> str:
    line = re.search(r"(?m)^(?P<indent>[ \t]*)max_levels[ \t]*=[ \t]*\S+", bf._depth_zero_text(body))
    if not line:
        raise ValueError(f"no max_levels line for {cap}")
    return f"{body[:line.start()]}{line['indent']}max_levels = {cap}{body[line.end():]}"


def _add_obsolete(body: str, previous: str, older: tuple[str, ...]) -> str:
    tops = bf._depth_zero_text(body)
    line = re.search(rf"(?m)^(?P<indent>[ \t]*)obsolete[ \t]*=[ \t]*{previous}\b[^\n]*\n", tops)
    if not line:
        raise ValueError(f"no obsolete = {previous} line")
    missing = [tag for tag in older if not re.search(rf"(?m)^[ \t]*obsolete[ \t]*=[ \t]*{tag}\b", tops)]
    return body[:line.end()] + "".join(f"{line['indent']}obsolete = {tag}\n" for tag in missing) + body[line.end():]


def _set_bonus(body: str, good: str, value: str) -> str:
    opening = re.search(r"(?m)^[ \t]*modifier[ \t]*=[ \t]*\{", bf._depth_zero_text(body))
    if not opening:
        raise ValueError(f"no modifier block for {good}")
    close = bf._brace_pairs(body)[opening.end() - 1]
    inner, changed = re.subn(rf"(local_{good}_output_modifier\s*=\s*)-?[\d.]+", rf"\g<1>{value}", body[opening.end():close])
    if not changed:
        raise ValueError(f"no local_{good}_output_modifier line")
    return body[:opening.end()] + inner + body[close:]


def rewrite(body: str, tier: Tier, config: Config) -> str:
    """The compiled block body with this tier's price, cap, obsolete lines and bonus; the same again on a second run."""
    body = _set_price(body, f"pp_{tier.tag}_price")
    if tier.deepens:
        body = _set_cap(body, cap_name(tier.tier))
    if tier.older:
        body = _add_obsolete(body, tier.previous, tier.older)
    for good, value in tier.bonus:
        body = _set_bonus(body, good, _fmt(value * config.level_bonus_factor))
    return body


def _render_prices(tiers: list[Tier]) -> str:
    rows = "".join(f"pp_{tier.tag}_price = {{ gold = {tier.price} }}\n" for tier in tiers)
    return f"{HEADER}# Final gold: zz_pp_building_price_stockpile.txt does not touch these keys.\n{rows}"


def _render_caps(source: str, tiers: list[Tier], config: Config) -> str:
    """One cap per tier: the rows of rural_building_cap (its tooltip stays) and one row for the extra depth."""
    opening = re.search(rf"(?m)^REPLACE:{BASE_CAP}\s*=\s*\{{", source)
    if not opening:
        raise ValueError(f"REPLACE:{BASE_CAP} not found in {CAPS_SOURCE}")
    rows = source[opening.end():bf._brace_pairs(source)[opening.end() - 1]].strip("\n")
    parts = [HEADER]
    for tier in sorted({t.tier for t in tiers if t.deepens}):
        depth = f"{cap_name(tier)}_depth"
        parts.append(
            f"\n{cap_name(tier)} = {{\n{rows}\n\tadd = {{\n\t\tdesc = \"{DEPTH_ROW}\"\n\t\tvalue = this.{depth}\n\t}}\n}}\n"
            f"\n{depth} = {{\n\tvalue = {BASE_CAP}\n\tmultiply = {_fmt(config.depth_per_tier * tier)}\n}}\n"
        )
    return "".join(parts)


def _render_loc(tiers: list[Tier]) -> str:
    rows = "".join(f"  pp_{tier.tag}_price: \"[ShowBuildingTypeName('{tier.tag}')|e] Price\"\n" for tier in tiers)
    return f"l_english:\n  {DEPTH_ROW}: \"{DEPTH_ROW_TEXT}\"\n{rows}"


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8-sig", newline="\n")


def apply(repo: Path, project: Path, mod_root: Path, vanilla_root: Path) -> Result:
    config = load_config(project)
    tiers = plan(repo, project)
    owners = bf.owner_blocks(mod_root, vanilla_root)
    result = Result(lines=len({tier.line for tier in tiers}))
    by_path: dict[Path, list[tuple[bf.Block, Tier]]] = defaultdict(list)
    for tier in tiers:
        if tier.tag in owners:
            by_path[owners[tier.tag].path].append((owners[tier.tag], tier))
            result.buildings += 1
        else:
            result.not_in_mod.append(tier.tag)
    for path, items in by_path.items():
        text = bf._read(path)
        new = text
        for block, tier in sorted(items, key=lambda item: -item[0].open):
            new = new[:block.open + 1] + rewrite(new[block.open + 1:block.close], tier, config) + new[block.close:]
        if new != text:
            _write(path, new)
            result.files_changed += 1
    _write(Path(mod_root) / PRICES_OUTPUT, _render_prices(tiers))
    _write(Path(mod_root) / CAPS_OUTPUT, _render_caps(bf._read(Path(mod_root) / CAPS_SOURCE), tiers, config))
    _write(Path(mod_root) / LOC_OUTPUT, _render_loc(tiers))
    return result
