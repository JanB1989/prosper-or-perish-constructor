@dataclass(frozen=True)
class Item:
    """One plan of the tab: its picker entry (group, icon) and what it builds."""

    key: str
    group: str
    icon: str
    good: bool
    builds: tuple[str, ...]  # its buildings, lowest tier first
    rank: str | None  # the rank its producers need when the plan raises the settlement (town / city), else None
    charter: str | None  # the specialization charter the plan grants
    rights: str | None  # the stronger rights it swaps the charter for (or grants alone)

    @property
    def upper(self) -> str:
        return self.key.upper()


@dataclass
class Result:
    items: list[Item] = field(default_factory=list)
    files_changed: int = 0


# ---------------------------------------------------------------------------------------------------------------------
# expressions


def value(name: str) -> str:
    return f"GetPlayer.MakeScope.ScriptValue('{name}')"


def is_on(name: str) -> str:
    return f"GreaterThan_CFixedPoint({value(name)}, '(CFixedPoint)0.5')"


def is_any(name: str) -> str:
    return f"EqualTo_CFixedPoint({value(name)}, '(CFixedPoint)0')"


def call(gui: str, key: str | None = None) -> str:
    scope = f".AddScope('pp_key', MakeScopeFlag('{key}'))" if key else ""
    return f"[GetScriptedGui('{gui}').Execute(GuiScope.SetRoot(GetPlayer.MakeScope){scope}.End)]"


def selected(item: Item) -> str:
    return f"GetVariableSystem.HasValue('{SELECTED}', '{item.key}')"


def own(item: Item) -> str:
    return is_on(PB_OWN + item.key)


def used_values(items: list[Item]) -> set[str]:
    """Every script value the tab reads."""
    return set(CONTRACT_VALUES) | {prefix + item.key for item in items for prefix in CONTRACT_VALUE_PREFIXES}


