# the plans


def build_items(repo: Path, project: Path, mod_root: Path, vanilla_root: Path) -> list[Item]:
    """Every plan in the picker's order (location_plan: its groups and icons), with its buildings (town_plans) and the
    charter and rights it grants (construction_plan_country.plan_grants)."""
    from prosper_or_perish_constructor import construction_plan as cp
    from prosper_or_perish_constructor import construction_plan_country as cc
    from prosper_or_perish_constructor import location_plan as lp
    from prosper_or_perish_constructor import location_profiles as lpf

    depths = lpf.tier_depths(cp._database(mod_root, vanilla_root, cp.BUILDING_TYPES))
    picker = lp.plannable(lp.plans_for(repo, project, mod_root, vanilla_root))
    plans = {plan.key: plan for plan in town_plans.plans(repo, project, mod_root, vanilla_root)}
    if [plan.key for plan in picker] != list(plans):
        raise ValueError("the Location Plan picker and the plan list differ")
    rights, _, _ = cc.read_rights(mod_root, vanilla_root)
    grants = {grant.plan: grant for grant in cc.plan_grants([r for r in rights if r.icon], set(plans))}
    items: list[Item] = []
    for entry in picker:
        plan = plans[entry.key]
        grant = grants.get(plan.key)
        items.append(Item(
            key=plan.key, group=entry.group, icon=entry.icon, good=entry.good,
            builds=tuple(sorted(plan.candidates, key=lambda name: (depths.get(name, 0), name))),
            rank=plan.rank if plan.raises else None,
            charter=grant.charter if grant else None, rights=grant.rights if grant else None,
        ))
    return items


def groups(items: list[Item]) -> list[tuple[str, list[Item]]]:
    order: list[tuple[str, list[Item]]] = []
    for item in items:
        if not order or order[-1][0] != item.group:
            order.append((item.group, []))
        order[-1][1].append(item)
    return order


# ---------------------------------------------------------------------------------------------------------------------
# layout arithmetic (see the constants on top)


def _plain_chars(text: str) -> int:
    """The visible length of a card text, a linked game name counted as LINK_CHARS."""
    return len(re.sub(r"\[[^\]]*\]|\$[A-Za-z0-9_]+\$", "x" * LINK_CHARS, text))


def card_text_lines(item: Item) -> int:
    return sum(max(1, math.ceil(_plain_chars(part) / CHARS_PER_LINE)) for part in card_text(item).split("\n"))


def card_rows(item: Item) -> int:
    return 1 + len(card_options(item))  # the payback limit, then the options


def card_height(item: Item) -> int:
    rows = card_rows(item)
    return CARD_TITLE_H + CARD_GAP + max(card_text_lines(item) * LINE_H, rows * ROW_H + (rows - 1) * CARD_GAP)


def grid_rows(items: list[Item]) -> int:
    return sum(math.ceil(len(members) / PER_ROW) for _, members in groups(items))


def grid_height(items: list[Item]) -> int:
    rows, count = grid_rows(items), len(groups(items))
    return rows * TILE_SIZE + (rows - count) * TILE_GAP + (count - 1) * GROUP_GAP


def shared_rows() -> int:
    return 8 + len(tpo.options(tpo.ALL))  # the eight older settings, then the new ones


def layout_heights(items: list[Item]) -> dict[str, int]:
    """The fixed heights of the two columns (px, margins included); the right one with the tallest card."""
    rows = shared_rows()
    left = 2 * MARGIN_Y + TITLE_H + PART_GAP + rows * ROW_H + (rows - 1) * ROW_GAP
    card = max(card_height(item) for item in items)
    right = 2 * MARGIN_Y + TITLE_H + PART_GAP + grid_height(items) + PART_GAP + card
    return {"left": left, "right": right, "grid": grid_height(items), "card": card}


