def _name(item: Item) -> str:
    return f"[ShowGoodsName('{item.key}')|e]" if item.good else f"$PP_TPLAN_NAME_{item.upper}$"


def _building(key: str) -> str:
    return f"[ShowBuildingTypeName('{key}')|e]"


def _listed(names: list[str]) -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def card_text(item: Item) -> str:
    """What the plan builds, in tier order; whether it raises the settlement; the charter and rights it grants."""
    if len(item.builds) <= MAX_NAMES:
        what = f"Builds {_listed([_building(b) for b in item.builds])}, each newer kind once you have researched it."
    elif item.key == "food":
        what = (f"Builds the buildings that feed the [province|e]: the producers of the [pp_staple_foods|e], the "
                f"{_building('cookshop')} and the {_building('tavern')}, each newer kind once you have researched it.")
    elif item.key == "trade":
        first = "marketplace" if "marketplace" in item.builds else item.builds[0]
        what = (f"Builds the trade buildings, such as the {_building(first)}, each newer kind once you have "
                "researched it.")
    else:
        what = (f"Builds {_listed([_building(b) for b in item.builds[:MAX_NAMES]])} and the other makers of "
                f"{_name(item)}, each newer kind once you have researched it.")
    lines = [what]
    if item.rank:
        lines.append(f"They need a [ShowLocationRankName('{item.rank}')], so the plan raises the [location_rank|e] of a "
                     "smaller settlement first.")
    if item.charter and item.rights:
        lines.append(f"Grants the planned town the [ShowTownRightsName('{item.charter}')] and later the stronger "
                     f"[ShowTownRightsName('{item.rights}')], where their conditions hold.")
    elif item.rights:
        lines.append(f"Grants the planned town the [ShowTownRightsName('{item.rights}')], where its conditions hold.")
    return "\n".join(lines)


