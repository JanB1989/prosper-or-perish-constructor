def _write(path: Path, text: str, write: bool) -> bool:
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    if old == text:
        return False
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return True


def apply(repo: Path, project: Path, mod_root: Path, vanilla_root: Path, write: bool = True) -> Result:
    items = build_items(repo, project, mod_root, vanilla_root)
    result = Result(items=items)
    texts_out = {mod_root / GUI: "\ufeff" + render_gui(items), mod_root / LOC: render_loc(items)}
    result.files_changed = sum(_write(path, text, write) for path, text in texts_out.items())
    return result


def summary(result: Result) -> str:
    return (f"Construction Plan, Plans tab: {len(result.items)} plans "
            f"({sum(1 for item in result.items if item.rank)} raise the rank, "
            f"{sum(1 for item in result.items if item.rights)} grant rights), {result.files_changed} files changed.")
