"""Location-window tooltips that list goods output apart from the other effects, and the land-potential chip.

View only: nothing here changes a game value. The engine lists every line of a modifier in one list, so the ~20-30
goods output rows of a climate, vegetation or topography class, a winter or a harvest bury the handful of effects a
player opens the tooltip for. For every such value the constructor writes

- ``pp_tt_<attribute>_<value>``: a static modifier holding the value's other lines. It is never applied; the tooltip
  shows it with ``ShowModifierEffect``, so the engine formats it like any modifier list;
- for the classes, the engine's non-modifier terrain lines (winter, movement cost, attacker penalty, ...) as one text
  block, worded from vanilla's own localization;
- a goods table, best first: one icon and value per good, or one row per value when many goods share it.

The land-potential chip sums the goods output of the land attributes (class, fertility, soil, coast, lake) per good
in script values and lists the goods in six labelled tiers. The GUI cannot sort by a value, so a script value puts each
good in a 2% step and a tier's line holds a cell per (good, step), steps best first, shown only in the good's step.
Only the (good, step) pairs that occur at some location get a cell (the attributes never change), which keeps the
tooltip at a few hundred cheap tests.

The values are read back from the files the game loads (the class definitions with the mod's injects, the static
modifiers), so the views show what applies. The location window is patched before those files are written (geography
sync), so it refers to the generated templates and types by name only.
"""

