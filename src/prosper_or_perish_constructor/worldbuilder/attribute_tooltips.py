@dataclass(frozen=True)
class View:
    attribute: str                   # climate, vegetation, topography, fertility, soil, coast, lake, winter, harvest
    value: str                       # class key, fertility or soil class, winter level, harvest, shore modifier
    gate: str                        # GUI test: the location has this value
    name: str                        # localization naming the value
    effects: dict[str, str]          # the value's lines without goods output
    goods: list[tuple[str, float]]   # goods output, best first
    extras: list[str] = ()           # the engine's non-modifier terrain lines, localized
    trigger: str | None = None       # script trigger for the land potential (land attributes only)

    @property
    def modifier(self) -> str:
        return f"pp_tt_{self.attribute}_{self.value}"

    @property
    def extras_key(self) -> str:
        return f"PP_TT_EXTRAS_{self.attribute}_{self.value}".upper()


def split_goods(lines: Mapping[str, str], goods: set[str]) -> tuple[dict[str, str], list[tuple[str, float]]]:
    """(effects, goods output best first): output lines of real goods move to the table, everything else stays."""
    effects: dict[str, str] = {}
    output: list[tuple[str, float]] = []
    for key, value in lines.items():
        match = _OUTPUT.fullmatch(key)
        number = _number(value)
        if match and match[1] in goods and number is not None:
            output.append((match[1], number))
        else:
            effects[key] = value
    return effects, sorted(output, key=lambda item: (-item[1], item[0]))


# Terrain fields the engine prints in a class tooltip, in its order, with the vanilla localization that words them.
# Movement cost is a multiplier; the line shows how far it is from normal ground.
TERRAIN_LINES = (
    ("movement_cost", "TERRAIN_MOVEMENT_COST", lambda v: v - 1.0),
    ("defender", "TERRAIN_ATTACKER_PENALTY", lambda v: v),
    ("proximity", "TERRAIN_PROXIMITY_COST", lambda v: v),
    ("colonial_migration_size_modifier", "TERRAIN_COLONIAL_MIGRATION", lambda v: v),
)
TERRAIN_FLAGS = (("can_freeze_over", "TERRAIN_CAN_FREEZE_OVER"), ("blocked_in_winter", "TERRAIN_BLOCKS_IN_WINTER"))
WINTER_KEY = "CLIMATE_TT_WINTER"
EXTRA_KEYS = [key for _, key, _ in TERRAIN_LINES] + [key for _, key in TERRAIN_FLAGS] + [WINTER_KEY]


def format_value(value: float, flags: str) -> str:
    """A number as the game's ``$VALUE|flags$`` shows it: ``%`` percent, ``=`` explicit plus, ``+``/``-`` green when
    the value is positive/negative."""
    shown = value * 100 if "%" in flags else value
    text = f"{shown:.1f}".rstrip("0").rstrip(".")
    text = ("+" + text if "=" in flags and shown > 0 else text) + ("%" if "%" in flags else "")
    good = (shown > 0) if "+" in flags else (shown < 0) if "-" in flags else None
    if good is None or shown == 0:
        return text
    return f"#{'P' if good else 'N'} {text}#!"


def _substitute(text: str, value: float) -> str:
    return re.sub(r"\$VALUE(?:\|([^$]*))?\$", lambda m: format_value(value, m[1] or ""), text)


def terrain_lines(fields: Mapping[str, str], loc: Mapping[str, str]) -> list[str]:
    lines: list[str] = []
    if "winter" in fields and WINTER_KEY in loc:
        lines.append(loc[WINTER_KEY].replace("$MAX$", fields["winter"]))
    for field, key, shown in TERRAIN_LINES:
        number = _number(fields.get(field, ""))
        if number is not None and key in loc and abs(shown(number)) > 1e-9:
            lines.append(_substitute(loc[key], shown(number)))
    lines.extend(loc[key] for field, key in TERRAIN_FLAGS if fields.get(field) == "yes" and key in loc)
    return lines


def class_gate(attribute: str, key: str) -> str:
    return f"EqualTo_string({_LOC}.Custom('pp_tt_{attribute}'), Localize('{class_token(attribute, key)}'))"


def class_token(attribute: str, key: str) -> str:
    return f"PP_TT_KEY_{attribute}_{key}".upper()


def class_views(vanilla_root: Path | None, mod_root: Path, goods: set[str], loc: Mapping[str, str]) -> dict[str, list[View]]:
    views: dict[str, list[View]] = {}
    for attribute, directory in CLASS_DIRS.items():
        views[attribute] = []
        for key, body in definitions(game_files(vanilla_root, mod_root, f"in_game/common/{directory}")).items():
            effects, output = split_goods(modifier_lines(body, "location_modifier"), goods)
            views[attribute].append(View(attribute, key, class_gate(attribute, key), f"${key}$", effects, output, terrain_lines(scalars(body), loc), f"{attribute} = {key}"))
    return views


def static_views(defs: Mapping[str, Block], goods: set[str], harvests: Iterable[str]) -> dict[str, list[View]]:
    """Fertility, soil, coast and lake chips (the World Builder static modifiers, gated like the chips gate them), the
    winter levels and the harvests."""
    harvest_keys = set(harvests)
    views: dict[str, list[View]] = {"fertility": [], "soil": [], "coast": [], "lake": [], "winter": [], "harvest": []}
    for name, body in defs.items():
        trigger = f"has_location_modifier = {name}"
        if match := re.fullmatch(r"pp_wb_fertility_(\w+)", name):
            attribute, value = "fertility", match[1]
            gate = f"EqualTo_string({_LOC}.Custom('ha1300_fertility_name'), Localize('HA1300_FERTILITY_{value.upper()}'))"
        elif match := re.fullmatch(r"pp_wb_soil_(\w+)", name):
            attribute, value = "soil", match[1]
            gate = f"EqualTo_string({_LOC}.Custom('ha1300_soil_type_name'), Localize('HA1300_SOIL_{value.upper()}_TITLE'))"
        elif name in SHORE_GATES:
            (attribute, gate), value = SHORE_GATES[name], name.removeprefix("pp_wb_")
        elif (match := re.fullmatch(r"winter_(\w+)", name)) and match[1] in WINTER_LEVELS:
            attribute, value, trigger = "winter", match[1], None
            gate = class_gate("winter", value)
        elif name in harvest_keys:
            attribute, value, trigger = "harvest", name.removeprefix("pp_harvest_"), None
            gate = location_status.harvest_gate(name)
        else:
            continue
        effects, output = split_goods(modifier_lines(body), goods)
        views[attribute].append(View(attribute, value, gate, f"$STATIC_MODIFIER_NAME_{name}$", effects, output, trigger=trigger))
    return views


