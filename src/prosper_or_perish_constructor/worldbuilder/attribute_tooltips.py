def goods_table(goods: list[tuple[str, float]]) -> str:
    rows = []
    for start in range(0, len(goods), CELLS_PER_ROW):
        cells = " ".join(
            f'pp_goods_output_cell = {{ blockoverride "good_icon" {{ texture = "gfx/interface/icons/trade_goods/icon_goods_{good}.dds" '
            f'tooltip = "[ShowGoodsName(\'{good}\')]" }} blockoverride "good_value" {{ raw_text = "{format_value(value, "+=%")}" }} }}'
            for good, value in goods[start:start + CELLS_PER_ROW]
        )
        rows.append(f'\t\t\t\t\tpp_goods_output_row = {{ blockoverride "cells" {{ {cells} }} }}')
    return "\t\t\t\tpp_goods_output_table = { blockoverride \"rows\" {\n" + "\n".join(rows) + "\n\t\t\t\t} }"


def view_section(view: View) -> str:
    parts = []
    if view.effects:
        parts.append(f"\t\t\t\tTooltipStringPairList = {{ textcontext = \"[ShowModifierEffect('{view.modifier}')]\" }}")
    if view.extras:
        parts.append(f'\t\t\t\tTooltipTextBlock = {{ blockoverride "text" {{ text = "{view.extras_key}" }} }}')
    if view.goods:
        parts.append(goods_table(view.goods))
    body = "\n".join(parts)
    return f'\t\tTooltipContentSection = {{\n\t\t\tvisible = "[{view.gate}]"\n\t\t\tblockoverride "section_content" {{\n{body}\n\t\t\t}}\n\t\t}}'


def view_type(attribute: str, views: list[View]) -> str:
    sections = "\n".join(view_section(view) for view in views if view.effects or view.extras or view.goods)
    return f"\ttype pp_attribute_view_{attribute} = vbox {{\n\t\tlayoutpolicy_horizontal = expanding\n\t\tspacing = 10\n\t\tignoreinvisible = yes\n{sections}\n\t}}"


def _close(text: str, start: int) -> int:
    """Index just past the brace block opening at ``text[start] == '{'``; comments and strings are skipped."""
    depth, i = 0, start
    while i < len(text):
        char = text[i]
        if char == "#":
            i = text.find("\n", i)
            if i < 0:
                break
            continue
        if char == '"':
            i = text.index('"', i + 1)
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced braces")


def _template(gui: str, name: str) -> str:
    match = re.search(rf"^template {name} \{{", gui, flags=re.MULTILINE)
    if match is None:
        raise ValueError(f"vanilla location tooltips: template {name} not found")
    return gui[match.start():_close(gui, match.end() - 1)]


def class_template(gui: str, attribute: str) -> str:
    """Vanilla's class tooltip with its modifier list swapped for the view. The engine's own list stays for classes the
    view does not know (another mod's), where the location's key resolves to the fallback."""
    template = _template(gui, CLASS_TEMPLATES[attribute])
    content = re.search(r'blockoverride "tooltip_content" \{', template)
    if content is None:
        raise ValueError(f"{CLASS_TEMPLATES[attribute]}: no tooltip_content")
    end = _close(template, content.end() - 1)
    marker = template.find(".GetTooltip]", content.end(), end)
    if marker < 0:
        raise ValueError(f"{CLASS_TEMPLATES[attribute]}: no engine modifier list to replace")
    i = content.end()
    while True:   # the direct child of tooltip_content holding the engine list
        child = re.compile(r"\w+\s*=\s*\{").search(template, i, end)
        if child is None:
            raise ValueError(f"{CLASS_TEMPLATES[attribute]}: engine list not found among the content blocks")
        child_end = _close(template, child.end() - 1)
        if child.start() < marker < child_end:
            break
        i = child_end
    fallback = f'visible = "[EqualTo_string({_LOC}.Custom(\'pp_tt_{attribute}\'), Localize(\'PP_TT_KEY_NONE\'))]"'
    engine_list = template[child.start():child.end()] + f"\n                {fallback}" + template[child.end():child_end]
    swapped = template[:child.start()] + f"pp_attribute_view_{attribute} = {{}}\n            " + engine_list + template[child_end:]
    return swapped.replace(f"template {CLASS_TEMPLATES[attribute]} {{", f"template pp_attribute_tooltip_{attribute} {{", 1)


def render_gui(vanilla_gui: str, views: Mapping[str, list[View]]) -> str:
    templates = "\n\n".join(class_template(vanilla_gui, attribute) for attribute in CLASS_TEMPLATES)
    types = "\n\n".join(view_type(attribute, attribute_views) for attribute, attribute_views in views.items())
    header = f"{GENERATED}\n# The geography chips of the location window: effects first, goods output as an icon table after (view only)."
    return f"{header}\n\n{templates}\n\ntypes pp_attribute_tooltips\n{{\n{_TYPES}\n{types}\n}}\n"


# --- script and localization ---------------------------------------------------------------------------------------

def render_modifiers(views: Iterable[View]) -> str:
    blocks = [GENERATED, "# Tooltip views of the attribute chips (attribute_tooltips.py): never applied, only shown with ShowModifierEffect."]
    for view in views:
        if view.effects:
            lines = "\n".join(f"\t{key} = {value}" for key, value in view.effects.items())
            blocks.append(f"{view.modifier} = {{\n\tgame_data = {{ category = location }}\n{lines}\n}}")
    return "\n\n".join(blocks) + "\n"


def render_custom_localization(views: Mapping[str, list[View]]) -> str:
    blocks = [GENERATED]
    for attribute in CLASS_TEMPLATES:
        lines = [f"pp_tt_{attribute} = {{", "\ttype = location"]
        lines += [f"\ttext = {{ localization_key = {class_token(attribute, v.value)} trigger = {{ {attribute} = {v.value} }} }}" for v in views[attribute]]
        lines += ["\ttext = { localization_key = PP_TT_KEY_NONE fallback = yes }", "}"]
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"


_LOC_NEWLINE = "\\n"   # a line break inside a localization string


def _yml(text: str) -> str:
    return text.replace('"', '\\"')


def render_localization(views: Mapping[str, list[View]]) -> str:
    lines = ["l_english:", f" {GENERATED}", ' PP_TT_GOODS_OUTPUT: "Goods Output"', ' PP_TT_KEY_NONE: "none"']
    for attribute_views in views.values():
        for view in attribute_views:
            if view.attribute in CLASS_TEMPLATES:
                lines.append(f' {class_token(view.attribute, view.value)}: "{view.value}"')
            if view.effects:
                lines.append(f' STATIC_MODIFIER_NAME_{view.modifier}: "{view.name}"')
            if view.extras:
                lines.append(f' {view.extras_key}: "{_LOC_NEWLINE.join(_yml(line) for line in view.extras)}"')
    return "\n".join(lines) + "\n"


def write(mod_root: Path, vanilla_root: Path | None) -> dict[str, int]:
    """Write the chip tooltips; run after the class injects and the World Builder static modifiers are written."""
    goods = goods_keys(vanilla_root, mod_root)
    loc = vanilla_localization(vanilla_root, EXTRA_KEYS)
    views = {**class_views(vanilla_root, mod_root, goods, loc), **static_views(vanilla_root, mod_root, goods)}
    vanilla_gui = (Path(vanilla_root) / VANILLA_TOOLTIPS).read_text(encoding="utf-8-sig")
    outputs = {
        GUI_PATH: render_gui(vanilla_gui, views),
        MODIFIERS_PATH: render_modifiers(view for attribute_views in views.values() for view in attribute_views),
        CUSTOM_LOC_PATH: render_custom_localization(views),
        LOCALIZATION_PATH: render_localization(views),
    }
    for rel, text in outputs.items():
        path = Path(mod_root) / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("﻿" + text, encoding="utf-8", newline="\n")
    return {attribute: sum(1 for v in attribute_views if v.goods) for attribute, attribute_views in views.items()}
