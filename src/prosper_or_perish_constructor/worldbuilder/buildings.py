"""Improvement buildings, farm land costs and game-start setup from the World Builder contract.

Improvement buildings (one per World Builder ledger type, mapped to blueprint keys in constructor.toml):
- ``raw_modifier local_population_capacity`` = people per level / 1000 (unscaled by staffing);
- ``max_levels = pp_wb_cap_<key>``: a script value = base + attribute class terms + levels per development
  point x development, floored, clamped to the level limit; classes are tested with the location's own
  climate/vegetation/topography, the ``pp_wb_fertility_*`` / ``pp_wb_soil_*`` static modifiers (placed in the
  game-start setup, so they already exist when the engine validates starting levels), the river size
  modifier, coast and lake;
- ``location_potential``: the World Builder gate (OR of ANDs over the same attributes);
- starting levels written to ``main_menu/setup/1337/14_pp_worldbuilder_buildings.txt`` for owned locations.

Niche buildings (``[worldbuilder.buildings.niche]``: culture- or country-locked vanilla buildings such as the Khmer
baray) keep their lock and join a general family: every member carries a level counter
(``raw_modifier pp_wb_levels_<key> = 1``) and its max is the family's cap equation minus the other members' levels,
so a location never holds two full sets of the same idea. A niche level is worth ``strength`` x the family's people
per level. A member with ``upgrades = <key>`` is a later tier of that building: its blueprint says ``obsolete = <key>``,
so each level built converts one lower-tier level, and its cap leaves the lower tiers' levels out (as the farm upgrade
chains do). Their blueprints must be full ``REPLACE`` or new ``CREATE`` definitions (the lock, the gate and the level formula cannot be
injected). ``vanilla_capacity_leaks`` lists vanilla buildings with capacity lines that the mod does not REPLACE.

Farm buildings (the mod's rural land users) take farmland: ``raw_modifier local_population_capacity = -land``
per level; their max level is generated by ``scripts/generate_rural_capacity_values.py`` from the same constants.
Levels and people per level may be rescaled per building with ``[worldbuilder.level_scale]`` (multiply
levels, divide people per level).
"""

