# River size as the caps read it. The engine's own river_flowing_through_N static modifier is invisible to
# has_location_modifier (only the ones pp_navigation_preserve_rivers adds where the engine traces no river are
# visible), so a cap row tested that way was missing in game wherever the engine traced the river itself (EU5 1.4
# start: irrigated fields on the Yangtze banks 8 levels and Taverns 1 level above max). Modifier values add up over
# static and script-added modifiers alike, and each river_flowing_through_N carries irrigant_cap_modifier = N
# (pp_location_modifier_adjustments.txt; start_simulation.run checks it).
RIVER_SIZE_MODIFIER = "irrigant_cap_modifier"
RIVER_SIZE_TRIGGERS_PATH = Path("in_game/common/scripted_triggers/pp_wb_river_size.txt")


def river_size_trigger(level: int | str) -> str:
    """The trigger a cap row uses for "the location's river has size ``level``" (1-5)."""
    return f"pp_wb_river_size_{int(level)} = yes"


def write_river_size_triggers(mod_root: Path) -> Path:
    """``pp_wb_river_size_1`` .. ``_5``: the river size read from ``modifier:irrigant_cap_modifier`` (see above)."""
    lines = [GENERATED, "# River size N <=> modifier:irrigant_cap_modifier = N (every river_flowing_through_N carries it). Read as a",
             "# modifier value, the engine's own river statics count too (has_location_modifier does not see them)."]
    for n in range(1, 6):
        lines.append(f"pp_wb_river_size_{n} = {{ modifier:{RIVER_SIZE_MODIFIER} > {n - 0.5} modifier:{RIVER_SIZE_MODIFIER} < {n + 0.5} }}")
    path = mod_root / RIVER_SIZE_TRIGGERS_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("﻿" + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


def _fmt(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


def _game_key(contract: Contract, attribute: str, value: str) -> str:
    rows = contract.attribute_rows.filter((pl.col("attribute") == attribute) & (pl.col("value") == value))
    return str(rows["game_key"][0]) if len(rows) and rows["game_key"][0] else value


def trigger_for(contract: Contract, attribute: str, value: str, *, gate: bool = False) -> str:
    navigation = (contract.root / "navigation/manifest.json").exists()
    if attribute == "river_level" and gate:
        # A gate must hold while the game validates the setup buildings, before the engine applies the river-size
        # modifiers, so it uses the map-native trigger. The World Builder gates only ever ask for "any river"
        # (levels 1-5) or "no river"; the caps' per-size class terms keep the size modifiers below.
        return "has_river = no" if str(value) == "0" else "has_river = yes"
    if attribute == "river_level" and str(value) != "0":
        # cap rows read the river size as a modifier value (river_size_trigger): the engine's own river statics count
        return river_size_trigger(value)
    if attribute == "river_level" and navigation:
        return "pp_navigation_has_river = no"
    if attribute == "is_coastal" and navigation:
        # river banks next to navigable water are coastal to the engine; the sea coast is the setup-placed modifier
        trigger = "has_location_modifier = pp_wb_coastal"
        return trigger if str(value) == "True" else f"NOT = {{ {trigger} }}"
    template = ATTRIBUTE_TRIGGERS[attribute]
    if attribute in ("is_coastal", "is_adjacent_to_lake"):
        return template if str(value) == "True" else f"NOT = {{ {template} }}"
    if attribute == "river_level" and str(value) == "0":
        return "has_river = no"  # river_flowing_through_0 does not exist
    return template.format(key=_game_key(contract, attribute, value), value=value)


def gate_trigger(contract: Contract, rules: list[dict[str, list[str]]]) -> list[str]:
    """OR over rules, AND within a rule, as indented trigger lines (without the location_potential wrapper)."""
    if not rules:
        return ["always = yes"]
    ands: list[list[str]] = []
    for rule in rules:
        conditions: list[str] = []
        for attribute, allowed in rule.items():
            allowed = [str(a) for a in allowed]
            if not allowed:
                conditions.append("always = no")
                continue
            triggers = list(dict.fromkeys(trigger_for(contract, attribute, a, gate=True) for a in allowed))
            if len(triggers) == 1:
                conditions.append(triggers[0])
            else:
                conditions.append("OR = { " + " ".join(triggers) + " }")
        ands.append(conditions)
    if len(ands) == 1:
        return ands[0]
    lines = ["OR = {"]
    for conditions in ands:
        if len(conditions) == 1:
            lines.append(f"\t{conditions[0]}")
        else:
            lines.append("\tAND = {")
            lines.extend(f"\t\t{c}" for c in conditions)
            lines.append("\t}")
    lines.append("}")
    return lines


def cap_script_value(contract: Contract, key: str, equation: Mapping[str, object], scale: float, level_limit: int, *, name: str | None = None) -> str:
    base = float(equation["base_levels"]) * scale
    lines = [f"{name or f'pp_wb_cap_{key}'} = {{", "\tadd = {", '\t\tdesc = "BUILDING_LEVEL_WB_BASE"', f"\t\tvalue = {_fmt(base)}", "\t}"]
    previous = None
    for term in equation["class_terms"]:
        levels = float(term["levels"]) * scale
        if not levels:
            continue
        attribute, value = str(term["attribute"]), str(term["value"])
        # A location has one class per exclusive attribute: its terms chain, so the checks stop at the match.
        branch = "else_if" if attribute == previous and attribute in EXCLUSIVE_ATTRIBUTES else "if"
        previous = attribute
        lines.extend([
            f"\t{branch} = {{",
            f"\t\tlimit = {{ {trigger_for(contract, attribute, value)} }}",
            "\t\tadd = {",
            f'\t\t\tdesc = "BUILDING_LEVEL_WB_{attribute.upper()}_{value.upper()}"',
            f"\t\t\tvalue = {_fmt(levels)}",
            "\t\t}",
            "\t}",
        ])
    gamma = float(equation["levels_per_development_point"]) * scale
    if gamma:
        lines.extend(["\tadd = {", '\t\tdesc = "BUILDING_LEVEL_WB_DEVELOPMENT"', "\t\tvalue = development", f"\t\tmultiply = {gamma:.4f}".rstrip("0").rstrip("."), "\t}"])
    # Every operation needs a desc, or the breakdown tooltip shows a "missing key" line; no floor = yes, the engine
    # floors max_levels to whole levels itself (2026-10-01).
    lines.extend([_clamp("min", "MINIMUM", 0), _clamp("max", "MAXIMUM", int(round(level_limit * scale))), "}"])
    return "\n".join(lines)


def _clamp(op: str, label: str, value: object) -> str:
    """A described min/max line of a cap script value (BUILDING_LEVEL_WB_MINIMUM / _MAXIMUM)."""
    return f'\t{op} = {{ desc = "BUILDING_LEVEL_WB_{label}" value = {value} }}'


def families(cfg: WorldBuilderConfig) -> dict[str, list[str]]:
    """general blueprint key -> niche keys sharing its cap (only families with at least one niche member)."""
    out: dict[str, list[str]] = {}
    for key, spec in cfg.niche.items():
        out.setdefault(str(spec["family"]), []).append(key)
    return out


def lower_tiers(cfg: WorldBuilderConfig, key: str) -> list[str]:
    """The buildings ``key`` upgrades (the ``upgrades`` chain of its niche spec), nearest first."""
    chain: list[str] = []
    current = cfg.niche.get(key, {}).get("upgrades")
    while current and current not in chain:
        chain.append(current)
        current = cfg.niche.get(current, {}).get("upgrades")
    return chain


def shared_cap_value(name: str, source: str, siblings: list[str]) -> str:
    """``name`` = the family's cap equation minus the levels already used by the other family members."""
    lines = [f"{name} = {{", "\tadd = {", '\t\tdesc = "BUILDING_LEVEL_WB_FAMILY"', f"\t\tvalue = {source}", "\t}"]
    for sibling in siblings:
        lines.extend(["\tsubtract = {", f'\t\tdesc = "BUILDING_LEVEL_WB_SHARED_{sibling.upper()}"', f"\t\tvalue = modifier:{LEVELS_MODIFIER.format(key=sibling)}", "\t}"])
    lines.extend([_clamp("min", "MINIMUM", 0), "}"])
    return "\n".join(lines)


def write_level_counters(keys: list[str], mod_root: Path) -> None:
    """Modifier types (with icon and name) for the per-building level counters of shared families."""
    types = [GENERATED, "# Level counters of buildings that share a cap: raw_modifier pp_wb_levels_<key> = 1 per level.", ""]
    icons = [GENERATED, ""]
    loc = ["l_english:"]
    for key in keys:
        modifier = LEVELS_MODIFIER.format(key=key)
        types.extend([f"{modifier} = {{", "\tdecimals = 0", "\tgame_data = {", "\t\tcategory = location", "\t}", "}", ""])
        icons.extend([f"{modifier} = {{", f'\tpositive = "gfx/interface/icons/buildings/{key}.dds"', f'\tnegative = "gfx/interface/icons/buildings/{key}.dds"', "}", ""])
        loc.append(f'  MODIFIER_TYPE_NAME_{modifier}: "${key}$ levels"')
        loc.append(f'  MODIFIER_TYPE_DESC_{modifier}: "Levels of ${key}$ in this location. They count against the shared cap of every building of the same kind."')
    for path, lines in ((LEVELS_TYPES_PATH, types), (LEVELS_ICONS_PATH, icons), (LEVELS_LOC_PATH, loc)):
        target = mod_root / path
        if not keys:
            if target.is_file():
                target.unlink()
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("\ufeff" + "\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")


def write_caps(contract: Contract, cfg: WorldBuilderConfig, mod_root: Path) -> dict[str, dict[str, float]]:
    """Write the cap script values; return per building key {unit_people, unit_units, scale, limit, kind[, family, niche]}."""
    blocks: list[str] = []
    info: dict[str, dict[str, float]] = {}
    shared = families(cfg)
    for row in contract.building_types.iter_rows(named=True):
        kind = str(row["building"])
        key = cfg.building_map.get(kind)
        if key is None:
            raise ValueError(f"[worldbuilder.buildings.map] has no blueprint for World Builder type {kind!r}")
        scale = float(cfg.level_scale.get(key, cfg.level_scale.get(kind, 1.0)))
        equation = json.loads(str(row["cap_equation_json"]))
        limit = int(row.get("level_limit") or cfg.level_limit)
        people = float(row["unit_people_per_level"]) / scale
        info[key] = {"kind": kind, "unit_people": people, "unit_units": units(people), "scale": scale, "limit": int(round(limit * scale))}
        members = shared.get(key, [])
        if not members:
            blocks.append(cap_script_value(contract, key, equation, scale, limit))
            continue
        source = f"pp_wb_cap_{key}_shared"
        blocks.append(cap_script_value(contract, key, equation, scale, limit, name=source))
        blocks.append(shared_cap_value(f"pp_wb_cap_{key}", source, members))
        for niche in members:
            strength = float(cfg.niche[niche]["strength"])
            niche_people = people * strength
            lower = lower_tiers(cfg, niche)
            siblings = [m for m in (key, *members) if m != niche and m not in lower]
            block = shared_cap_value(f"pp_wb_cap_{niche}", source, siblings)
            if cfg.niche[niche].get("maximum_levels"):
                block = block[:-1] + _clamp("max", "MAXIMUM", int(cfg.niche[niche]["maximum_levels"])) + "\n}"
            blocks.append(block)
            info[niche] = {"kind": kind, "unit_people": niche_people, "unit_units": units(niche_people), "scale": scale, "limit": int(round(limit * scale)), "family": key, "strength": strength, "niche": True}
    missing = [n for n, spec in cfg.niche.items() if spec["family"] not in info]
    if missing:
        raise ValueError(f"[worldbuilder.buildings.niche] family is not a mapped general building: {', '.join(missing)}")
    counters = sorted({k for family, members in shared.items() for k in (family, *members)})
    write_level_counters(counters, mod_root)
    text = "\n\n".join([GENERATED, "# Improvement building level caps: base + attribute class terms + levels per development point x development.",
                          "# Families with niche members: <key>_shared is the equation; each member's cap subtracts the other members' levels.", *blocks]) + "\n"
    (mod_root / CAPS_PATH).parent.mkdir(parents=True, exist_ok=True)
    (mod_root / CAPS_PATH).write_text("﻿" + text, encoding="utf-8", newline="\n")
    write_river_size_triggers(mod_root)
    # tooltip rows for the cap values and the farm values
    keys = sorted(set(re.findall(r'desc = "(BUILDING_LEVEL_WB_[A-Z0-9_]+)"', text)))
    loc = ["l_english:", '  BUILDING_LEVEL_WB_BASE: "Base levels"', '  BUILDING_LEVEL_WB_DEVELOPMENT: "From [development|e]"',
           '  BUILDING_LEVEL_WB_FREE_FARMLAND: "Available Subsistence Land"', '  BUILDING_LEVEL_WB_MINIMUM: "Minimum"',
           '  BUILDING_LEVEL_WB_MAXIMUM: "Upper limit"', '  BUILDING_LEVEL_WB_FAMILY: "Capacity shared with related buildings"']
    fixed = ("BUILDING_LEVEL_WB_BASE", "BUILDING_LEVEL_WB_DEVELOPMENT", "BUILDING_LEVEL_WB_FREE_FARMLAND",
             "BUILDING_LEVEL_WB_MINIMUM", "BUILDING_LEVEL_WB_MAXIMUM", "BUILDING_LEVEL_WB_FAMILY")
    for key in keys:
        if key in fixed:
            continue
        rest = key.removeprefix("BUILDING_LEVEL_WB_")
        if rest.startswith("SHARED_"):
            loc.append(f'  {key}: "Levels of ${rest.removeprefix("SHARED_").lower()}$"')
            continue
        attribute, _, value = rest.partition("_")
        if attribute == "SOIL":
            attribute, _, value = rest.partition("_TYPE_")
        if attribute == "RIVER":
            attribute, _, value = rest.partition("_LEVEL_")
        if attribute == "IS":
            attribute, _, value = ("COASTAL", "", "") if "COASTAL" in rest else ("LAKE", "", "")
        label = " ".join(w.capitalize() for w in value.lower().split("_")) if value else ""
        loc.append(f'  {key}: "{(label + " " if label else "") + attribute.capitalize()}"')
    loc_path = mod_root / "main_menu/localization/english/pp_wb_building_caps_l_english.yml"
    loc_path.parent.mkdir(parents=True, exist_ok=True)
    loc_path.write_text("﻿" + "\n".join(loc) + "\n", encoding="utf-8", newline="\n")
    return info


def _raw_modifier_blocks(body: str) -> list[tuple[int, int, str, list[str]]]:
    """(start, end, indent, inner lines) of every raw_modifier block, found by brace matching."""
    blocks = []
    for match in re.finditer(r"^(?P<indent>[ \t]*)raw_modifier\s*=\s*\{", body, re.MULTILINE):
        depth = 0
        i = match.end() - 1
        while i < len(body):
            if body[i] == "{":
                depth += 1
            elif body[i] == "}":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        inner = body[match.end(): i]
        blocks.append((match.start(), i + 1, match.group("indent"), [l.strip() for l in inner.splitlines() if l.strip()]))
    return blocks


def _replace_raw_modifier(body: str, lines: Mapping[str, str], *, drop_prefixes: tuple[str, ...] = ()) -> str:
    """Set lines in the raw_modifier block (merging duplicate blocks), dropping keys with the given prefixes; create it if absent."""
    blocks = _raw_modifier_blocks(body)
    if not blocks:
        indent = re.search(r"^([ \t]*)modifier\s*=\s*\{", body, re.MULTILINE)
        pad = indent.group(1) if indent else "    "
        block = "\n".join([f"{pad}raw_modifier = {{", *[f"{pad}  {k} = {v}" for k, v in lines.items()], f"{pad}}}"])
        anchor = re.search(r"^[ \t]*modifier\s*=\s*\{", body, re.MULTILINE)
        return body[: anchor.start()] + block + "\n\n" + body[anchor.start():] if anchor else body.rstrip("\n") + "\n\n" + block + "\n"
    merged: dict[str, str] = {}
    for _, _, _, inner in blocks:
        for line in inner:
            key, _, value = line.partition("=")
            key, value = key.strip(), value.strip()
            if key and value and key not in lines and not key.startswith(drop_prefixes):
                merged.setdefault(key, value)
    merged.update(lines)
    pad = blocks[0][2]
    new = "\n".join([f"{pad}raw_modifier = {{", *[f"{pad}  {k} = {v}" for k, v in merged.items()], f"{pad}}}"])
    # replace the first block, delete the others (from the end so offsets stay valid)
    for start, end, _, _ in sorted(blocks[1:], key=lambda b: -b[0]):
        body = body[:start].rstrip(" \t") + body[end:].lstrip("\n") if body[end:].startswith("\n\n") else body[:start].rstrip(" \t") + body[end:]
    start, end, _, _ = blocks[0]
    return body[:start] + new + body[end:]


def _set_max_levels(body: str, value: str) -> str:
    match = _MAX_LEVELS_RE.search(body)
    if match is None:
        # no max_levels line yet (vanilla default): add one after the first line of the body
        first = re.match(r"^(?P<indent>[ \t]*)\S", body, re.MULTILINE)
        pad = first.group("indent") if first else "    "
        head, _, tail = body.partition("\n")
        return f"{head}\n{pad}max_levels = {value}\n{tail}"
    return body[: match.start()] + f"{match.group('indent')}max_levels = {value}" + body[match.end():]


def _set_location_potential(body: str, trigger_lines: list[str]) -> str:
    match = _POTENTIAL_RE.search(body)
    pad = match.group("indent") if match else "    "
    block = "\n".join([f"{pad}location_potential = {{", *[f"{pad}  {l}" for l in trigger_lines], f"{pad}}}"])
    if match is None:
        return body.rstrip("\n") + "\n\n" + block + "\n"
    return body[: match.start()] + block + body[match.end():]


def _load_blueprint(repo: Path, key: str) -> tuple[Path, dict]:
    path = repo / BLUEPRINTS / f"{key}.yml"
    if not path.is_file():
        raise FileNotFoundError(f"blueprint missing: {path}")
    return path, yaml_io.safe_load(path.read_text(encoding="utf-8"))


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper: yaml.SafeDumper, data: str):  # block style for multi-line bodies
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def _normalise_body(text: str) -> str:
    """Tabs and trailing spaces keep PyYAML from using a literal block; normalise so bodies stay readable."""
    return "\n".join(line.replace("\t", "  ").rstrip() for line in text.splitlines()) + ("\n" if text.endswith("\n") else "")


def _save_blueprint(path: Path, data: dict) -> None:
    building = data.get("building")
    if isinstance(building, dict) and isinstance(building.get("body"), str):
        building["body"] = _normalise_body(building["body"])
    path.write_text(yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=10_000), encoding="utf-8")


