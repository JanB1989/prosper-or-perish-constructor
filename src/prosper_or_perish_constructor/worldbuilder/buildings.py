def farm_constants(cfg: WorldBuilderConfig, building: str) -> tuple[float, float]:
    """(land per level, reserve) in capacity units for a farm building, by configured class."""
    for cls, members in cfg.farm_classes.items():
        if building in members:
            values = cfg.farm_land[cls]
            return float(values["land"]), float(values["reserve"])
    values = cfg.farm_land["arable"]
    return float(values["land"]), float(values["reserve"])


def patch_farm_blueprints(cfg: WorldBuilderConfig, repo: Path, farm_buildings: list[str]) -> list[str]:
    """Each farm level takes land: raw_modifier local_population_capacity = -land (kept beside its level counter), and
    records it as local_pp_farmland_used = land, which the farm max-level tooltips read as "Used by other farms"
    (scripts/generate_rural_capacity_values.py; one modifier read instead of a sum over every farm type)."""
    patched: list[str] = []
    for key in farm_buildings:
        path = repo / BLUEPRINTS / f"{key}.yml"
        if not path.is_file():
            continue
        land, _ = farm_constants(cfg, key)
        data = yaml_io.safe_load(path.read_text(encoding="utf-8"))
        body = str(data["building"]["body"])
        new = _replace_raw_modifier(body, {"local_population_capacity": _fmt(-land), "local_pp_farmland_used": _fmt(land)})
        if new != body:
            data["building"]["body"] = new
            _save_blueprint(path, data)
            patched.append(key)
    return patched


def cap_levels(equation: Mapping[str, object], attributes: Mapping[str, object], scale: float, limit: int) -> int:
    """The cap as the game evaluates it: scaled base + matching class terms + development term, floored, clamped."""
    cap = float(equation["base_levels"]) * scale
    for term in equation["class_terms"]:
        if str(attributes.get(str(term["attribute"]))) == str(term["value"]):
            cap += float(term["levels"]) * scale
    cap += float(equation["levels_per_development_point"]) * scale * float(attributes.get("development") or 0.0)
    return min(max(int(math.floor(cap + 1e-9)), 0), int(limit))


def gate_matches(rules: list[dict[str, list[str]]], attributes: Mapping[str, object]) -> bool:
    """Evaluate the same OR-of-ANDs gate used in location_potential (CSV booleans are lowercase)."""
    return not rules or any(all(str(attributes.get(key, "")).lower() in {str(v).lower() for v in values}
                               for key, values in rule.items()) for rule in rules)


def write_setup(contract: Contract, cfg: WorldBuilderConfig, caps: Mapping[str, Mapping[str, float]], owners: Mapping[str, str], mod_root: Path,
                demand: Mapping[str, float] | None = None, cultures: Mapping[str, str] | None = None) -> dict[str, int]:
    """Starting improvement levels for owned locations (levels rescaled with the building's scale, never above the cap).

    ``demand`` (people per location the improvements must house so the pops at game start fit their capacity) raises
    the ledger's levels of the location's eligible buildings up to their caps, largest people per level first. The
    pops are evidence for how far the land had been improved by 1337, never for the caps themselves.
    Opted-in regional variants replace their family's levels when their structured gate matches; opaque
    country or advance locks are not guessed. The highest-capacity eligible member receives the family allocation.
    """
    rows: list[tuple[str, str, str, int]] = []
    skipped = 0
    clamped = 0
    gated = 0
    raised = 0
    navigation_exchanged = 0
    filled: set[str] = set()
    short: set[str] = set()
    kinds = {str(v["kind"]): k for k, v in caps.items() if not v.get("niche")}
    equations = {str(r["building"]): json.loads(str(r["cap_equation_json"])) for r in contract.building_types.iter_rows(named=True)}
    gates = {str(r["building"]): json.loads(str(r["gate_json"])) for r in contract.building_types.iter_rows(named=True)}
    for key, spec in cfg.niche.items():
        if spec.get("place_at_start") and (spec.get("lock") or not spec.get("gate")):
            raise ValueError(f"{key}: starting niche placement requires a structured gate and no opaque lock")
    attributes = contract.location_attributes
    if "development" not in attributes.columns and "development" in contract.location_targets.columns:
        attributes = attributes.join(contract.location_targets.select("location_tag", "development"), on="location_tag", how="left")
    by_tag = {str(r["location_tag"]): r for r in attributes.iter_rows(named=True)}
    eligible: dict[str, dict[str, int]] = {}
    has_cap = "cap_at_start" in contract.location_buildings.columns
    for row in contract.location_buildings.iter_rows(named=True):
        if has_cap and row["cap_at_start"] is None:
            continue
        eligible.setdefault(str(row["location_tag"]), {})[str(row["building"])] = int(row["starting_levels"] or 0)
    for tag in sorted(eligible):
        owner = owners.get(tag, "")
        if not owner:
            skipped += sum(1 for v in eligible[tag].values() if v > 0)
            continue
        levels: dict[str, tuple[int, int]] = {}
        for kind, start in eligible[tag].items():
            key = kinds.get(kind)
            if key is None:
                continue
            scale = float(caps[key]["scale"])
            limit = int(caps[key]["limit"])
            level = min(int(math.floor(start * scale + 1e-9)), limit)
            cap = cap_levels(equations[kind], by_tag.get(tag, {}), scale, limit) if tag in by_tag else level
            if level > cap:
                clamped += 1
                level = cap
            attrs = {**by_tag.get(tag, {}), "culture": (cultures or {}).get(tag, "")}
            if not gate_matches(gates[kind], attrs):
                # the game rejects a setup building whose location_potential fails ("has an invalid building")
                gated += 1
                continue
            candidates = [key] + [n for n, spec in cfg.niche.items()
                                  if spec["family"] == key and spec.get("place_at_start")
                                  and gate_matches(spec.get("gate", []), attrs) and gate_matches(gates[kind], attrs)]
            # A niche replaces the general family's starting levels; it never adds another full cap.
            selected = max(candidates, key=lambda k: float(caps[k]["unit_units"]))
            levels[selected] = (level, cap)
        need = float(demand.get(tag, 0.0)) if demand else 0.0
        need -= sum(level * float(caps[key]["unit_people"]) for key, (level, _) in levels.items())
        while need > 0:
            room = [key for key, (level, cap) in levels.items() if level < cap]
            if not room:
                short.add(tag)
                break
            key = max(room, key=lambda k: float(caps[k]["unit_units"]))
            level, cap = levels[key]
            levels[key] = (level + 1, cap)
            need -= float(caps[key]["unit_people"])
            raised += 1
            filled.add(tag)
        for key, (level, _) in levels.items():
            if level > 0:
                rows.append((key, tag, owner, level))
    # documented starting navigations: one River Navigation Canal at the bank (no capacity, outside the families)
    from .navigation import exchange_levels
    for tag, site in sorted(cfg.raw.get("_navigation", {}).get("sites", {}).items()):
        owner = owners.get(tag, "")
        canal: dict[str, tuple[int, int]] = {}
        if owner and exchange_levels(canal, site):
            navigation_exchanged += 1
            rows.extend((key, tag, owner, level) for key, (level, _) in canal.items())
    rows.sort()
    lines = [f"\t{key} = {{ tag = {owner} level = {level} location = {tag} }}" for key, tag, owner, level in rows]
    text = "\n".join([GENERATED, "building_manager = {", *lines, "}", ""])
    (mod_root / SETUP_PATH).parent.mkdir(parents=True, exist_ok=True)
    (mod_root / SETUP_PATH).write_text("\ufeff" + text, encoding="utf-8", newline="\n")
    for rel in LEGACY_SETUP:
        if (mod_root / rel).is_file():
            (mod_root / rel).unlink()
    return {"rows": len(rows), "navigation_levels_exchanged": navigation_exchanged, "unowned_skipped": skipped, "clamped_to_cap": clamped, "gate_rejected": gated, "levels_raised_for_pops": raised,
            "locations_filled_for_pops": len(filled), "locations_still_short": len(short)}


def vanilla_capacity_buildings(vanilla_root: Path) -> dict[str, str]:
    """Vanilla building keys whose definition carries a population capacity line (flat or percent) -> file name."""
    found: dict[str, str] = {}
    folder = Path(vanilla_root) / "game/in_game/common/building_types"
    for path in sorted(folder.glob("*.txt")):
        text = path.read_text(encoding="utf-8-sig", errors="replace")
        starts = list(_VANILLA_BUILDING_RE.finditer(text))
        for index, match in enumerate(starts):
            end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
            if _CAPACITY_LINE_RE.search(text[match.start(): end]):
                found[match.group("key")] = path.name
    return found


def vanilla_capacity_leaks(repo: Path, vanilla_root: Path) -> dict[str, str]:
    """Vanilla capacity buildings the mod does not fully REPLACE (their vanilla capacity would leak into the flat)."""
    manifest = yaml_io.safe_load((repo / MANIFEST).read_text(encoding="utf-8")) or {}
    enabled = manifest.get("enabled", {}) if isinstance(manifest, dict) else {}
    leaks: dict[str, str] = {}
    for key, source in vanilla_capacity_buildings(vanilla_root).items():
        path = repo / BLUEPRINTS / f"{key}.yml"
        if not path.is_file():
            leaks[key] = f"no blueprint ({source})"
            continue
        if not enabled.get(f"buildings/{key}.yml", False):
            leaks[key] = f"blueprint disabled in manifest ({source})"
            continue
        data = yaml_io.safe_load(path.read_text(encoding="utf-8-sig")) or {}
        mode = str((data.get("building") or {}).get("mode", "")).upper()
        if mode != "REPLACE":
            leaks[key] = f"blueprint mode {mode or 'unset'} keeps the vanilla capacity ({source})"
    return leaks
