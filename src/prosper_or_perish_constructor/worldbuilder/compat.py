"""Widen vanilla attribute tests to the World Builder's new classes.

The World Builder adds climate, vegetation and topography classes as children of vanilla classes (the
``families`` map in the export's ``geography_compatibility.json``: e.g. ``forest`` -> coniferous forest, mixed
forest, swamp). Vanilla scripts that test ``vegetation = forest`` would silently exclude those locations, so the
configured vanilla files (``[worldbuilder.compat] vanilla_files``) are copied into the mod with every test of a
parent class widened to ``OR = { attribute = parent attribute = child ... }``. Nothing else in the copies changes,
and the copies are regenerated from the current vanilla files on every ``ppc worldbuilder apply``.

The same expansion is applied once, in place, to the mod's own hand-authored scripts and blueprints.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Mapping
from pathlib import Path

ATTRIBUTES = ("climate", "vegetation", "topography")
COMPAT_JSON = "geography_compatibility.json"
MANIFEST_RELATIVE_PATH = Path("artifacts/data/worldbuilder/compat_patches.json")
HEADER = "# Generated by ppc worldbuilder: vanilla file with every climate/vegetation/topography test widened to the World Builder classes; do not edit by hand."
_TEST_RE = re.compile(r"\b(?P<attr>climate|vegetation|topography)\s*=\s*(?P<value>[a-z_0-9]+)\b")

Families = Mapping[str, Mapping[str, list[str]]]


def load_families(export_dir: Path) -> dict[str, dict[str, list[str]]]:
    data = json.loads((Path(export_dir) / COMPAT_JSON).read_text(encoding="utf-8-sig"))
    families = data.get("families")
    if not isinstance(families, dict):
        raise ValueError(f"{Path(export_dir) / COMPAT_JSON}: missing families map")
    return {str(attr): {str(parent): [str(c) for c in children] for parent, children in parents.items()} for attr, parents in families.items()}


def expand_attribute_tests(text: str, families: Families) -> tuple[str, int]:
    """Widen every ``attribute = parent`` test whose parent has children; returns (text, tests widened).

    Idempotent: a test already followed on its line by the first child is left alone. Comments are not touched.
    """
    out_lines: list[str] = []
    widened = 0
    for line in text.splitlines(keepends=True):
        code, sep, comment = line.partition("#")

        def replace(match: re.Match[str]) -> str:
            nonlocal widened
            attr, value = match.group("attr"), match.group("value")
            children = families.get(attr, {}).get(value)
            if not children:
                return match.group(0)
            rest = code[match.end():]
            if re.search(rf"\b{attr}\s*=\s*{re.escape(children[0])}\b", rest) or re.search(rf"\b{attr}\s*=\s*{re.escape(children[0])}\b", code[: match.start()]):
                return match.group(0)
            widened += 1
            return "OR = { " + " ".join(f"{attr} = {v}" for v in (value, *children)) + " }"

        out_lines.append(_TEST_RE.sub(replace, code) + sep + comment)
    return "".join(out_lines), widened


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


_OBJECT_KEY_RE = re.compile(r"([A-Za-z0-9_.:\-]+)\s*=\s*\Z")


def top_level_objects(text: str) -> list[tuple[str, int, int]]:
    """``(name, start, end)`` of every top-level ``name = { ... }`` block; comments and quoted strings are skipped."""
    out: list[tuple[str, int, int]] = []
    depth = 0
    i = 0
    start = -1
    name = ""
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == "#":
            nl = text.find("\n", i)
            i = n if nl < 0 else nl
            continue
        if ch == '"':
            close = text.find('"', i + 1)
            i = n if close < 0 else close + 1
            continue
        if ch == "{":
            if depth == 0:
                window = max(0, i - 200)
                match = _OBJECT_KEY_RE.search(text, window, i)
                name, start = (match.group(1), match.start(1)) if match else ("", i)
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and name:
                out.append((name, start, i + 1))
                name = ""
        i += 1
    return out


_OVERRIDE_RE = re.compile(r"(?m)^(?P<kind>REPLACE|TRY_REPLACE|REPLACE_OR_CREATE|INJECT|TRY_INJECT|INJECT_OR_CREATE):(?P<name>[A-Za-z0-9_.\-]+)\s*=")
_REPLACE_KINDS = frozenset({"REPLACE", "TRY_REPLACE", "REPLACE_OR_CREATE"})


def mod_overrides(folder: Path, exclude: str) -> dict[str, list[tuple[str, str]]]:
    """Object name -> ``(kind, file name)`` of every top-level ``REPLACE:``/``INJECT:`` in the mod's files of ``folder``."""
    out: dict[str, list[tuple[str, str]]] = {}
    if not folder.is_dir():
        return out
    for path in sorted(folder.glob("*.txt")):
        if path.name == exclude:
            continue
        for match in _OVERRIDE_RE.finditer(path.read_text(encoding="utf-8-sig", errors="replace")):
            out.setdefault(match["name"], []).append((match["kind"], path.name))
    return out


def _is_generated_copy(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8-sig") as handle:
            return handle.readline().rstrip("\n") == HEADER
    except (OSError, UnicodeDecodeError):
        return False


def remove_objects(text: str, names: list[str], rel: str) -> str:
    """``text`` without the named top-level objects; fails when one is missing (vanilla changed, review the removal)."""
    spans = {name: (a, b) for name, a, b in top_level_objects(text)}
    missing = [name for name in names if name not in spans]
    if missing:
        raise ValueError(f"[worldbuilder.compat] {rel}: objects to remove not found: {', '.join(missing)}; vanilla changed, review removed_objects")
    for a, b in sorted((spans[name] for name in names), reverse=True):
        text = text[:a] + text[b:]
    return text


def replace_exact(text: str, replacements: list[tuple[str, str, int]], rel: str) -> str:
    """Exact text replacements; each must occur exactly its configured number of times."""
    for find, new, count in replacements:
        found = text.count(find)
        if found != count:
            raise ValueError(f"[worldbuilder.compat] {rel}: expected {count} occurrence(s) of {find!r}, found {found}; vanilla changed, review the replacement")
        text = text.replace(find, new)
    return text


def removed_vanilla_buildings(repo: Path) -> set[str]:
    """Vanilla building types the mod deletes (``[worldbuilder.compat] removed_objects`` of building_types files)."""
    import tomllib

    compat = tomllib.loads((Path(repo) / "constructor.toml").read_text(encoding="utf-8")).get("worldbuilder", {}).get("compat", {})
    return {str(name) for rel, names in (compat.get("removed_objects") or {}).items() if "/building_types/" in rel for name in names}


def write_compat_patches(vanilla_root: Path, mod_root: Path, repo: Path, families: Families, relative_files: list[str],
                         removed: Mapping[str, list[str]] | None = None,
                         replacements: Mapping[str, list[tuple[str, str, int]]] | None = None) -> dict[str, object]:
    """Copy the configured vanilla files into the mod with widened tests; drop copies no longer produced.

    A copy is a whole-file override and becomes a mod file, so it must not undo the mod's own overrides:
    - tests inside objects the mod ``REPLACE``s elsewhere do not count (the replacement wins and carries its own
      widened tests); a file whose only widened tests are in such objects is not copied (EU5 1.4: unique_buildings.txt,
      where only the Maghreb palm irrigation is widened and its blueprint is a REPLACE);
    - a copy is refused when the mod overrides one of its objects in a file that sorts before it in the same
      folder: the copy's plain definition would load after that override and replace it.

    ``removed`` (``[worldbuilder.compat] removed_objects``) deletes vanilla objects: they are left out of the file's
    copy, which is then always written (without it the vanilla definition would come back). ``replacements``
    (``[[worldbuilder.compat.replacements]]``) rewrite the vanilla references to them; a file listed only there is
    copied with the replacements and no widening.
    """
    removed = dict(removed or {})
    replacements = dict(replacements or {})
    manifest_path = repo / MANIFEST_RELATIVE_PATH
    previous = json.loads(manifest_path.read_text(encoding="utf-8")).get("files", {}) if manifest_path.is_file() else {}
    files: dict[str, dict[str, object]] = {}
    unchanged: list[str] = []
    for rel in dict.fromkeys([*relative_files, *removed, *replacements]):
        source = Path(vanilla_root) / "game" / rel
        if not source.is_file():
            raise FileNotFoundError(f"[worldbuilder.compat] vanilla file not found: {source}")
        vanilla_text = source.read_text(encoding="utf-8-sig")
        original = replace_exact(remove_objects(vanilla_text, removed.get(rel, []), rel), replacements.get(rel, []), rel)
        if rel in relative_files:
            expanded, widened = expand_attribute_tests(original, families)
        else:
            expanded, widened = original, 0
        target = mod_root / rel
        overrides = mod_overrides(target.parent, target.name)
        objects = top_level_objects(original)
        replaced = {name for name, uses in overrides.items() if any(kind in _REPLACE_KINDS for kind, _ in uses)}
        if rel in relative_files:
            widened -= sum(expand_attribute_tests(original[a:b], families)[1] for name, a, b in objects if name in replaced)
        if widened == 0 and rel not in removed and rel not in replacements:
            unchanged.append(rel)
            if target.is_file() and (rel in previous or _is_generated_copy(target)):
                target.unlink()
            continue
        clobbered = sorted(f"{name} ({kind} in {file})" for name, _, _ in objects for kind, file in overrides.get(name, ()) if file < target.name)
        if clobbered:
            raise ValueError(f"[worldbuilder.compat] {rel}: the copy would load after and undo the mod's overrides of "
                             + ", ".join(clobbered) + "; move them to a file that sorts after it (zz_pp_*) or drop the file from the list")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("﻿" + HEADER + "\n" + expanded, encoding="utf-8", newline="\n")
        files[rel] = {"vanilla_sha256": _sha(vanilla_text), "tests_widened": widened}
        if rel in removed:
            files[rel]["removed_objects"] = list(removed[rel])
        if rel in replacements:
            files[rel]["replacements"] = len(replacements[rel])
    for rel in previous:
        if rel not in files and (mod_root / rel).is_file():
            (mod_root / rel).unlink()
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps({"files": files, "unchanged": unchanged}, indent=2) + "\n", encoding="utf-8")
    return {"files": len(files), "tests_widened": sum(int(v["tests_widened"]) for v in files.values()), "unchanged": unchanged}


def expand_file_in_place(path: Path, families: Families) -> int:
    """Widen the tests of one of the mod's own scripts; returns the number of tests widened."""
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    text = raw.decode("utf-8-sig")
    expanded, widened = expand_attribute_tests(text, families)
    if widened:
        path.write_bytes(("﻿" if bom else "").encode("utf-8") + expanded.encode("utf-8"))
    return widened
