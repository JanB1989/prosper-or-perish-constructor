"""Vanilla game-start development per location.

EU5 ships development as ~300 additive rules (``main_menu/setup/1337/14_development.txt``: base,
region/area/province/location, rank, climate/topography/vegetation, coast x harbour, river x size,
road). The mod replaces climate/vegetation/topography classes with the World Builder geography, which
would silently change what those rules add up to, so the constructor evaluates the vanilla rules once
against the vanilla location table and writes explicit per-location values. The same table is exported
for the World Builder, which uses it as its development input.

The rule evaluation is an approximation: on EU5 1.4 it matched the engine for 48 % of the owned locations (river
locations never; the engine's river term is not 0.5 x the parser's river size). The engine's own values come from a
vanilla game-start save (``config/start_development.csv``, owned locations) and replace the evaluation wherever
they exist; the engine takes setup development as written (1.3.11 PP start saves: 12,848 of 12,853 exact).
"""

from __future__ import annotations

import csv
from pathlib import Path

import polars as pl

from prosper_or_perish_constructor.location_baseline import load_vanilla_location_frame
from prosper_or_perish_constructor.setup_layout import SETUP_DIR

GENERATED_MARKER = "# Generated by ppc worldbuilder from the vanilla development rules; do not edit by hand."
SETUP_RELATIVE_PATH = SETUP_DIR / "14_development.txt"
EXPORT_RELATIVE_PATH = Path("artifacts/data/worldbuilder/vanilla_start_development.csv")
# location_tag, development of the owned locations in a vanilla game-start save (refresh from a new start save after a
# patch, like config/start_province_capitals.txt)
START_DEVELOPMENT_RELATIVE_PATH = Path("config/start_development.csv")


def compute_vanilla_development(repo: Path, project: Path) -> pl.DataFrame:
    """location_tag, development: the vanilla start save's value, else the vanilla rules evaluated on vanilla attributes."""
    from eu5gameparser.load_order import LoadOrderConfig

    from prosper_or_perish_constructor.free_building_levels import build_game_start_location_frame, resolve_parser_config

    parser_config = resolve_parser_config(repo, project)
    load_order_path = repo / str(parser_config.get("load_order") or "constructor.load_order.toml")
    # Vanilla layer only: the mod itself writes 14_development.txt and setup corrections, which must not feed back.
    profile = LoadOrderConfig.load(load_order_path).profile(str(parser_config.get("vanilla_profile") or "vanilla"))
    base = load_vanilla_location_frame(repo, project, profile=str(parser_config.get("profile") or "constructor"))
    enriched = build_game_start_location_frame(base, profile=profile)
    evaluated = enriched.select(
        pl.col("location_tag").cast(pl.String),
        pl.col("development").cast(pl.Float64).fill_null(0.0).clip(0.0, None).round(3).alias("development"),
    )
    return with_start_save_development(evaluated, load_start_development(repo)).unique("location_tag").sort("location_tag")


def load_start_development(repo: Path) -> pl.DataFrame | None:
    path = repo / START_DEVELOPMENT_RELATIVE_PATH
    if not path.is_file():
        return None
    return pl.read_csv(path, comment_prefix="#", schema={"location_tag": pl.String, "development": pl.Float64})


def with_start_save_development(evaluated: pl.DataFrame, observed: pl.DataFrame | None) -> pl.DataFrame:
    """The engine's game-start development where the start save has it, the rule evaluation elsewhere."""
    if observed is None:
        return evaluated
    return (
        evaluated.join(observed.rename({"development": "observed"}), on="location_tag", how="left")
        .with_columns(pl.coalesce("observed", "development").clip(0.0, None).round(3).alias("development"))
        .drop("observed")
    )


def render_development_setup(frame: pl.DataFrame) -> str:
    lines = [GENERATED_MARKER, "development = {", "\tbase = 0"]
    for tag, value in frame.select("location_tag", "development").iter_rows():
        lines.append(f"\t{tag} = {value:.3f}")
    lines.extend(("}", ""))
    return "\n".join(lines)


def write_development_export(frame: pl.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["location_tag", "development"])
        for tag, value in frame.select("location_tag", "development").iter_rows():
            writer.writerow([tag, f"{value:.3f}"])
