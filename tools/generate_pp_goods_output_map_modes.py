from eu5gameparser.domain.eu5 import load_eu5_data


ROOT = Path(__file__).resolve().parents[1]
PROJECT_CONFIG = ROOT / "constructor.toml"

MAP_MODE_REL = Path("in_game/gfx/map/map_modes/pp_goods_output_map_modes_generated.txt")
SCRIPT_VALUES_REL = Path("in_game/common/script_values/pp_goods_output_map_modes_generated.txt")
LOCALIZATION_REL = Path("main_menu/localization/english/pp_goods_output_map_modes_l_english.yml")
IN_GAME_ICON_REL = Path("in_game/gfx/interface/icons/map_modes")
TRADE_GOOD_ICON_REL = Path("main_menu/gfx/interface/icons/trade_goods")
GOODS_OUTPUT_BUCKETS = (
    ("RANGE_0_10", 0, 10, "define:NMapColors|MAP_COLOR_MIN", "define:NMapColors|MAP_COLOR_LOW"),
    ("RANGE_10_30", 10, 30, "define:NMapColors|MAP_COLOR_LOW", "define:NMapColors|MAP_COLOR_MID"),
    ("RANGE_30_60", 30, 60, "define:NMapColors|MAP_COLOR_MID", "define:NMapColors|MAP_COLOR_HIGH"),
    ("RANGE_60_100", 60, 100, "define:NMapColors|MAP_COLOR_HIGH", "define:NMapColors|MAP_COLOR_MAX"),
    ("RANGE_100_150", 100, 150, "define:NMapColors|MAP_COLOR_MAX", "define:NMapColors|MAP_COLOR_TOP"),
    ("RANGE_150_300", 150, 300, "define:NMapColors|MAP_COLOR_TOP", "rgb { 245 245 245 }"),
)
GOODS_OUTPUT_CAP_COLOR = "rgb { 245 245 245 }"
GOODS_OUTPUT_OVERFLOW_COLOR = "rgb { 70 210 255 }"


def main() -> None:
    project = _load_project_config(PROJECT_CONFIG)
    mod_root = _project_path(project["project"]["mod_root"])
    goods = sorted(_all_goods(project))

    _write_crlf(mod_root / MAP_MODE_REL, _map_modes_file(goods))
    _write_crlf(mod_root / SCRIPT_VALUES_REL, _script_values_file(goods))
    _write_crlf(mod_root / LOCALIZATION_REL, _localization_file(goods))
    _ensure_icons(mod_root, goods, project)
    print(f"Generated goods output map modes for {len(goods)} goods.")


def _load_project_config(path: Path) -> dict:
    with path.open("rb") as stream:
        return tomllib.load(stream)


def _project_path(raw: str) -> Path:
    path = _host_path(Path(raw))
    return path if path.is_absolute() else (ROOT / path).resolve()


def _host_path(path: Path) -> Path:
    path_text = str(path)
    match = re.match(r"^([A-Za-z]):[\\/](.*)$", path_text)
    if match is None or os.name == "nt":
        return path
    drive = match.group(1).lower()
    tail = match.group(2).replace("\\", "/")
    return Path("/mnt") / drive / tail


def _all_goods(project: dict) -> list[str]:
    parser = project.get("parser", {})
    profile = str(parser.get("profile") or "constructor")
    load_order = _project_path(str(parser.get("load_order") or "constructor.load_order.toml"))
    data = load_eu5_data(profile=profile, load_order_path=load_order)
    return data.goods.select("name").to_series().to_list()


def _vanilla_root(project: dict) -> Path:
    parser = project.get("parser", {})
    load_order = _project_path(str(parser.get("load_order") or "constructor.load_order.toml"))
    with load_order.open("rb") as stream:
        raw = tomllib.load(stream)
    paths = raw.get("paths", {})
    vanilla_root = _project_path(str(paths.get("vanilla_root", "")))
    if not vanilla_root.is_absolute():
        vanilla_root = (load_order.parent / vanilla_root).resolve()
    return vanilla_root


def _map_modes_file(goods: Iterable[str]) -> str:
    goods_list = list(goods)
    blocks = [
        "# Generated by tools/generate_pp_goods_output_map_modes.py - do not edit by hand.",
        "# Fixed bucket heatmap: raw = local output x market_access; colors lerp inside each configured range.",
        "# Locations with zero local output of the good get no overlay (terrain); sea/unowned stay grey.",
        "",
        "@zoom_step_near = 2",
        "@data_gradient_alpha_inside = 1",
        "@data_gradient_alpha_outside = 1",
        "@data_gradient_width = 0.25",
        "@data_gradient_color_mult = 0.9",
        "@data_edge_width = 0",
        "@data_edge_sharpness = 0.01",
        "@data_edge_alpha = 0",
        "@data_edge_color_mult = 0",
        "@data_before_lighting_blend = 0.5",
        "@data_after_lighting_blend = 0.5",
        "",
    ]
    for good in goods_list:
        blocks.append(_map_mode_block(good))
    return "\n".join(blocks).rstrip() + "\n"


