def _goods_output_color_cases(good: str) -> str:
    value_name = f"pp_{good}_output_raw"
    cases: list[str] = []
    for index, (_suffix, lower, upper, min_color, max_color) in enumerate(GOODS_OUTPUT_BUCKETS):
        keyword = "if" if index == 0 else "else_if"
        factor_lines = [f"\t\t\t\t\tvalue = {value_name}"]
        if lower:
            factor_lines.append(f"\t\t\t\t\tsubtract = {lower}")
        factor_lines.extend(
            [
                f"\t\t\t\t\tdivide = {upper - lower}",
                "\t\t\t\t\tmax = 1",
                "\t\t\t\t\tmin = 0",
            ]
        )
        cases.append(
            f"""\t\t{keyword} = {{
\t\t\tlimit = {{
\t\t\t\thas_owner = yes
\t\t\t\t"goods_output(goods:{good})" > 0
\t\t\t\t{value_name} < {upper}
\t\t\t}}
\t\t\tlerp = {{
\t\t\t\tmin_color = {min_color}
\t\t\t\tmax_color = {max_color}
\t\t\t\tfactor = {{
{chr(10).join(factor_lines)}
\t\t\t\t}}
\t\t\t}}
\t\t}}"""
        )
    cases.append(
        f"""\t\telse_if = {{
\t\t\tlimit = {{
\t\t\t\thas_owner = yes
\t\t\t\t"goods_output(goods:{good})" > 0
\t\t\t}}
\t\t\tvalue = {GOODS_OUTPUT_OVERFLOW_COLOR}
\t\t}}"""
    )
    return "\n".join(cases)


def _goods_output_legend_keys(prefix: str) -> str:
    lines = []
    for suffix, _lower, _upper, color, _max_color in GOODS_OUTPUT_BUCKETS:
        lines.extend(
            [
                "\tlegend_key = {",
                f'\t\tdesc = "{prefix}_{suffix}"',
                f"\t\tcolor = {color}",
                "\t}",
            ]
        )
    lines.extend(
        [
            "\tlegend_key = {",
            f'\t\tdesc = "{prefix}_CAPPED"',
            f"\t\tcolor = {GOODS_OUTPUT_OVERFLOW_COLOR}",
            "\t}",
        ]
    )
    return "\n".join(lines)


def _script_values_file(goods: Iterable[str]) -> str:
    blocks = [
        "# Generated by tools/generate_pp_goods_output_map_modes.py - do not edit by hand.",
        "# Local monthly goods output x location market_access (cf. Location.GetMarketAccess).",
        "",
    ]
    for good in goods:
        blocks.append(_script_value_block(good))
    return "\n".join(blocks).rstrip() + "\n"


def _script_value_block(good: str) -> str:
    return f"""pp_{good}_output_raw = {{
\tvalue = "goods_output(goods:{good})"
\tmultiply = market_access
}}
"""


def _localization_file(goods: Iterable[str]) -> str:
    lines = [
        "l_english:",
        "  # Generated by tools/generate_pp_goods_output_map_modes.py - do not edit by hand.",
    ]
    for good in goods:
        upper = good.upper()
        lines.extend(
            [
                f'  mapmode_pp_{good}_output_name: "[ShowGoodsName(\'{good}\')|e] Output (x Market Access)"',
                f'  MAPMODE_PP_{upper}_OUTPUT: "{_legend_text(good)}"',
                f'  MAPMODE_PP_{upper}_OUTPUT_RANGE_0_10: "0-10 output"',
                f'  MAPMODE_PP_{upper}_OUTPUT_RANGE_10_30: "10-30 output"',
                f'  MAPMODE_PP_{upper}_OUTPUT_RANGE_30_60: "30-60 output"',
                f'  MAPMODE_PP_{upper}_OUTPUT_RANGE_60_100: "60-100 output"',
                f'  MAPMODE_PP_{upper}_OUTPUT_RANGE_100_150: "100-150 output"',
                f'  MAPMODE_PP_{upper}_OUTPUT_RANGE_150_300: "150-300 output"',
                f'  MAPMODE_PP_{upper}_OUTPUT_CAPPED: "300+ output"',
                f'  MAPMODE_PP_{upper}_OUTPUT_TT_LAND: "{_land_tooltip_text(good)}"',
                f'  MAPMODE_PP_{upper}_OUTPUT_TT_WATER: "$MAPMODE_PP_LOCAL_OUTPUT_TT_WATER$"',
            ]
        )
    return "\n".join(lines) + "\n"


def _legend_text(good: str) -> str:
    base = (
        f"#T $mapmode_pp_{good}_output_name$#!\\n"
        f"Colors [locations|e] by local [ShowGoodsName('{good}')|e] [output|e] x "
        "[market_access|e] using fixed buckets: 0-10, 10-30, 30-60, 60-100, 100-150, 150-300, and 300+. Colors blend inside each bounded bucket; zero-output locations are left without overlay."
    )
    if good == "marble":
        base += (
            " Marble comes from dedicated [ShowBuildingTypeName('marble_quarry')|e] and "
            "[ShowBuildingTypeName('marble_saw_yard')|e] production."
        )
    return base


def _land_tooltip_text(good: str) -> str:
    base = (
        f"#T $mapmode_pp_{good}_output_name$#!\\n"
        f"[ROOT.GetLocation.GetName]: [ROOT.GetLocation.MakeScope.ScriptValue('pp_{good}_output_raw')|2] = "
        f"[ShowGoodsName('{good}')|e] [output|e] x [market_access|e] (per month).\\n"
        "[market_access|e]: [ROOT.GetLocation.GetMarketAccess|2%V]."
    )
    if good == "marble":
        base += (
            "\\n#italic Marble is produced by dedicated [ShowBuildingTypeName('marble_quarry')|e] "
            "and [ShowBuildingTypeName('marble_saw_yard')|e] buildings.#!"
        )
    return base


def _ensure_icons(mod_root: Path, goods: Iterable[str], project: dict) -> None:
    vanilla_root = _vanilla_root(project)
    target = mod_root / IN_GAME_ICON_REL
    target.mkdir(parents=True, exist_ok=True)

    missing: list[str] = []
    for good in goods:
        destination = target / f"pp_{good}_output.dds"
        if destination.exists():
            continue
        source = vanilla_root / "game" / TRADE_GOOD_ICON_REL / f"icon_goods_{good}.dds"
        if source.is_file():
            shutil.copy2(source, destination)
        else:
            missing.append(good)

    if missing:
        raise FileNotFoundError("Missing icon source for goods: " + ", ".join(missing))


def _write_crlf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="\r\n") as stream:
        stream.write(text)


if __name__ == "__main__":
    main()
